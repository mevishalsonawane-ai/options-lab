"""R55 tables (results/report.md) from results/design.json and results/final.json.

    python3 research/hunt/r55/r55report.py
"""
from __future__ import annotations

import json

import r55cfg as K
from r54report import inr, share

EXIT_NAME = {"T0": "T0 trail from fill", "T2": "T2 armed at 2x", "T3": "T3 armed at 3x", "T5": "T5 armed at 5x",
             "H": "H hold"}
END_NAME = {"1505": "15:05", "1515": "15:15", "SETTLE": "settlement"}
HEAD = ("| entry | end | exit | tickets | hit | 2x / 5x / 10x | net | per Rs 1,000 | worst day | max DD | "
        "top-1 / top-5 | net without top 5 | ITM / OTM at settle | 2x spread | p | q |")


def hhmm(s: str) -> str:
    return f"{s[:2]}:{s[2:]}"


def cell_row(c: dict) -> str:
    m = c["m"]
    st = f"{m['itm']} / {m['otm']}" if c["end"] == "SETTLE" else "-"
    return (f"| {hhmm(c['entry'])} | {END_NAME[c['end']]} | {EXIT_NAME[c['exit']]} | {m['tickets']} | {m['hit']:.0f}% | "
            f"{m['x2']} / {m['x5']} / {m['x10']} | {inr(m['net'])} | {inr(m['per1000'])} | {inr(m['worst_day'])} | "
            f"{m['max_dd']:,.0f} | {share(m['top1'])} / {share(m['top5'])} | {inr(m['ex5'])} | {st} | "
            f"{inr(c['spread2x'])} | {c['p']:.3f} | {c['q']:.2f} |")


def order(k: str):
    e, z, x = k.split("-")
    return (K.ENTRIES.index(e), K.ENDS.index(z), K.EXITS.index(x))


def table(res: dict) -> str:
    out = [HEAD, "|" + "---|" * 16]
    for k in sorted(res["cells"], key=order):
        out.append(cell_row(res["cells"][k]))
    return "\n".join(out)


def compare(des: dict, fin: dict) -> str:
    out = ["| comparison (per index-expiry-day) | design mean [95% CI] | final mean [95% CI] | reading |", "|---|---|---|---|"]
    for k, d in des["compare"].items():
        f = fin["compare"][k]
        out.append(f"| {k.replace(' | ', ', ')} | {inr(d['mean'])} [{inr(d['lo'])}, {inr(d['hi'])}] | {inr(f['mean'])} "
                   f"[{inr(f['lo'])}, {inr(f['hi'])}] | {f['reading']} |")
    return "\n".join(out)


def row_time(r) -> str:
    if r is None:
        return "-"
    hh, mm = divmod(int(r) + 9 * 60 + 15, 60)
    return f"{hh:02d}:{mm:02d}"


def callouts(fin: dict) -> str:
    out = ["| cell | day | leg | strike | fill | armed (bar start) | exit (bar start) | exit price (why) | peak | net |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(fin["cells"], key=order):
        for c in fin["cells"][k]["callouts"]:
            why = c["why"] + (f" at {c['settle_px']:,.2f}" if c["why"] == "settle" else "")
            out.append(f"| {k} | {c['und']} {c['d']} | {c['side']} | {c['strike']:,.0f} | {c['entry']:.2f} | "
                       f"{row_time(c['armed_row'])} | {row_time(c['exit_row']) if c['why'] != 'settle' else '15:30'} | "
                       f"{c['exit']:.2f} ({why}) | {c['peak']}x | {inr(c['net'])} |")
    return "\n".join(out)


def gates(fin: dict) -> str:
    out = ["| cell | final net > 0 | p < 0.05 | q <= 0.10 | 40+ tickets | without top 5 > 0 | design net > 0 | pass |",
           "|---|---|---|---|---|---|---|---|"]
    yn = {True: "yes", False: "no"}
    for k in sorted(fin["cells"], key=order):
        g = fin["cells"][k]["gates"]
        out.append(f"| {k} | " + " | ".join(yn[g[x]] for x in ("net>0", "p<0.05", "q<=0.10", "40+ tickets",
                                                               "net without top 5 > 0", "design net > 0", "pass")) + " |")
    return "\n".join(out)


def main():
    des = json.loads((K.RESULTS / "design.json").read_text())
    fin = json.loads((K.RESULTS / "final.json").read_text())
    md = ["# R55 tables (generated by r55report.py)", "",
          f"Design: {des['n_days']} index-expiry-days {des['by_index']}. Final test: {fin['n_days']} {fin['by_index']}.",
          f"Best trail start at 12:30 on DESIGN, per end time: {des['best_trail_design']}.",
          f"Days whose settlement fell back to the last close (fewer than 20 bars 15:00-15:29): design "
          f"{des['settle_flagged_days'] or 'none'}, final {fin['settle_flagged_days'] or 'none'}.", "",
          "## Design (20 Nov 2024 - 31 Mar 2026)", "", table(des), "",
          "## Final test (1 Apr - 13 Oct 2026, read once)", "", table(fin), "",
          "## Paired comparisons", "", compare(des, fin), "",
          "## Called-out days (final test): SENSEX 2 Apr 2026 and NIFTY 13 Oct 2026", "", callouts(fin), "",
          "## Paper gate (final test)", "", gates(fin), ""]
    (K.RESULTS / "report.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
