"""R123 study (PREREG.md): V1 (k = 1.0) and V2 (k = 1.5) on 2021-26 expiry days.

    python3 research/hunt/r123_straddle_index_stop/r123study.py run      # -> results/results.json, results/report.md
"""
from __future__ import annotations

import json
import pickle
import sys
from multiprocessing import Pool

import numpy as np

import r123cfg as K
import r123lib as L
import r119lib as L19
import r119study as S19
import r98data as R
import r54lib as LB
import r117lib as L117


def _job(und):
    LB.load_late()
    out = {t: dict(tr=[], tr2=[], tw=[]) for t in K.TESTS}
    for day in R.load(und):
        per = K.period(day.day)
        if per is None:
            continue
        c = L19.DayCtx(day)
        for t, k in K.TESTS.items():
            a = L.straddle(c, K.ROW_DEC, k)
            if a is None:
                continue
            out[t]["tr"].append(a)
            b = L.straddle(c, K.ROW_DEC, k, mult=2.0)
            if b is not None:
                out[t]["tr2"].append(b)
            if per == "final":
                out[t]["tw"].append([x.net for x in (L.straddle(c, r, k) for r in range(K.TWIN_A, K.TWIN_B + 1)) if x is not None])
    print(und, {t: len(v["tr"]) for t, v in out.items()}, flush=True)
    return out


def run(procs: int = 4):
    with Pool(procs) as p:
        parts = p.map(_job, R.UNDS)
    K.OUT.mkdir(parents=True, exist_ok=True)
    (K.OUT / "trades.pkl").write_bytes(pickle.dumps(parts))
    m_all = L117.count_prior(K.ROOT / "research" / "experiments" / "entries", K.ENTRIES_LAST_DAY) + len(K.TESTS)
    rng = np.random.default_rng(K.SEED)
    res = {"tests": {}, "m_all": m_all}
    ps = []
    for t, k in K.TESTS.items():
        tr = [x for p_ in parts for x in p_[t]["tr"]]
        tr2 = [x for p_ in parts for x in p_[t]["tr2"]]
        tw = [x for p_ in parts for x in p_[t]["tw"]]
        m = {per: S19.metrics([y for y in tr if K.period(y.day) == per]) for per in K.PERIODS}
        m["all"] = S19.metrics(tr)
        for per in (*K.PERIODS, "all"):
            sel = tr if per == "all" else [y for y in tr if K.period(y.day) == per]
            m[per]["stopped_pct"] = float(np.mean([y.extra["stopped"] for y in sel]) * 100) if sel else 0.0
        f2 = S19.metrics([y for y in tr2 if K.period(y.day) == "final"])
        tot = np.zeros(K.TWINS)
        for o in tw:
            o = np.asarray(o, float)
            if len(o):
                tot += o[rng.integers(0, len(o), K.TWINS)]
        fin = sum(y.net for y in tr if K.period(y.day) == "final")
        tp = L117.twin_p(fin, tot)
        ps.append(tp["p"])
        by = {u: {per: S19.metrics([y for y in tr if y.und == u and K.period(y.day) == per]) for per in K.PERIODS} for u in R.UNDS}
        res["tests"][t] = dict(name=f"short ATM straddle 09:30, index stop at {k:g} straddles, else out 15:05", k=k,
                               periods=m, final_2x=f2, twin=tp, by_index=by)
    q_all, q_own = L117.bh(ps, m_all), L117.bh(ps)
    for i, t in enumerate(K.TESTS):
        r = res["tests"][t]
        r.update(q_all=float(q_all[i]), q_r123=float(q_own[i]))
        f = r["periods"]["final"]
        fails = [f"{per} mean <= 0" for per in K.PERIODS if not r["periods"][per].get("trades") or r["periods"][per]["mean"] <= 0]
        if f.get("trades") and f["ex3"] <= 0:
            fails.append("final <= 0 without 3 best days")
        if not r["final_2x"].get("trades") or r["final_2x"]["mean"] <= 0:
            fails.append("final mean <= 0 at 2x slippage")
        if r["twin"]["p"] >= K.GATE_P:
            fails.append(f"twin p {r['twin']['p']:.3g}")
        if r["q_all"] > K.GATE_Q:
            fails.append(f"BH q {r['q_all']:.3g}")
        if f.get("trades", 0) < K.MIN_FINAL:
            fails.append(f"< {K.MIN_FINAL} final trades")
        if f.get("trades") and f["months_at_stop"] > 0:
            fails.append(f"{f['months_at_stop']} final months <= -13k")
        if f.get("trades") and f["max_dd"] >= K.DD_STOP:
            fails.append("final drawdown >= 40k")
        r["gates"] = dict(passed=not fails, fails=fails)
    K.RESULTS.mkdir(exist_ok=True)
    (K.RESULTS / "results.json").write_text(json.dumps(res, indent=1, default=str))
    (K.RESULTS / "report.md").write_text(report(res))
    print(report(res))


def rs(x):
    return "-" if x is None else f"{x:+,.0f}".replace("+-", "-")


def report(res: dict) -> str:
    md = ["# R123 results (generated by r123study.py)", "", f"Signal source: {K.SIGNAL_SOURCE}. BH m = {res['m_all']:,}.", ""]
    for t, r in res["tests"].items():
        md += [f"## {t}: {r['name']}", "",
               "| | trades | WIN | stopped | mean Rs | total Rs | gross / trade | charges / trade | worst day | max DD | "
               "months <= -13k | w/o 3 best | margin (est.) |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for per in (*K.PERIODS, "all"):
            m = r["periods"][per]
            md.append(f"| {per} | {m['trades']} | {m['win']:.1f}% | {m['stopped_pct']:.0f}% | {rs(m['mean'])} | "
                      f"{rs(m['total'])} | {rs(m['gross'])} | {m['charges']:,.0f} | {rs(m['worst_day'])} | "
                      f"{m['max_dd']:,.0f} | {m['months_at_stop']} | {rs(m['ex3'])} | {m['margin']:,.0f} |")
        f2 = r["final_2x"]
        md += ["", f"- Final at 2x slippage: {f2.get('trades', 0)} trades, mean Rs {rs(f2.get('mean'))}.",
               f"- Final twin p {r['twin']['p']:.4f}; BH q (all) {r['q_all']:.3g}; q (R123's 2) {r['q_r123']:.3g}.",
               f"- **{'PASS' if r['gates']['passed'] else 'fail'}**" + ("" if r["gates"]["passed"] else ": "
               + "; ".join(r["gates"]["fails"])), "", f"### {t} by index", "",
               "| index | design mean (n, win) | wf mean (n, win) | final mean (n, win) |", "|---|---|---|---|"]
        for u, b in r["by_index"].items():
            md.append(f"| {u} | " + " | ".join(
                f"{rs(b[p].get('mean'))} ({b[p].get('trades', 0)}, {b[p].get('win', 0):.0f}%)" for p in K.PERIODS) + " |")
        md.append("")
    return "\n".join(md) + "\n"


if __name__ == "__main__":
    if sys.argv[1:2] == ["run"]:
        run()
    elif sys.argv[1:2] == ["report"]:
        print(report(json.loads((K.RESULTS / "results.json").read_text())))
    else:
        print(__doc__)
