"""R197 report and log entries: results/final.json -> results/report.md and research/experiments/entries/r197-*.yaml.

    python3 -I research/hunt/r197_winrate80/r197report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
for p in (HERE, HERE.parent / "r195_option_selling", HERE.parent / "r196_selling_plus"):
    sys.path.insert(0, str(p))
import r197study as S7  # noqa: E402

ENTRIES = HERE.parents[1] / "experiments" / "entries"


def rs(x):
    return "-" if x is None else (f"-Rs {abs(round(x)):,}" if x < 0 else f"Rs {round(x):,}")


def describe(cid):
    c = S7.parse(cid)
    if c["fam"] == "G1":
        what = "straddle" if c["o"] == 0 else f"strangle {c['o']} steps out"
        return (f"NIFTY 09:20 short {what}, stop per leg at +{c['s']}% of its fill, "
                + ("no target" if c["t"] is None else f"target {c['t']}% of credit"))
    return (f"NIFTY bull put spread {c['o']} steps OTM, 4 wide, stop at 50% of max loss, "
            + ("no target" if c["t"] is None else f"target {c['t']}% of credit"))


def main():
    F = json.loads((S7.RESULTS / "final.json").read_text())
    T, m, sel = F["tests"], F["m"], F["selection"]
    L = ["# R197 results (generated by r197report.py)", "",
         f"Selection (design only, PREREG 4): Pick-N = {sel['Pick-N']}, Pick-A = {sel['Pick-A']} (no grid test reached "
         f"80% wins with a positive design net, so no pick and no extensions). BH m = {m:,}.", "",
         "| test | rule | design trades / win (Wilson 95%) / net | avg win / avg loss / W* | post-Nov-2024 net | 2026 second "
         "look trades / win / net | worst month / max DD (design + 2026) | BH q |", "|---|---|---|---|---|---|---|---|"]
    for cid in sorted(T, key=lambda k: -T[k]["design"]["win"]):
        t = T[cid]
        d, r, h, a = t["design"], t["design_ratio"], t["second_look_2026"], t["all"]
        L.append(f"| {cid} | {describe(cid)} | {d['n']} / {d['win']:.1%} ({r['wilson'][0]:.1%}-{r['wilson'][1]:.1%}) / "
                 f"{rs(d['net'])} | {rs(r['avg_win'])} / {rs(r['avg_loss'])} / {r['breakeven_win']:.1%} | "
                 f"{rs(t['post_regime'].get('net'))} | {h.get('n', 0)} / {h.get('win', 0):.1%} / {rs(h.get('net'))} | "
                 f"{rs(a.get('worst_month'))} / {rs(a.get('max_dd'))} | {t['bh_q']:.2f} |")
    (S7.RESULTS / "report.md").write_text("\n".join(L) + "\n")
    for cid, t in T.items():
        d, h, r = t["design"], t["second_look_2026"], t["design_ratio"]
        e = dict(
            id=f"r197-{cid.lower()}", title=f"R197 80% win-rate grid (side study): {cid} - {describe(cid)}",
            family="option-structure", date="2026-11-18", doc="research/HUNT_R197_WINRATE80.md",
            hypothesis="this setting wins >= 80% of trades AND makes money after costs (the selection rule takes the best "
                       "such grid test)",
            data_version="R195's stores (Drive lake copy of 18 Nov 2026; R51 Amendment A clean held contracts, 2 Aug 2021 - "
                         "13 Nov 2026)",
            period=dict(design="2021-08-02..2025-12-31", holdout="2026 is a second look (R195 read it); forward window from "
                                                                 "2026-11-16 not read"),
            instruments=["NIFTY"],
            features=["signal source: none directional (strikes from the index)", "stops and targets on the option premium"],
            model_or_rule=describe(cid), settings="research/hunt/r197_winrate80/r197study.py; PREREG.md section 3",
            prereg="research/hunt/r197_winrate80/PREREG.md", variants_tried=1,
            results=dict(summary=(f"design {d['n']} tr, win {d['win']:.1%} (Wilson {r['wilson'][0]:.1%}-{r['wilson'][1]:.1%}), "
                                  f"net {rs(d['net'])}, avg win {rs(r['avg_win'])}, avg loss {rs(r['avg_loss'])}, break-even "
                                  f"win {r['breakeven_win']:.1%}; 2026 second look {h.get('n', 0)} tr, win {h.get('win', 0):.1%}, "
                                  f"net {rs(h.get('net'))}; BH q {t['bh_q']:.2f} (m = {m:,}). Not selected: below 80% wins "
                                  f"in design (no grid test reached 80%)."),
                         costs="dated Zerodha charges, R103 'liq' slippage (stops doubled), today's lot every year"),
            holdout_read=False, verdict="rejected",
            notes="Research only (Boss, 18 Nov 2026: 'get me 80% winrate'). The app stays buy-only.")
        (ENTRIES / f"r197-{cid.lower()}.yaml").write_text(yaml.safe_dump(e, sort_keys=False, width=120, allow_unicode=True))
    print("report and", len(T), "entries written")


if __name__ == "__main__":
    main()
