from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import r196study as S6  # noqa: E402

ENTRIES = HERE.parents[1] / "experiments" / "entries"
RULE = {
    "A1": "09:20 straddle, 25% stop per leg, and the surviving leg's stop moved to cost after the first stop",
    "A2": "09:20 straddle with one combined stop at 1.20x the pair's entry (no per-leg stop)",
    "A3": "09:20 straddle, 25% stop per leg, profit lock armed at +30% of credit, out at +15%",
    "A4": "the 25%-per-leg straddle entered at 10:30",
    "A5": "09:20 strangle 2 steps out each side, 30% stop per leg",
    "A6": "09:20 straddle, 25% stop per leg, skipping shock days (open > 0.6% from yesterday's close or yesterday's range "
          ">= 1.5x its 20-session average)",
    "A7": "09:20 straddle, 25% stop per leg + stop to cost + profit lock, on days India VIX >= its 250-session median",
    "PS1": "bull put spread (short 2 steps OTM, long 6 steps OTM) at 09:20 on non-expiry days, stop at 50% of max loss",
    "PS2": "PS1 on days India VIX >= its 250-session median",
    "PS3": "PS1 on BANKNIFTY",
}


def rs(x):
    return "-" if x is None else (f"-Rs {abs(round(x)):,}" if x < 0 else f"Rs {round(x):,}")


def cell(s):
    if not s or not s.get("n"):
        return "0 trades"
    return (f"{s['n']} / {s['win'] * 100:.0f}% / {rs(s['net'])} / DD {rs(s['max_dd'])} / worst month {rs(s['worst_month'])} / "
            f"worst day {rs(s['worst_day'])}")


def main():
    fj = json.loads((S6.RESULTS / "final.json").read_text())
    T, m = fj["tests"], fj["m"]
    L = ["# R196 results (generated by r196report.py from results/final.json)", "",
         f"1 lot at today's lot, after slippage and dated charges; BH m = {m:,}. Cells: trades / win / net / max drawdown / "
         "worst month / worst day. 2026 is a SECOND LOOK (R195 read it once); the clean holdout is the forward window "
         "from 16 Nov 2026 (PREREG 3).", "",
         "| test | design 2021-2025 | post-Nov-2024 part | 2026 second look | base on the same design days | margin p95 (2026) "
         "| verdict: failed gates |", "|---|---|---|---|---|---|---|"]
    for cid in S6.CANDIDATES:
        t = T[cid]
        L.append(f"| {cid} | {cell(t['design'])} | {cell(t['post_regime'])} | {cell(t['second_look_2026'])} | "
                 f"{cell(t['base_same_days'])} | {rs(t['second_look_2026'].get('margin_p95'))} | {t['verdict']}: "
                 f"{', '.join(t['fails']) or 'none'} |")
    L += ["", "| test | aims vs base (net / win / DD) | paired gain vs base, design | paired p | twin p | boot p | BH q | "
          "2x slippage | account stop (design + 2026) | possible at Rs 56k |", "|---|---|---|---|---|---|---|---|---|---|"]
    for cid in S6.CANDIDATES:
        t, a = T[cid], T[cid]["all"]
        aims = " / ".join("yes" if t["aims"][k] else "no" for k in ("net", "win", "dd"))
        L.append(f"| {cid} | {aims} | {rs(t['paired_gain_vs_base'])} | {t['paired_p'] if t['paired_p'] is None else round(t['paired_p'], 3)} | "
                 f"{t['twin']['p_emp']} | {t['boot_p']:.3f} | {t['bh_q']:.3f} | {rs(t['net_2x_slip'])} | worst month "
                 f"{rs(a.get('worst_month'))}, DD {rs(a.get('max_dd'))} | "
                 f"{'yes' if t['possible_at_56k'] else 'no'} ({t['second_look_2026'].get('affordable_share', 0) * 100:.0f}%) |")
    L += ["", "## By year (design)", "", "| test | 2021 | 2022 | 2023 | 2024 | 2025 |", "|---|---|---|---|---|---|"]
    for cid in S6.CANDIDATES:
        y = T[cid]["years"]
        L.append(f"| {cid} | " + " | ".join(f"{y[str(k)]['n']} / {rs(y[str(k)]['net'])}" if str(k) in y else "-"
                                             for k in range(2021, 2026)) + " |")
    (S6.RESULTS / "report.md").write_text("\n".join(L) + "\n")
    for cid in S6.CANDIDATES:
        t, f = T[cid], S6.fam(cid)
        e = dict(
            id=f"r196-{cid.lower()}", title=f"R196 option selling, enhanced (side study): {cid} - {RULE[f]}",
            family="option-structure", date="2026-11-18", doc="research/HUNT_R196_SELLING_PLUS.md",
            hypothesis=f"{RULE[f]} beats R195's base (more net, higher win rate, smaller drawdown) and makes money after "
                       f"costs in design and 2026, inside the account stop",
            data_version="R195's stores (Drive lake copy of 18 Nov 2026; R51 Amendment A clean held contracts, 2 Aug 2021 - "
                         "13 Nov 2026)",
            period=dict(design="2021-08-02..2025-12-31 (no fitted parameter; trailing filters)",
                        holdout="2026-01-01..2026-11-13 is a second look (R195 read it once); the clean holdout is the "
                                "forward window from 2026-11-16, not read yet"),
            instruments=[S6.und_of(cid)],
            features=["signal source: none directional (strikes from the index); A6 the index; A7 / PS2 India VIX",
                      "stops and locks on the option premium; stale legs marked by Black-Scholes (R195)"],
            model_or_rule=RULE[f], settings="research/hunt/r196_selling_plus/r196study.py; PREREG.md section 4",
            prereg="research/hunt/r196_selling_plus/PREREG.md", variants_tried=1,
            results=dict(summary=(f"design {cell(t['design'])}; post-Nov-2024 {cell(t['post_regime'])}; 2026 second look "
                                  f"{cell(t['second_look_2026'])}; base on the same days {cell(t['base_same_days'])}; twin p "
                                  f"{t['twin']['p_emp']}, BH q {t['bh_q']:.3g} (m = {m:,}); possible at Rs 56k: "
                                  f"{'yes' if t['possible_at_56k'] else 'no'}. {t['verdict']}: {', '.join(t['fails']) or 'none'}"),
                         costs="dated Zerodha charges, R103 'liq' slippage (stops doubled), today's lot every year"),
            holdout_read=False, verdict="rejected" if t["verdict"] == "fail" else "inconclusive",
            notes="Research only (Boss, 18 Nov 2026: 'Enhance it more try internet'). The app stays buy-only. 2026 was "
                  "already read by R195; a pass would wait for the forward read.")
        (ENTRIES / f"r196-{cid.lower()}.yaml").write_text(yaml.safe_dump(e, sort_keys=False, width=120, allow_unicode=True))
    print("report and", len(S6.CANDIDATES), "entries written")


if __name__ == "__main__":
    main()
