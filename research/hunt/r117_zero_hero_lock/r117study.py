"""R117 study (PREREG.md): every pre-registered lock on the existing FT3 and Hero tickets, 2021-26.

    python3 research/hunt/r117_zero_hero_lock/r117study.py run      # tickets, parity, metrics, twins, BH, gates
                                                                    # -> results/results.json, results/report.md

Ticket lists go to $R117_OUT (not in git). The final period is read in the same run as design and walk-forward: nothing
is fitted, so there is nothing to choose between them (PREREG section 1); the run is done once.
"""
from __future__ import annotations

import json
import math
import pickle
import sys
from multiprocessing import Pool

import numpy as np

import r117cfg as K
import r117lib as L
import r98data as R98
import r54data as DD
import r54lib as LB
import r55lib as L55


def ft3_days(und):
    return [d for d in R98.load(und) if K.period(d.day) is not None]


def hero_days(und):
    days = pickle.loads(DD.days_path(und).read_bytes())
    return [d for d in DD._prep(days) if K.period(d.day) is not None]


def _ft3_job(und):
    return L.ft3_tickets(ft3_days(und), with_rand=True)


def _hero_job(und):
    LB.load_late()
    days = hero_days(und)
    ts = L.hero_tickets(days, with_rand=True)
    # parity, ticket by ticket: R117's T0 and HOLD are R55's own simulate (PREREG section 1)
    t = L55.ENTRY_ROW[L.HERO_ENTRY]
    byd = {d.day: d for d in days}
    for tk in ts:
        d = byd[tk.day]
        sgn = 1 if tk.side == "C" else -1
        pk = LB.pick(d, sgn, t)
        for x, r55 in (("T0", "T0"), ("HOLD", "H")):
            tr = L55.simulate(d, pk[0], sgn, t, pk[1], L.HERO_END, r55)
            assert tr is not None and abs(tr.net - tk.nets[x]) < 0.01, (tk.und, tk.day, tk.side, x, tr and tr.net, tk.nets[x])
    return ts


def rs(x):
    return "-" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:+,.0f}".replace("+-", "-")


def run(procs: int = 4):
    LB.load_late()
    with Pool(procs) as p:
        ft3 = [t for part in p.map(_ft3_job, R98.UNDS) for t in part]
        hero = [t for part in p.map(_hero_job, ("NIFTY", "SENSEX")) for t in part]
    # parity (PREREG section 1)
    n, m = len(ft3), float(np.mean([t.nets["HOLD"] for t in ft3]))
    assert (n, round(m, 2)) == K.FT3_PARITY, (n, m)
    for per, (pn, pnet) in K.HERO_PARITY.items():
        lo, hi = (K55_START, K55_DESIGN_END) if per == "design" else (K55_FINAL_START, K55_LAKE_END)
        sel = [t for t in hero if lo <= t.day <= hi]
        assert (len(sel), round(sum(t.nets["T0"] for t in sel))) == (pn, pnet), (per, len(sel), sum(t.nets["T0"] for t in sel))
    K.OUT.mkdir(parents=True, exist_ok=True)
    (K.OUT / "tickets.pkl").write_bytes(pickle.dumps(dict(FT3=ft3, HERO=hero)))
    fams = {"FT3": ft3, "HERO": hero}
    res: dict = {"families": {}, "tests": []}
    for f, ts in fams.items():
        exits = [K.FAMILY_BASE[f], K.FAMILY_REF[f], *K.FAMILY_RULES[f]]
        res["families"][f] = {x: {per: L.metrics([t for t in ts if K.period(t.day) == per], x) for per in K.PERIODS}
                              | {"all": L.metrics(ts, x)} for x in exits}
    m_all = L.count_prior(K.ROOT / "research" / "experiments" / "entries") + len(K.TESTS)
    m_zh = L.count_prior(K.ROOT / "research" / "experiments" / "entries", only=K.ZERO_HERO) + len(K.TESTS)
    ps = []
    for f, x in K.TESTS:
        fin = [t for t in fams[f] if K.period(t.day) == "final"]
        tw = L.twin_totals(fin, x, K.FAMILY_BASE[f])
        tp = L.twin_p(sum(t.nets[x] for t in fin), tw)
        changed = sum(t.dec[x] != t.dec[K.FAMILY_BASE[f]] for t in fin)
        res["tests"].append(dict(family=f, rule=x, name=K.RULES[x]["name"], twin=tp, changed_final=changed))
        ps.append(tp["p"])
    q_all, q_zh, q_own = L.bh(ps, m_all), L.bh(ps, m_zh), L.bh(ps)
    for i, tt in enumerate(res["tests"]):
        tt.update(q_all=float(q_all[i]), q_zero_hero=float(q_zh[i]), q_r117=float(q_own[i]))
        fm = res["families"][tt["family"]]
        tt["gates"] = L.gates(fm[tt["rule"]], fm[K.FAMILY_BASE[tt["family"]]], tt["twin"]["p"], tt["q_all"])
    res.update(m_all=m_all, m_zero_hero=m_zh, signal_source=K.SIGNAL_SOURCE,
               counts={f: {per: sum(K.period(t.day) == per for t in ts) for per in K.PERIODS} for f, ts in fams.items()})
    K.RESULTS.mkdir(exist_ok=True)
    (K.RESULTS / "results.json").write_text(json.dumps(res, indent=1, default=str))
    (K.RESULTS / "report.md").write_text(report(res))
    print(report(res))


import r55cfg as K55  # noqa: E402
K55_START, K55_DESIGN_END, K55_FINAL_START, K55_LAKE_END = K55.START, K55.DESIGN_END, K55.FINAL_START, K55.LAKE_END

NAMES = {**{k: v["name"] for k, v in K.ALL_EXITS.items()}}


def report(res: dict) -> str:
    md = ["# R117 results (generated by r117study.py)", "",
          f"Signal source: {res['signal_source']}.", "",
          f"BH: m = {res['m_all']:,} (every logged family to 27 Oct + R117's 12); zero-hero families only: "
          f"m = {res['m_zero_hero']:,}.", ""]
    for f, block in res["families"].items():
        md += [f"## {f} ({'Rs 5,000, five indices' if f == 'FT3' else 'Rs 1,000 lot, NIFTY + SENSEX, CE + PE'})", ""]
        for per in (*K.PERIODS, "all"):
            md += [f"### {per}", "",
                   "| exit | tickets | win | mean Rs | total Rs | reach 3x / 5x / 10x | sold >= 3x | worst run (n, Rs) | "
                   "max DD Rs | total w/o 3 best days | 95% range of mean |",
                   "|---|---|---|---|---|---|---|---|---|---|---|"]
            for x, mm in block.items():
                m = mm[per]
                if not m.get("tickets"):
                    md.append(f"| {x} {NAMES[x]} | 0 |  |  |  |  |  |  |  |  |  |")
                    continue
                md.append(f"| {x} {NAMES[x]} | {m['tickets']} | {m['win']:.1f}% | {rs(m['mean'])} | {rs(m['total'])} | "
                          f"{m['r3']:.1f}% / {m['r5']:.1f}% / {m['r10']:.1f}% | {m['sold3']:.1f}% | {m['run_n']}, "
                          f"{rs(m['run_rs'])} | {rs(m['max_dd'])} | {rs(m['ex3'])} | {rs(m['boot_lo'])} .. "
                          f"{rs(m['boot_hi'])} |")
            md.append("")
    md += ["## Tests (final period twins, BH, gates)", "",
           "| family | rule | final tickets changed | twin p | q (all) | q (zero-hero) | q (R117 only) | pass | fails |",
           "|---|---|---|---|---|---|---|---|---|"]
    for t in res["tests"]:
        md.append(f"| {t['family']} | {t['rule']} {t['name']} | {t['changed_final']} | {t['twin']['p']:.4f} | "
                  f"{t['q_all']:.3g} | {t['q_zero_hero']:.3g} | {t['q_r117']:.3g} | "
                  f"{'PASS' if t['gates']['passed'] else 'fail'} | {'; '.join(t['gates']['fails'])} |")
    return "\n".join(md) + "\n"


if __name__ == "__main__":
    if sys.argv[1:2] == ["run"]:
        run()
    elif sys.argv[1:2] == ["report"]:
        print(report(json.loads((K.RESULTS / "results.json").read_text())))
    else:
        print(__doc__)
