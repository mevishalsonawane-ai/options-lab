def events(path_csv, with_jobs=False):
    ev = pd.read_csv(path_csv)
    jobs = sorted(set(JOBS_EARLY) | set(ev.loc[ev.event == "jobs", "date"]))
    rows = [(d, "fomc", "14:00") for d in FOMC] + [(d, "cpi", "08:30") for d in CPI]
    if with_jobs:  # not used by the rules: several jobs dates in events.csv are wrong (first-Friday rule)
        rows += [(d, "jobs", "08:30") for d in jobs]
    out = pd.DataFrame(rows, columns=["date", "kind", "et"])
    out["t"] = [pd.Timestamp(f"{d} {t}", tz="America/New_York").tz_convert("UTC") for d, _, t in rows]
    return out.sort_values("t").reset_index(drop=True)
