"""R181 report: results/report.md from results/results.json. The plain-English part for Boss is
results/narrative.md (written after reading the one run), placed first; the tables below are generated.

    python -I research/hunt/r181_orderflow_cases/r181report.py      # re-render without re-running
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"C1": "Case 1 failed breakdown + absorption at VAL (long)", "C2": "Case 2 failed breakout + exhaustion at VAH (short)",
         "C3": "Case 3 stacked imbalances across VAH / VAL + retest", "C4": "Case 4 double bottom / top at POC + CVD divergence",
         "C5": "Case 5 stop-run trap beyond the prior-day low / high", "A+": "Bonus A+ edge + OI wall + order flow (16-28 Oct)"}


def rs(x):
    return "-" if x is None else f"Rs {x:,.0f}"


def pct(x):
    return "-" if x is None else f"{100 * x:.0f}%"


def row(name, s):
    return (f"| {name} | {s['n']} | {pct(s['win'])} | {rs(s['net'])} | {rs(s.get('net2'))} | {rs(s.get('mean'))} | "
            f"{rs(s.get('avg_win'))} | {rs(s.get('avg_loss'))} |")


def render(res: dict) -> str:
    out = []
    nar = HERE / "results" / "narrative.md"
    if nar.exists():
        out.append(nar.read_text().rstrip() + "\n")
    else:
        out.append("# R181 report\n\n(narrative pending)\n")
    out.append("\n---\n\n# Detail (generated by r181report.py from results.json)\n")
    out.append(f"Days in the 1-second export: {len(res['days'])} ({res['days'][0]} .. {res['days'][-1]}); the first is a "
               f"profile day only. 1 lot (NIFTY 65, BANKNIFTY 30); liquidity fills, dated charges; 2x = slippage doubled. "
               f"Rupees are per trade summed over the sample.\n")
    out.append("## Per case: order-flow (OF) version vs its price-only twin, the OF-fail rest and random entries\n")
    for c, S in res["cases"].items():
        out.append(f"### {NAMES[c]}\n")
        out.append("| set | trades | win | net 1x | net 2x | mean 1x | avg win | avg loss |\n|---|---|---|---|---|---|---|---|")
        out.append(row("price-only twin (all episodes)", S["price_only"]))
        out.append(row("**OF version**", S["of"]))
        out.append(row("OF-fail rest", S["of_fail"]))
        if "variant" in S:
            out.append(row("variant: app absorb formula", S["variant"]))
        out.append(row("OF at recorded bid / ask (sensitivity)", S["of_bid_ask"]))
        rt = S["random_twin"]
        out.append("")
        out.append(f"- Random-entry twins (200 a trade): mean of the 200 twin means {rs(rt['mean_of_means'])} a trade "
                   f"(2x {rs(rt['mean_of_means2'])}; 10th-90th percentile {rs(rt['p10'])} .. {rs(rt['p90'])}; twin win "
                   f"{pct(rt['win'])}) vs OF {rs(S['of']['mean'])}.")
        out.append(f"- T1 (OF vs random same-size picks of the price-only trades) p = {S['p_T1']}; T2 (vs random entries) "
                   f"p = {S['p_T2']}. Verdict: **{S['verdict']}**.")
        bi = ", ".join(f"{u} {v['n']} trades {rs(v['net'])}" for u, v in S["of_by_index"].items())
        bs = ", ".join(f"{'long' if s == 'L' else 'short'} {v['n']} trades {rs(v['net'])}" for s, v in S["of_by_side"].items())
        ps = ", ".join(f"{'long' if s == 'L' else 'short'} {v['n']} trades {rs(v['net'])}" for s, v in S["price_by_side"].items())
        out.append(f"- OF by index: {bi}. OF by side: {bs}. Price-only by side: {ps}. Off-ATM strikes used: {S['off_atm']}.")
        if "cross_check" in S:
            x = S["cross_check"]
            out.append(f"- Source cross-check (16-28 Oct, {x['n']} episodes): OF condition agrees between the two exports "
                       f"on {pct(x['agree'])}; OF trades with this export {x['of_this']['n']} ({rs(x['of_this']['net'])}), "
                       f"with the first export's deltas {x['of_other']['n']} ({rs(x['of_other']['net'])}).")
        out.append("")
    sa = res.get("sensitivity_amend2")
    if sa:
        out.append("## Post-hoc sensitivity (Amendment 2): levels without the noisy basis shift\n")
        out.append("No shift on the same futures contract; the roll day shifted by median basis. Descriptive only, no p "
                   "value.\n")
        out.append("| case | price-only trades | price-only net 1x / 2x | OF trades | OF win | OF net 1x / 2x |\n|---|---|---|---|---|---|")
        for c, v in sa["cases"].items():
            p_, o_ = v["price_only"], v["of"]
            out.append(f"| {c} | {p_['n']} | {rs(p_['net'])} / {rs(p_['net2'])} | {o_['n']} | {pct(o_['win'])} | "
                       f"{rs(o_['net'])} / {rs(o_['net2'])} |")
        out.append("")
    out.append(f"## Tests and BH (m = {res['m_total']:,})\n")
    out.append("| test | p | BH q (all m) | q within R181 |\n|---|---|---|---|")
    for t in res["tests"]:
        out.append(f"| {t['id']} | {t['p']} | {t['q_all']} | {t['q_within']} |")
    out.append("\nT1 = selection twin; T2 = random-entry twin; T1v = the app-absorb-formula variant's selection twin.\n")
    out.append("## Dropped episodes\n")
    out.append(", ".join(f"{k} {v}" for k, v in sorted(res["drops"].items())) or "none")
    out.append("\n(rr = failed the 2:1 rule, a price rule applied to every version; no_strike / no_price = no recorded "
               "option near the ATM at the entry second.)\n")
    out.append("## Per day (all cases)\n")
    out.append("| day | price-only trades | price-only net | OF trades | OF net |\n|---|---|---|---|---|")
    for d, v in sorted(res["per_day"].items()):
        out.append(f"| {d} | {v['price_n']} | {rs(v['price_net'])} | {v['of_n']} | {rs(v['of_net'])} |")
    out.append("\n## Data checks (per day, NIFTY / BANKNIFTY)\n")
    out.append("| day | futures minutes (of 375) | thin minutes (<20 s) | gap rows >= 5 s | stale | footprint minutes | "
               "spot minutes | option strikes |\n|---|---|---|---|---|---|---|---|")
    for d, q in sorted(res["quality"].items()):
        n, b = q["NIFTY"], q["BANKNIFTY"]
        out.append(" | ".join([f"| {d}"] + [f"{n[k]} / {b[k]}" for k in ("fut_minutes", "thin", "gap5", "stale",
                                                                         "fp_minutes", "spot_minutes", "strikes")]) + " |")
    out.append("\n## Levels used (prior day's futures volume profile, shifted by the change in basis)\n")
    out.append("| day index | POC | VAH | VAL | PDH | PDL | shift |\n|---|---|---|---|---|---|---|")
    for k, lv in res["levels"].items():
        if lv is None:
            out.append(f"| {k} | no levels (prior day < 300 footprint minutes) | | | | | |")
        else:
            out.append(f"| {k} | {lv['poc']:.1f} | {lv['vah']:.1f} | {lv['val']:.1f} | {lv['pdh']:.1f} | {lv['pdl']:.1f} | "
                       f"{lv['shift']} |")
    out.append("\n## Run log\n")
    for r in res["runs"]:
        out.append(f"- {r['at']}: {r['trades']} trades; PREREG sha256 {r['prereg_sha256'][:12]}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    res = json.loads((HERE / "results" / "results.json").read_text())
    (HERE / "results" / "report.md").write_text(render(res))
