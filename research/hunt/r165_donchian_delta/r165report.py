"""R165 report tables (results/tables.md) from results/design.json, design_r151.json, final.json, decision.json.

    python research/hunt/r165_donchian_delta/r165report.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
ARMS = ("R72", "R51")
RULES = ("B0", "DB1", "DB2", "DB3", "SD50", "SD60", "SD70", "SD80", "XI1", "XI2", "PKD", "OF1", "OF2", "OF3")
LOTS = (1, 2, 3)


def rs(x) -> str:
    if x is None:
        return "-"
    return ("-" if x < 0 else "") + "Rs " + f"{abs(round(x)):,}"


def pct(x) -> str:
    return "-" if x is None else f"{100 * x:.1f}%"


def main() -> str:
    d = json.loads((RESULTS / "design.json").read_text())
    f = json.loads((RESULTS / "final.json").read_text())
    dec = json.loads((RESULTS / "decision.json").read_text())
    d151 = json.loads((RESULTS / "design_r151.json").read_text())
    out = ["# R165 tables (generated by r165report.py)", ""]
    for arm in ARMS:
        out += [f"## {arm}: every rule, walk-forward (Apr 2025 - Mar 2026) and final (Apr - Oct 2026)", "",
                "| rule | lots | WF trades | WF win | WF net | final trades | final win | final net | final per trade | "
                "final worst month | final max DD | raw p | BH q (m 2,242) | pass |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in RULES:
            for n in LOTS:
                w, x = d[arm][f"{r}@{n}"]["wf"], f[arm][f"{r}@{n}"]["final"]
                g = dec.get(f"{arm}:{r}@{n}", {})
                out.append(f"| {r} | {n} | {w['trades']:,} | {pct(w['win'])} | {rs(w['net'])} | {x['trades']:,} | "
                           f"{pct(x['win'])} | {rs(x['net'])} | {rs(x['per_trade'])} | {rs(x['worst_month'])} | "
                           f"{rs(x['max_dd'])} | {g.get('p', '-')} | {g.get('q', '-')} | "
                           f"{'-' if r == 'B0' else ('yes' if g.get('passed') else 'no')} |")
        pk = f[arm]["r151_picker"]
        out += ["", f"R151's app picker on the final (a skipped break holds its side; the arm as it runs today): "
                + "; ".join(f"{n} lot{'s' if n > 1 else ''} {pk[f'@{n}']['trades']:,} trades, win {pct(pk[f'@{n}']['win'])}, "
                            f"net {rs(pk[f'@{n}']['net'])}" for n in LOTS) + ".", ""]
        out += [f"### {arm}: today's trades by the bought option's delta at entry (1 lot)", "",
                "| delta | WF trades | WF win | WF net | final trades | final win | final net |", "|---|---|---|---|---|---|---|"]
        for bw, bf in zip(d[arm]["buckets"]["wf"], f[arm]["buckets"]["final"]):
            out.append(f"| {bw['band']} | {bw['trades']:,} | {pct(bw['win'])} | {rs(bw['net'])} | {bf['trades']:,} | "
                       f"{pct(bf['win'])} | {rs(bf['net'])} |")
        z = d151[arm]
        out += ["", f"### {arm}: the Greeks in the picker vs R151's picker, same folds and size (walk-forward, 1 lot, "
                "dropped breaks removed before the walk)", "",
                "| picker | trades | win | net | per trade |", "|---|---|---|---|---|"]
        for k in ("B0", "R151_M2", "PKD"):
            out.append(f"| {k} | {z[k]['trades']:,} | {pct(z[k]['win'])} | {rs(z[k]['net'])} | {rs(z[k]['per_trade'])} |")
        fp = f[arm]["futures_proxy"]
        out += ["", f"### {arm}: index-future order-flow proxy at entry, descriptive ({fp.get('period')}, 1 lot)", "",
                "| 3-min futures proxy delta vs the trade | trades | win | net |", "|---|---|---|---|"]
        for k in ("with", "against", "flat"):
            out.append(f"| {k} | {fp[k]['trades']} | {pct(fp[k]['win'])} | {rs(fp[k]['net'])} |")
        out += ["", f"IV check ({arm}): design {d[arm]['iv_check']}; final {f[arm]['iv_check']}. Deltas: design "
                f"{d[arm]['deltas']}; final {f[arm]['deltas']}. PKD: {f[arm]['pkd']}.", ""]
    text = "\n".join(out) + "\n"
    (RESULTS / "tables.md").write_text(text)
    return text


if __name__ == "__main__":
    print(main()[:2000])
