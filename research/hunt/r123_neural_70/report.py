"""R123 report: results/wf.json (+ results/holdout.json when read) -> results/report.md. Pure formatting.

    python research/hunt/r123_neural_70/report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import r123cfg as K  # noqa: E402


def rs(x):
    if x is None:
        return "-"
    return f"{x:,.0f}" if abs(x) >= 10 else f"{x:,.1f}"


def pct(x):
    return "-" if x is None else f"{100 * x:.0f}%"


def rule_table(rules: dict, part: str) -> list[str]:
    head = ("| rule | n | trades/session | win | +X hit | avg win | avg loss | avg net | avg net 2x slip | break-even win "
            "| per session | per trade day | max DD | worst day | worst month | green days | p twins | p side | q |")
    out = [head, "|" + "---|" * 19]
    for r, s in rules.items():
        if not s.get("n"):
            out.append(f"| {r} | 0 | | | | | | | | | | | | | | | | | |")
            continue
        out.append(
            f"| {r} | {s['n']:,} | {s['trades_per_session']:.2f} | {pct(s['win_rate'])} | {pct(s['target_hit_rate'])} "
            f"| {rs(s['avg_win'])} | {rs(s['avg_loss'])} | {rs(s['avg_net'])} | {rs(s['avg_net_x2'])} "
            f"| {pct(s['breakeven_win'])} | {rs(s['per_session'])} | {rs(s['per_trade_day'])} | {rs(s['max_dd'])} "
            f"| {rs(s['worst_day'])} | {rs(s['worst_month'])} ({s['worst_month_name']}) | {pct(s['green_days'])} "
            f"| {s['p_twins']:.3f} | {s.get('p_side_twins', float('nan')):.3f} | {s['q']:.3f} |")
    return out


def main():
    res = K.RESULTS
    wf = json.loads((res / "wf.json").read_text())
    L = ["# R123 results (generated by report.py)", "",
         f"Rupees per lot after charges and slippage, today's lots. Walk-forward: {wf['rows']:,} decision rows, "
         f"{wf['sessions']:,} sessions (folds F1 2023, F2 2024, F3 2025, F4 Jan - 15 Mar 2026).", "",
         "## Walk-forward rules (pooled out-of-sample folds)", ""]
    L += rule_table(wf["rules"], "wf")
    L += ["", "Folds (n / net Rs / win):", ""]
    L += ["| rule | " + " | ".join(K.FOLDS) + " | folds positive | passes walk-forward | gates |",
          "|---|" + "---|" * (len(K.FOLDS) + 3)]
    for r, s in wf["rules"].items():
        fo = s.get("folds", {})
        cells = [f"{v['n']} / {rs(v['net'])} / {pct(v['win'])}" for v in fo.values()]
        g = ", ".join(k for k, v in s["gates"].items() if not v) or "all pass"
        L.append(f"| {r} | " + " | ".join(cells) + f" | {s.get('folds_positive', 0)} | {s['passes_wf']} | fails: {g} |")
    L += ["", "Per index (walk-forward n / net Rs / win):", "",
          "| rule | " + " | ".join(K.UNDS) + " |", "|---|" + "---|" * len(K.UNDS)]
    for r, s in wf["rules"].items():
        if s.get("n"):
            L.append(f"| {r} | " + " | ".join(f"{v['n']} / {rs(v['net'])} / {pct(v['win'])}"
                                              for v in s["by_und"].values()) + " |")
    L += ["", "## Model tests (walk-forward)", "",
          "| net | cell | metric | n | base rate | NN | best baseline | NN - best | 95% CI | folds better | p | q |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for m in wf["models"]:
        ci = m.get("ci") or m.get("ci_mse_gain") or m.get("ci_gain")
        d = m.get("nn_minus_best", m["nn"] - m["best_score"])
        L.append(f"| {m['net']} | {m['cell']} | {m['metric']} | {m['n']:,} | {m.get('base_rate', m.get('base_r2', ''))!s:.6} "
                 f"| {m['nn']:.4f} | {m['best']} {m['best_score']:.4f} | {d:+.4f} | [{ci[0]:+.5f}, {ci[1]:+.5f}] "
                 f"| {m.get('folds_better', '-')} | {m['p']:.3f} | {m['q']:.3f} |")
    L += ["", "## Calibration (walk-forward): predicted P(+X first) for the better side vs what happened", ""]
    for k, rows in wf["calibration"].items():
        L.append(f"- {k}: " + "; ".join(f"{b['bin']} n {b['n']:,}: predicted {pct(b['predicted'])}, "
                                         f"happened {pct(b['observed'])}" for b in rows if b["n"]))
    if wf.get("committee_gate"):
        L += ["", "N2 committee, average weight per specialist (walk-forward): " +
              ", ".join(f"{k} {v:.2f}" for k, v in wf["committee_gate"].items())]
    hp = res / "holdout.json"
    if hp.exists():
        ho = json.loads(hp.read_text())
        L += ["", f"## Holdout (1 Apr - 19 Oct 2026, read once): {ho['rows']:,} rows, {ho['sessions']} sessions", ""]
        L += rule_table(ho["rules"], "holdout")
        L += ["", "| rule | passes every gate | failed gates | Boss target strict (>= 65% win, >= Rs 800 avg) "
              "| lenient (>= 65% win, winners >= Rs 800, avg > 0) |", "|---|---|---|---|---|"]
        for r, s in ho["rules"].items():
            g = ", ".join(k for k, v in s["gates"].items() if not v) or "-"
            L.append(f"| {r} | {s['passes']} | {g} | {s['boss_target_strict']} | {s['boss_target_lenient']} |")
        L += ["", "Per index (holdout n / net Rs / win):", "",
              "| rule | " + " | ".join(K.UNDS) + " |", "|---|" + "---|" * len(K.UNDS)]
        for r, s in ho["rules"].items():
            if s.get("n"):
                L.append(f"| {r} | " + " | ".join(f"{v['n']} / {rs(v['net'])} / {pct(v['win'])}"
                                                  for v in s["by_und"].values()) + " |")
        L += ["", "### Holdout model tests", "",
              "| net | cell | metric | n | NN | best baseline | NN - best | 95% CI | p | q |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for m in ho["models"]:
            ci = m.get("ci") or m.get("ci_mse_gain") or m.get("ci_gain")
            d = m.get("nn_minus_best", m["nn"] - m["best_score"])
            L.append(f"| {m['net']} | {m['cell']} | {m['metric']} | {m['n']:,} | {m['nn']:.4f} "
                     f"| {m['best']} {m['best_score']:.4f} | {d:+.4f} | [{ci[0]:+.5f}, {ci[1]:+.5f}] "
                     f"| {m['p']:.3f} | {m['q']:.3f} |")
        L += ["", "### Holdout calibration", ""]
        for k, rows in ho["calibration"].items():
            L.append(f"- {k}: " + "; ".join(f"{b['bin']} n {b['n']:,}: predicted {pct(b['predicted'])}, "
                                             f"happened {pct(b['observed'])}" for b in rows if b["n"]))
        if ho.get("committee_gate"):
            L += ["", "N2 committee weights (holdout): " +
                  ", ".join(f"{k} {v:.2f}" for k, v in ho["committee_gate"].items())]
    (res / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
