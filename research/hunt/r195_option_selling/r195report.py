"""R195 report: results/final.json -> results/report.md (every column the PREREG lists).

    python3 -I research/hunt/r195_option_selling/r195report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import r195cfg as K  # noqa: E402
import r195rules as RU  # noqa: E402


def rs(x) -> str:
    if x is None:
        return "-"
    x = round(x)
    return f"-Rs {abs(x):,}" if x < 0 else f"Rs {x:,}"


def row(cid: str, label: str, s: dict) -> str:
    if not s or not s.get("n"):
        return f"| {cid} | {label} | 0 | - | - | - | - | - | - | - |"
    rom = f"{s['rom_year'] * 100:+.0f}%" if s.get("rom_year") is not None else "-"
    return (f"| {cid} | {label} | {s['n']} | {s['win'] * 100:.0f}% | {rs(s['net'])} | {rs(s['max_dd'])} | "
            f"{rs(s['worst_month'])} ({s['worst_month_at']}) | {rs(s['worst_day'])} ({s['worst_day_at']}) | "
            f"{rs(s['margin_p95'])} | {rom} |")


def main():
    fj = json.loads((K.RESULTS / "final.json").read_text())
    T, m = fj["tests"], fj["m"]
    L = ["# R195 results (generated by r195report.py from results/final.json)", "",
         f"One lot at today's lot, after slippage and dated charges. BH m = {m:,}. Margin = PREREG 3's model (95th "
         "percentile of the period's trades). Return on margin = net / mean margin, a year.", "",
         "## Every test by period", "",
         "| test | period | trades | win | net | max DD | worst month | worst day | margin p95 | return on margin |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for cid in RU.TESTS:
        t = T[cid]
        L.append(row(cid, "walk-forward", t["design"]))
        L.append(row(cid, "WF post-Nov-2024", t["post_regime_design"]))
        L.append(row(cid, "holdout 2026", t["holdout"]))
    L += ["", "## Gates and verdicts", "",
          "| test | verdict | failed gates | twin p | boot p | BH q | design net 2x slippage | net w/o top 5 (WF / HO) | "
          "account stop (design + holdout) | possible at Rs 56k (holdout share <= Rs 56k) |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for cid in RU.TESTS:
        t = T[cid]
        a = t["all"]
        acct = (f"worst month {rs(a.get('worst_month'))}, DD {rs(a.get('max_dd'))}, "
                f"{a.get('months_le_13k', 0)} months <= -Rs 13k" + (f", DD > Rs 40k from {a['dd_over_40k_from']}"
                                                                      if a.get('dd_over_40k_from') else ""))
        L.append(f"| {cid} | {t['verdict']} | {', '.join(t['failed']) or 'none'} | {t['twin'].get('p_emp')} | "
                 f"{t['boot_p']:.3f} | {t['bh_q']:.3f} | {rs(t['net_2x_slip'])} | "
                 f"{rs(t['design'].get('net_wo_top5'))} / {rs(t['holdout'].get('net_wo_top5'))} | {acct} | "
                 f"{'yes' if t['possible_at_56k'] else 'no'} ({t['holdout'].get('affordable_share', 0) * 100:.0f}%) |")
    L += ["", "## By calendar year (walk-forward period)", "", "| test | " + " | ".join(
        str(y) for y in range(2021, 2026)) + " |", "|---|" + "---|" * 5]
    for cid in RU.TESTS:
        y = T[cid]["years"]
        L.append(f"| {cid} | " + " | ".join(
            (f"{y[str(k)]['n']} / {rs(y[str(k)]['net'])}" if str(k) in y else "-") for k in range(2021, 2026)) + " |")
    L += ["", "## Exits, stale legs, credit and charges (design + holdout)", "",
          "| test | exits | trades with a Black-Scholes mark or fill | mean credit | mean charges |", "|---|---|---|---|---|"]
    for cid in RU.TESTS:
        a = T[cid]["all"]
        L.append(f"| {cid} | {a.get('why')} | {a.get('stale_trades')} of {a.get('n')} | {rs(a.get('credit_mean'))} | "
                 f"{rs(a.get('charges_mean'))} |")
    L += ["", "## Tail days (net on the day, 1 lot; 'no trade' = the rule did not trade)", ""]
    for cid in RU.TESTS:
        L.append(f"- **{cid}**: " + "; ".join(f"{k}: {rs(v) if not isinstance(v, str) else v}"
                                              for k, v in T[cid]["tail"].items()))
    (K.RESULTS / "report.md").write_text("\n".join(L) + "\n")
    print("written", K.RESULTS / "report.md")


if __name__ == "__main__":
    main()
