"""R46 report: results/design.json (+ holdout.json when read) -> results/report.md and the gate verdicts.

    python -m research.hunt.r46.report
"""
from __future__ import annotations

import json
import sys

from . import r46cfg as K

FAMILY = [f"{s}-{side}-{ex}-real" for s in ("A", "B") for side in ("call", "put") for ex in K.OPT_EXITS] + \
         ["A-perplong-P1-real", "A-perpshort-P1-real"]


def load(part):
    p = K.RESULTS / f"{part}.json"
    return json.loads(p.read_text()) if p.exists() else None


def gate(d: dict, h: dict | None, key: str) -> tuple[bool, str]:
    a = d["variants"].get(key, {})
    why = []
    if a.get("trades", 0) < K.MIN_TRADES:
        why.append(f"design trades {a.get('trades', 0)} < {K.MIN_TRADES}")
    if (a.get("after_tax") or 0) <= 0:
        why.append("design loses after tax")
    if not (a.get("twin_p") is not None and a["twin_p"] < K.P_MAX):
        why.append(f"design p {fmt(a.get('twin_p'), 3)}")
    if not (a.get("q") is not None and a["q"] <= K.Q_MAX):
        why.append(f"design q {fmt(a.get('q'), 3)}")
    if h is not None:
        b = h["variants"].get(key, {})
        if b.get("trades", 0) < K.MIN_TRADES:
            why.append(f"holdout trades {b.get('trades', 0)} < {K.MIN_TRADES}")
        if (b.get("after_tax") or 0) <= 0:
            why.append("holdout loses after tax")
    else:
        why.append("holdout not read")
    return (not why), "; ".join(why) or "passes every gate"


def fmt(x, d=2):
    if x is None:
        return "-"
    if isinstance(x, float):
        return f"{x:,.{d}f}"
    return f"{x:,}" if isinstance(x, int) else str(x)


def row(name, s, extra=""):
    if not s or not s.get("trades"):
        return f"| {name} | 0 | - | - | - | - | - | - | - | - | - | {extra} |"
    return (f"| {name} | {s['trades']} | {s['win'] * 100:.1f}% | {fmt(s['avg_win'])} | {fmt(s['avg_loss'])} | "
            f"{fmt(s['net'])} | {fmt(s['after_tax'])} | {fmt(s['per_day'])} | {fmt(s['worst'])} | "
            f"{fmt(s['max_dd'])} | {fmt(s.get('twin_p'), 3)} / {fmt(s.get('q'), 3)} | {extra} |")


HEAD = ("| variant | trades | win | avg win | avg loss | net before tax | after tax | after tax / day | worst | max DD | "
        "p / q | note |\n|---|---|---|---|---|---|---|---|---|---|---|---|")


def table(res, keys, scale_key=None, label=""):
    out = [HEAD]
    for k in keys:
        s = res["variants"].get(k)
        if s is None:
            continue
        if scale_key and "perp" not in k:          # perp rows are already per 1 BTC
            s = dict(s.get(scale_key) or {}, twin_p=s.get("twin_p"), q=s.get("q"))
        out.append(row(k, s, label))
    return "\n".join(out)


def main(argv=None):
    d, h = load("design"), load("holdout")
    if d is None:
        print("no design results")
        return 1
    L = ["# R46 results (generated by report.py; statistics only)", "",
         f"Design {d['span'][0][:10]} to {d['span'][1][:10]} ({d['days']} days)" +
         (f"; holdout {h['span'][0][:10]} to {h['span'][1][:10]} ({h['days']} days, read once)" if h else
          "; holdout not read yet"), "",
         "Money in USD. 'per lot' = 1 Delta contract (0.001 BTC); 'claim size' = the other AI's 1,000 contracts "
         "(1 BTC of underlying). Main fill = the option price one minute later + half spread. After tax = 31.2% of "
         "each winning trade's gross gain, no set-off. p = random-entry twins (1,000 draws, same days), q = BH over "
         "the 14-variant family.", ""]
    for part, res in (("Design", d), ("Holdout", h)):
        if res is None:
            continue
        L += [f"## {part}: main fill, claim size (1,000 contracts)", "", table(res, FAMILY, "claim_size"), ""]
        L += [f"## {part}: main fill, per lot (0.001 BTC)", "", table(res, [k for k in FAMILY if "perp" not in k]), ""]
        L += [f"## {part}: edge before costs (claim size): gross, fees, net before tax", "",
              "| variant | trades | gross before any cost | fees + GST | net before tax |", "|---|---|---|---|---|"]
        for k in FAMILY + [k.replace("-real", "-naive") for k in FAMILY if "perp" not in k]:
            s = res["variants"].get(k, {})
            c = s if "perp" in k else (s.get("claim_size") or {})
            if c.get("trades"):
                L.append(f"| {k} | {c['trades']} | {fmt(c.get('gross'))} | {fmt(c.get('fees'))} | {fmt(c['net'])} |")
        L.append("")
        L += [f"## {part}: naive fill (the printed trade, no spread, no delay), claim size", "",
              table(res, [k.replace("-real", "-naive") for k in FAMILY if "perp" not in k], "claim_size"), ""]
        L += [f"## {part}: stress fill (spread x 1.5), claim size", "",
              table(res, [k.replace("-real", "-stress") for k in FAMILY if "perp" not in k], "claim_size"), ""]
        L += [f"## {part}: A on the months B could trade (comparison), claim size", "",
              table(res, [f"A@B-{s}-{e}-real" for s in ("call", "put") for e in K.OPT_EXITS], "claim_size"), ""]
        L += [f"## {part}: Boss's window only (entries 00:00-09:00 IST), per lot", "", HEAD]
        for k in FAMILY:
            s = res["variants"].get(k, {})
            if "boss_window" in s:
                L.append(row(k, s["boss_window"]))
        L += ["", f"## {part}: after tax per quarter (per lot)", ""]
        for k in FAMILY:
            qd = res["variants"].get(k, {}).get("quarters", {})
            if qd:
                pos = sum(v > 0 for v in qd.values())
                L.append(f"- {k}: {pos} of {len(qd)} quarters positive; " +
                         ", ".join(f"{q} {v:,.2f}" for q, v in qd.items()))
        L += ["", f"## {part}: unfilled signals", ""]
        for k in FAMILY:
            s = res["variants"].get(k, {})
            if "signals" in s:
                L.append(f"- {k}: {s['signals']} signals, {s['unfilled']} unfilled")
        L += ["", f"## {part}: extras", "", "```", json.dumps(res["extra"], indent=1), "```", ""]
        if part == "Holdout":
            L += ["## Their window (1 Sep - 12 Oct 2026, inside the holdout; not a test), claim size", "", HEAD]
            for k in FAMILY:
                s = res["variants"].get(k, {})
                if "claim_window" in s:
                    c = s["claim_window"]
                    L.append(row(k, c.get("claim_size", c) if "perp" not in k else c))
            L.append("")
        L += [f"## {part}: MLP walk-forward log", "", "```"] + [json.dumps(x) for x in res["nn_log"]] + ["```", ""]
    L += ["## Gate (main fill)", "", "| variant | pass | why |", "|---|---|---|"]
    for k in FAMILY:
        ok, why = gate(d, h, k)
        L.append(f"| {k} | {'PASS' if ok else 'fail'} | {why} |")
    (K.RESULTS / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
