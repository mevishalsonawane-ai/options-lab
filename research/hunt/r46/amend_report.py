"""R46 amendments report: results/amend.json -> results/amend_report.md (statistics only).

    python -m research.hunt.r46.amend_report
"""
from __future__ import annotations

import json
import sys

from . import amend_cfg as A
from . import r46cfg as K

NAMES = {"nov24": "PRIMARY view: design 20 Nov 2024 - 31 Mar 2026, final test 1 Apr - 12 Oct 2026",
         "full": "Full span (beside it): design 1 Jan 2024 - 31 Mar 2026, final test 1 Apr - 12 Oct 2026"}


def f(x, d=2):
    if x is None:
        return "-"
    if isinstance(x, float):
        return f"{x:,.{d}f}"
    return f"{x:,}" if isinstance(x, int) else str(x)


def cell(s: dict) -> str:
    if not s or not s.get("trades"):
        return "0 | - | - | - | - | - | - / -"
    return (f"{s['trades']} | {s['win'] * 100:.1f}% | {f(s['net'])} | {f(s['after_tax'])} | {f(s['worst'])} | "
            f"{f(s['max_dd'])} | {f(s.get('twin_p'), 3)} / {f(s.get('q'), 3)}")


HEAD = ("| variant | part | trades | win | net before tax | after tax | worst trade (after tax) | max DD | p / q |\n"
        "|---|---|---|---|---|---|---|---|---|")


def main_table(rows: dict, scheme_of) -> list[str]:
    out = [HEAD]
    for name, r in rows.items():
        for part in ("design", "final"):
            s = r[part].get(scheme_of(name), {})
            out.append(f"| {name} | {part} | {cell(s)} |")
    return out


def cost_table(rows: dict, opt=True) -> list[str]:
    sch = list(A.OPT_SCHEMES if opt else A.PERP_SCHEMES)
    out = ["| variant | part | " + " | ".join(f"{s} net / after tax" for s in sch) + " |",
           "|---|---|" + "---|" * len(sch)]
    for name, r in rows.items():
        for part in ("design", "final"):
            vals = []
            for s in sch:
                x = r[part].get(s, {})
                vals.append(f"{f(x.get('net'))} / {f(x.get('after_tax'))}" if x.get("trades") else "-")
            out.append(f"| {name} | {part} | " + " | ".join(vals) + " |")
    return out


def main(argv=None) -> int:
    res = json.loads((K.RESULTS / "amend.json").read_text())
    L = ["# R46 amendments (15 Oct 2026): results (generated by amend_report.py; statistics only)", "",
         "Money in USD. v1 and v2 at the other AI's size (1,000 contracts = 1 BTC); perp per 1 BTC; the dip buy at $300 "
         "of premium a trade. Main fill: the one-minute-later fill + half spread. After tax = 31.2% of each winning "
         "trade's gross gain, no set-off. p = random-entry twins (1,000 draws, same days); q = BH over the 22-variant "
         "family (R46's 14 + v2 x 4 + dip x 4) for that view, part and cost reading. 'delta' = Delta India fees + 18% GST "
         "(R46's own, the gate); 'cs_gst' / 'cs_nogst' = CoinSwitch PRO 0.015% of notional with / without 18% GST "
         "(third-party figure, unverified). The final test is R46's holdout span, already read once by R46.", ""]
    for view in ("nov24", "full"):
        L += [f"## {NAMES[view]}", ""]
        v1 = {k: r for k, r in res["v1"][view].items() if k != "nn_log"}
        opt = {k: r for k, r in v1.items() if "perp" not in k}
        perp = {k: r for k, r in v1.items() if "perp" in k}
        L += ["### Amendment 1: R46 v1 (Delta costs, the gate)", ""] + main_table(opt, lambda n: "delta") + [""]
        L += ["### Amendment 1: R46 v1 under each cost reading", ""] + cost_table(opt) + [""]
        L += ["Perp (CoinSwitch futures taker 0.05% / maker 0.02%):", ""] + cost_table(perp, opt=False) + [""]
        L += ["p / q under the cheapest CoinSwitch reading (cs_nogst):", ""] + main_table(opt, lambda n: "cs_nogst") + [""]
        v2 = {k[:-len(view) - 1]: r for k, r in res["v2"]["trades"].items() if k.endswith(f"-{view}")}
        L += ["### Amendment 2: v2 ensemble trades (Delta costs)", ""] + main_table(v2, lambda n: "delta") + [""]
        L += ["### Amendment 2: v2 under each cost reading", ""] + cost_table(v2) + [""]
        L += ["### Amendment 2: AUC, random split vs time-ordered walk-forward (purge + 12-bar embargo)", "",
              "| features + label | random 80/20 (design) | walk-forward design | walk-forward final | rolling model vs "
              "held label (design / final) |", "|---|---|---|---|---|"]
        for src in ("roll", "held"):
            a = res["v2"]["auc"].get(f"{src}-{view}", {})
            r = a.get("random_split_design", {})
            L.append(f"| {src} | {f(r.get('auc'), 3)} (n {f(r.get('n_test'))}) | "
                     f"{f(a.get('time_split_design', {}).get('auc'), 3)} (n {f(a.get('time_split_design', {}).get('n'))})"
                     f" | {f(a.get('time_split_final', {}).get('auc'), 3)} (n {f(a.get('time_split_final', {}).get('n'))})"
                     f" | {f(a.get('time_split_design_vs_held_label'), 3)} / {f(a.get('time_split_final_vs_held_label'), 3)}"
                     " |")
        L += ["", "Rolling ATM switches inside the 60-minute label window:", "", "```",
              json.dumps(res["v2"]["switch"][view], indent=1), "```", ""]
        dp = {k[:-len(view) - 1]: r for k, r in res["v3"]["held"].items() if k.endswith(f"-{view}")}
        L += ["### Amendment 3: dip buy on HELD contracts, stop + lock (Delta costs)", ""] + \
            main_table(dp, lambda n: "delta") + [""]
        L += ["### Amendment 3: dip buy under each cost reading", ""] + cost_table(dp) + [""]
        L += ["### Gates", "", "| variant / cost | verdict |", "|---|---|"]
        L += [f"| {k} | {v} |" for k, v in res["gates"][view].items()] + [""]
    L += ["## Their windows (inside the final test / the whole claim period; not tests)", ""]
    cw = {k: r["claim_window"] for k, r in {**res["v2"]["trades"], **res["v3"]["held"]}.items()
          if isinstance(r, dict) and "claim_window" in r}
    L += ["| variant | trades | win | net before tax | after tax | worst | max DD | p / q |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {k} | {cell(r.get('delta', {}))} |" for k, r in cw.items()] + [""]
    L += ["## Amendment 3: their code reproduced (no stop, $5 cost: their claim only, not a test)", "", "```",
          json.dumps(res["v3"]["reproduction"], indent=1), "```", "",
          "Held-contract dip counts (claim period):", "", "```",
          json.dumps({k: v for k, v in res["v3"]["held"].items() if k.startswith("count_")}, indent=1), "```", ""]
    L += ["## Walk-forward logs", "", "```"]
    for k, lg in res["v2"]["wf_log"].items():
        L += [k] + [json.dumps(x) for x in lg]
    L += ["```", ""]
    (K.RESULTS / "amend_report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
