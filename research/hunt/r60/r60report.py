def x_title(vid):
    import r60study as T
    sym, setup = T.X_RULES[vid]
    when = "12:00 -> 14:30" if setup == "SN" else "18:00 -> 20:30"
    who = "all six MCX commodities, strongest first" if sym == "ALL" else sym
    insts = ["MCX", "GOLD", "SILVER", "CRUDE", "NATURALGAS"] if sym == "ALL" else ["MCX", LABEL[sym]]
    return (f"SoloMidday translated to MCX: {who}, {when}, 1-ITM else ATM option, future stop 0.3 ATR14, breakeven at "
            f"0.45 ATR14", insts)


def money(x):
    return "-" if x is None else f"{x:+,.0f}"


def line(vid, dsg, fin):
    d, f = dsg["design"], fin["test"]
    return (f"| {vid} | {d['trades']}, {money(d['net'])} | {f['trades']}, {f.get('win', '-')} | {money(f['net'])} "
            f"({money(f.get('per_trade'))}) | {money(f.get('net_2x'))} | {f.get('max_dd', '-')} | {f.get('worst_day', '-')} "
            f"| {f.get('months_green', '-')} | {f.get('top5_share', '-')} | {f.get('capital_median', '-')} "
            f"| {f.get('trades_per_day', '-')} | {fin['p']} | {fin['q']} | {fin['verdict']} |")


def tables(des, fin) -> str:
    import r60study as T
    out = ["# R60 tables (generated by r60report.py from results/design.json and results/final.json)", "",
           "Money in Rs, 1 lot, after real costs. Design = full design period for rules, out-of-fold walk-forward months "
           "for models (I4/I5 Jul 2025 - Mar 2026; M1/M2 Nov 2025 - Mar 2026). Final = 1 Apr - 13 Oct 2026, read once.",
           "", "| id | design: trades, net | final: trades, win | final net (per trade) | 2x costs | max DD | worst day "
           "| months green | top-5 share | capital/lot (median) | trades/day | p | q | verdict |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for v in T.ALL_IDS:
        out.append(line(v, des["variants"][v], fin["variants"][v]))
    out += ["", "## Per market, final test", "", "| id | per market (trades, net) |", "|---|---|"]
    for v in T.ALL_IDS:
        pm = fin["variants"][v]["test"].get("per_market", {})
        out.append(f"| {v} | " + "; ".join(f"{k} {x['trades']}, {money(x['net'])}" for k, x in pm.items()) + " |")
    out += ["", "## Per setup, final test (models)", "", "| id | per setup (trades, net) |", "|---|---|"]
    for v in ("I4", "I5", "M1", "M2"):
        ps = fin["variants"][v]["test"].get("per_setup", {})
        out.append(f"| {v} | " + "; ".join(f"{k} {x['trades']}, {money(x['net'])}" for k, x in ps.items()) + " |")
    out += ["", "## By month, final test", "", "| id | months |", "|---|---|"]
    for v in T.ALL_IDS:
        bm = fin["variants"][v]["test"].get("by_month", {})
        out.append(f"| {v} | " + "; ".join(f"{k} {money(x)}" for k, x in bm.items()) + " |")
    out += ["", "## Every candidate unfiltered (several a day; context, not gated)", "",
            "| setup:market | design trades, net | final trades, net |", "|---|---|---|"]
    du, fu = des.get("setups_unfiltered", {}), fin.get("setups_unfiltered", {})
    for k in sorted(set(du) | set(fu)):
        a, b = du.get(k, {}), fu.get(k, {})
        out.append(f"| {k} | {a.get('trades', 0)}, {money(a.get('net', 0))} | {b.get('trades', 0)}, "
                   f"{money(b.get('net', 0))} |")
    out += ["", "## Model skill (AUC, purged walk-forward)", "", "| id | design AUC | final AUC |", "|---|---|---|"]
    for v in ("I4", "M1", "M2"):
        out.append(f"| {v} | {des['variants'][v].get('auc')} | {fin['variants'][v].get('auc')} |")
    return "\n".join(out) + "\n"


def summary(dsg, fin) -> str:
    d, f = dsg["design"], fin["test"]
    s = (f"Design: {d['trades']} trades, net Rs {d['net']:+,}" + (f", win {d['win']:.0%}" if d['trades'] else "") +
         f". Final test (1 Apr - 13 Oct 2026, read once): {f['trades']} trades")
    if f["trades"]:
        s += (f", win {f['win']:.0%}, net Rs {f['net']:+,} (Rs {f['per_trade']:+,}/trade), at 2x costs Rs "
              f"{f['net_2x']:+,}, max DD Rs {f['max_dd']:,}, worst day Rs {f['worst_day']:,}, months green "
              f"{f['months_green']}, top-5 share {f['top5_share']}, capital per lot (median) Rs {f['capital_median']:,}, "
              f"trades per day {f.get('trades_per_day')}")
    s += f"; twin p {fin['p']}, BH q {fin['q']} (21 variants). Verdict: {fin['verdict']}."
    return s


def entries(des, fin):
    import r60study as T
    for v in T.ALL_IDS:
        title, insts = TITLE.get(v) or x_title(v)
        model = v in T.MODELS
        mcx = v.startswith(("X", "M"))
        fam = "ml" if model else "mcx-crypto" if mcx else "patterns-indicators"
        verdict = "paper-only" if fin["variants"][v]["verdict"] == "PASS" else "rejected"
        src = ("the commodity's near future (median option spot); option IV / OI context only in M1/M2" if mcx else
               "the underlying index; option-chain IV / PCR context only in I4/I5")
        e = dict(
            id=f"r60-{v.lower()}", title=f"R60 Solo on all markets {v}: {title}", family=fam, date="2026-10-15",
            doc=DOC,
            hypothesis=("Solo's rule makes money after real costs on a market it does not trade yet (gates: final net > 0, "
                        "random-entry twin p < 0.05, BH q <= 0.10 over 21 variants, 40+ trades, top-5 < net, design "
                        "positive)."),
            data_version=("Drive lake gdrive:IraAlgo-data-lake: " + (
                "options_rolling_1m MCX MONTH files (ATM-3..+3, 5 Aug 2025 - 13 Oct 2026; R47 foreign rows, R42 F1 and "
                "spikes.py bad prints removed), near-future proxy = median option spot" if mcx else
                "index_1m + INDIAVIX, options_rolling_1m WEEK files (foreign rows, bad ticks removed), 21 Nov 2024 - "
                "13 Oct 2026")),
            period=dict(design=("5 Aug 2025 - 31 Mar 2026" if mcx else "21 Nov 2024 - 31 Mar 2026") +
                        (" (purged walk-forward, monthly refits)" if model else ""),
                        holdout="1 Apr - 13 Oct 2026 final test, read once (not pristine: R47-R59 saw parts of it)"),
            instruments=insts,
            features=[f"signal source: {src}"] + (
                ["proxy returns 15/60 min and since the open, range / ATR14, edge distance, 30-min realised vol, ATR %, "
                 "minute, US-session flag, sessions to expiry, ATM IV, PCR OI, commodity / setup one-hots, side"] if v in (
                    "M1", "M2") else ["R57 A2 inputs (12 brain index features, ATR14, minute, DTE, VIX, PCR / IV / skew "
                                      "context, index one-hots incl. SENSEX, side, setup)"] if v in ("I4", "I5") else []),
            model_or_rule=title, settings="research/hunt/r60/PREREG.md section 3; research/hunt/r60/r60study.py",
            prereg=PREREG, variants_tried=21,
            results=dict(summary=summary(des["variants"][v], fin["variants"][v]),
                         costs=("Zerodha MCX option charges (CTT 0.05% sell), per-commodity half-spread doubled before "
                                "17:00 and on a thin side, next-minute fills, one held contract, 1 lot" if mcx else
                                "dated charges (STT 0.15% from 1 Apr 2026; BSE rates for SENSEX), R17 liq fills, "
                                "next-minute fills, one held contract, 1 lot in force")),
            holdout_read=True, verdict=verdict,
            notes=("Paper only. " + ("SENSEX is BSE: the app's paper account is NSE F&O only (IraSolo.kt), so Solo cannot "
                                     "trade it today. " if "SENSEX" in insts else "") + EXTRA.get(v, "") +
                   "Signal on the underlying; no rule reads an option's own chart."))
        (ENTRIES / f"r60-{v.lower()}.yaml").write_text(yaml.safe_dump(e, sort_keys=False, allow_unicode=True, width=120))


def main():
    des = json.loads((C.RESULTS / "design.json").read_text())
    fin = json.loads((C.RESULTS / "final.json").read_text())
    (C.RESULTS / "r60_tables.md").write_text(tables(des, fin))
    entries(des, fin)
    print("wrote", C.RESULTS / "r60_tables.md", "and", len(list(ENTRIES.glob("r60-*.yaml"))), "entries")


if __name__ == "__main__":
    main()
