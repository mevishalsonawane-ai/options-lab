"""Writes research/hunt/r43/results/report.md from results/design.json (and final.json once the holdout was read).

    python3 research/hunt/r43/report.py
"""
from __future__ import annotations

import json

import r43cfg as K


def _f(x) -> str:
    return "-" if x is None else f"{x:+,.0f}"


def _row(rid: str, v: dict) -> str:
    m = v["m"]
    t5 = "-" if m["top5_share"] is None else f"{m['top5_share']:.0f}%"
    return (f"| {rid} | {m['trades']} ({m['ce']}/{m['pe']}) | {m['win_pct']:.1f} | {m['peak5']}/{m['peak10']} | "
            f"{m['banked5']}/{m['banked10']} | {_f(m['net'])} | {m['net_per_day']:+.0f} | {m['per_1000']:+.0f} | "
            f"{_f(m['worst_day'])} | {_f(m['max_dd'])} | {t5} | {_f(m['net_wo_top5'])} | {_f(m['spread2x'])} | "
            f"{_f(m['oor0'])} | {_f(v['twin_mean'])} | {v['p']:.3f} | {v['q']:.3f} |")


HEAD = ("| rule (signal-strike-window-exit) | trades (CE/PE) | win % | peak 5x/10x | banked 5x/10x | net Rs | net a day | "
        "per Rs 1,000 | worst day | max DD | top-5 share | net w/o top 5 | 2x spread | out-of-range at 0 | twin mean | "
        "p | q |\n|" + "---|" * 17)


def main():
    d = json.loads((K.RESULTS / "design.json").read_text())
    out = ["# R43 results (generated by report.py)", ""]
    fin = None
    if (K.RESULTS / "final.json").exists():
        fin = json.loads((K.RESULTS / "final.json").read_text())
        h = json.loads((K.RESULTS / "holdout.json").read_text())
        out += [f"Passed every gate: {len(fin['passed'])} of {fin['n_rules']}: {', '.join(fin['passed']) or 'none'}.", "",
                f"## Holdout (1 Jan 2025 - 12 Oct 2026; {h['n_index_days']} index-expiry-days {h['index_days']}; "
                f"BH over {h['bh_size']})", "", HEAD]
        out += [_row(rid, v) for rid, v in sorted(h["rules"].items(), key=lambda x: -x[1]["m"]["net"])]
        out += ["", "### Gates", "", "| rule | design net>0 | holdout net>0 | p<0.05 | q<=0.10 | 40+ trades | top-5 < 100% | "
                "pass |", "|" + "---|" * 8]
        for rid, v in sorted(fin["rules"].items(), key=lambda x: -x[1]["holdout"]["m"]["net"]):
            g = v["gates"]
            out.append(f"| {rid} | " + " | ".join("yes" if g[k] else "no" for k in
                       ("design_net>0", "holdout_net>0", "p<0.05", "q<=0.10", "trades>=40", "top5<100%", "passes")) + " |")
        out.append("")
    out += [f"## Design (expiry days to 31 Dec 2024; {d['n_index_days']} index-expiry-days {d['index_days']}; "
            f"BH over {d['bh_size']})", "", HEAD]
    out += [_row(rid, v) for rid, v in sorted(d["rules"].items(), key=lambda x: -x[1]["m"]["net"])]
    out += ["", "### Design per year (trades, net Rs): the walk-forward of fixed rules", "",
            "| rule | 2021 | 2022 | 2023 | 2024 |", "|---|---|---|---|---|"]
    for rid, v in d["rules"].items():
        y = v["by_year"]
        out.append(f"| {rid} | " + " | ".join(f"{y[k][0]}, {y[k][1]:+,.0f}" if k in y else "-"
                                             for k in ("2021", "2022", "2023", "2024")) + " |")
    out += ["", "### Per index (trades, net Rs): design" + (" | holdout" if fin else ""), "",
            "| rule | " + " | ".join(K.UNDS) + " |", "|" + "---|" * (len(K.UNDS) + 1)]
    for rid, v in d["rules"].items():
        cells = []
        for u in K.UNDS:
            a = v["by_index"].get(u, [0, 0])
            s = f"{a[0]}, {a[1]:+,.0f}"
            if fin:
                b = fin["rules"][rid]["holdout"]["by_index"].get(u, [0, 0])
                s += f" \\| {b[0]}, {b[1]:+,.0f}"
            cells.append(s)
        out.append(f"| {rid} | " + " | ".join(cells) + " |")
    (K.RESULTS / "report.md").write_text("\n".join(out) + "\n")
    print("wrote report.md")


if __name__ == "__main__":
    main()
