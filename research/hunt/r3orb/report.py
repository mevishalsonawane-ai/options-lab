#!/usr/bin/env python3
"""R3 tables for the report (results/report.md) from results/design.json and results/holdout.json.

    python3 research/hunt/r3orb/report.py
"""
from __future__ import annotations

import json

import r3cfg as K
import r3engine as E

ARMS4 = E.ARMS


def row(name, sc, extra=""):
    return (f"| {name} | {sc['trades']:,} | {sc['trades_per_day']:.2f} | {sc['win_rate']:.0%} | {sc['avg_win']:+,.0f} / "
            f"{sc['avg_loss']:+,.0f} | {sc['net']:+,.0f} | {sc['per_day']:+,.0f} | {sc['green_days']:.0%} | "
            f"{sc['worst_day']:+,.0f} | {sc['max_dd']:+,.0f} | {sc['cut_short']} |{extra}")


HEAD = ("| rule | trades | trades / day | win rate | avg win / avg loss | net Rs | Rs / day | green days | worst day | "
        "max drawdown | big winners cut short |")


def ids():
    out = []
    for a in ARMS4:
        out += [f"base-{a}"] + [f"r3-{a}-{x}" for x in "FESC"]
    return out


def main():
    d = json.loads((K.RESULTS / "design.json").read_text())["results"]
    hpath = K.RESULTS / "holdout.json"
    h = json.loads(hpath.read_text()) if hpath.exists() else None
    md = ["# R3 tables (generated by report.py)\n"]
    md.append("## T1. Design: BANKNIFTY + NIFTY, every session (Sep 2021 / Aug 2021 .. 12 Oct 2026), Rs after costs, 1 lot\n")
    md.append("Trades / day and Rs / day are per calendar day (2 indices). Green days: share of days with a trade that ended "
              "above zero.\n")
    md.append(HEAD + " BANKNIFTY | NIFTY | D1-D4 |\n|" + "---|" * 14)
    for i in ids():
        r = d[i]
        g = "".join("y" if r["gates"][k] else "n" for k in ("D1", "D2", "D3", "D4")) if "gates" in r else ""
        md.append(row(i, r["all"], f" {r['BANKNIFTY']['net']:+,.0f} | {r['NIFTY']['net']:+,.0f} | {g} |"))
    md.append("\n## T2. Design per year (BANKNIFTY + NIFTY), Rs (trades)\n")
    md.append("| rule | " + " | ".join(str(y) for y in K.YEARS) + " | years > 0 | 2025-26 (filter's walk-forward block) |\n|"
              + "---|" * (len(K.YEARS) + 3))
    for i in ids():
        yy = d[i]["years"]
        late = sum(yy[str(y)][0] for y in (2025, 2026) if str(y) in yy)
        md.append(f"| {i} | " + " | ".join(f"{yy[str(y)][0]:+,} ({yy[str(y)][1]})" if str(y) in yy else "-" for y in K.YEARS)
                  + f" | {sum(yy[k][0] > 0 for k in yy)} of {len(yy)} | {late:+,} |")
    if h:
        hr = h["results"]
        md.append(f"\n## T3. Holdout (read once {h['read']}): FINNIFTY + MIDCPNIFTY + SENSEX, every session, Rs after costs\n")
        md.append(HEAD + " FINNIFTY | MIDCPNIFTY | SENSEX | t p | twin mean / p | BH q (t / twin) | H1-H5 | PASS |\n|"
                  + "---|" * 19)
        for i in ids():
            r = hr[i]
            u = " | ".join(f"{r[x]['net']:+,.0f}" for x in K.HOLDOUT_UNDS)
            tw = f"{r['twin_mean']:+,.0f} / {r['twin_p']:.3f}" if "twin_p" in r else "-"
            q = f"{r['q_t']:.2f} / {r['q_twin']:.2f}" if "q_t" in r else "-"
            g = "".join("y" if r["gates"][k] else "n" for k in ("H1", "H2", "H3", "H4", "H5")) if "gates" in r else "-"
            ok = ("PASS" if r.get("holdout_pass") and d[i].get("design_pass") else "fail") if "gates" in r else "baseline"
            md.append(row(i, r["all"], f" {u} | {r['t_p']:.3f} | {tw} | {q} | {g} | {ok} |"))
        md.append(f"\nBH over m = {h['m']} p-values (R3's 32 + 151 earlier ORB-family tests, results/prior_p.json).\n")
        md.append("\n## T4. Holdout per year (pooled 3 indices), Rs (trades)\n")
        md.append("| rule | " + " | ".join(str(y) for y in K.YEARS) + " |\n|" + "---|" * (len(K.YEARS) + 1))
        for i in ids():
            yy = hr[i]["years"]
            md.append(f"| {i} | " + " | ".join(f"{yy[str(y)][0]:+,} ({yy[str(y)][1]})" if str(y) in yy else "-" for y in K.YEARS) + " |")
    wf = json.loads((K.RESULTS / "design.json").read_text())["walk_forward"]
    md.append("\n## T5. Nested walk-forward (design): the best rule on the years before, traded in the next year\n")
    md.append("| test year | pick | its net | ORB | ORB Fresh | ORB Sweep | Range Fade |\n|---|---|---|---|---|---|---|")
    for y, w in wf.items():
        b = w["baselines"]
        md.append(f"| {y} | {w['pick']} | {w['net']:+,} | {b['orb']:+,} | {b['orb_fresh']:+,} | {b['orb_sweep']:+,} | {b['range_fade']:+,} |")
    (K.RESULTS / "report.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
