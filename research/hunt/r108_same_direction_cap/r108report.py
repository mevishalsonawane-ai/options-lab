"""R108 report: results/report.md (every table, n with every number) and research/experiments/entries/r108-*.yaml (all 7
tests, failures included), from results/design.json, final.json and decision.json.

    python research/hunt/r108_same_direction_cap/r108report.py
"""
from __future__ import annotations

import json

import r108cfg as K

ROWS = K.BASES + K.TESTS


def rs(x) -> str:
    if x is None:
        return "-"
    x = float(x)
    s = f"{abs(x):,.0f}"
    # Indian grouping (lakh): 12,34,567
    neg = x < 0
    n = str(int(round(abs(x))))
    if len(n) > 3:
        head, tail = n[:-3], n[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts + [tail])
    else:
        s = n
    return ("-Rs " if neg else "Rs ") + s


def load():
    d = json.loads((K.RESULTS / "design.json").read_text())
    f = json.loads((K.RESULTS / "final.json").read_text())
    dec = json.loads((K.RESULTS / "decision.json").read_text())
    per = {"design": d["design"], "wf": d["wf"], "final": f["final"]}
    return per, dec


def table(per: dict, period: str) -> list:
    r = per[period]
    out = [f"### {dict(design='Design (20 Nov 2024 - 31 Mar 2026)', wf='Walk-forward window (1 Apr 2025 - 31 Mar 2026)', final='Final (1 Apr - 13 Oct 2026, read once)')[period]}",
           "",
           "| rule | net | trades | win | worst day | max drawdown | months <= -Rs 13k | Rs 40k DD breaches | days <= -Rs 13k | refused | twin p |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in ROWS:
        x = r[k]
        tw = x.get("twin", {}).get("p")
        out.append(f"| {k} | {rs(x['net'])} | {x['trades']:,} | {round(100 * x['win']) if x['win'] is not None else '-'}% | "
                   f"{rs(x['worst_day'])} | {rs(x['max_dd'])} | {x['months_below']} of {x['months']} | {x['dd_breaches']} | "
                   f"{x['days_below']} | {x.get('refused', '-') if k != 'ALONE' else '-'} | {tw if tw is not None else '-'} |")
    return out + [""]


def arms_table(per: dict, period: str, rule: str = "CAP2") -> list:
    r = per[period][rule]["arms"]
    out = [f"| arm ({rule}, {period}) | on the account: n, net | refused (would-be / dropped): n, net | one option, one arm (would-be): n, net |",
           "|---|---|---|---|"]
    for a in K.ARMS:
        x = r[a]
        out.append(f"| {K.ARM_NAME[a]} | {x['real']['n']:,}, {rs(x['real']['net'])} | {x['refused']['n']:,}, {rs(x['refused']['net'])} | "
                   f"{x['held']['n']:,}, {rs(x['held']['net'])} |")
    return out + [""]


def steps_table(per: dict) -> list:
    out = ["| step | design net (trades) | walk-forward net (trades) | final net (trades) |", "|---|---|---|---|"]
    for k in per["design"]["_r107_steps"]:
        cells = [f"{rs(per[p]['_r107_steps'][k]['net'])} ({per[p]['_r107_steps'][k]['trades']:,})" for p in K.PERIODS]
        out.append(f"| {k} | " + " | ".join(cells) + " |")
    return out + [""]


def subsets_table(per: dict) -> list:
    out = ["| arms (1 lot) | design: max DD, months <= -13k (no cap / cap 2) | final: max DD, months <= -13k (no cap / cap 2) | inside the rule in both (no cap / cap 2) |",
           "|---|---|---|---|"]
    for k in per["design"]["_subsets"]:
        cells, ok = [], []
        for p in ("design", "final"):
            a, b = per[p]["_subsets"][k]["NOCAP"], per[p]["_subsets"][k]["CAP2"]
            cells.append(f"{rs(a['max_dd'])}, {a['months_below']} / {rs(b['max_dd'])}, {b['months_below']}")
        for n in ("NOCAP", "CAP2"):
            ok.append("yes" if all(per[p]["_subsets"][k][n]["max_dd"] < K.ACCOUNT_DD and per[p]["_subsets"][k][n]["months_below"] == 0
                                   for p in ("design", "final")) else "no")
        out.append(f"| {k.replace('+', ' + ')} | " + " | ".join(cells) + f" | {ok[0]} / {ok[1]} |")
    return out + [""]


def gates_table(per: dict, dec: dict) -> list:
    out = ["| test | rule | net: design / walk-forward / final (CAP2: " +
           " / ".join(rs(per[p]["CAP2"]["net"]) for p in K.PERIODS) + ") | final twin p | BH q (5,784 tests) | verdict | first failures |",
           "|---|---|---|---|---|---|---|"]
    for t in K.TESTS:
        g = dec[t]
        nets = " / ".join(rs(per[p][t]["net"]) for p in K.PERIODS)
        out.append(f"| {t} | {K.LABEL[t]} | {nets} | {g['twin_p']} | {g['q_all']} | {'PASS' if g['passed'] else 'fail'} | "
                   f"{'; '.join(g['fails'][:3])}{' ...' if len(g['fails']) > 3 else ''} |")
    return out + [""]


def report() -> str:
    per, dec = load()
    L = ["# R108 results (generated by r108report.py)", "",
         f"Twins: {K.TWINS:,} random-refusal twins per test and period (seed {K.SEED}). BH over {dec['_m']['total']:,} tests "
         f"({dec['_m']['r108']} R108 + {dec['_m']['prior']:,} earlier, R64-R107). Nets after charges, 1 lot.", "",
         "## Gates", ""] + gates_table(per, dec)
    L += ["## With and without the cap, by period", ""]
    for p in K.PERIODS:
        L += table(per, p)
    L += ["## The arms inside the book", ""]
    for p in K.PERIODS:
        L += arms_table(per, p, "CAP2") + arms_table(per, p, "NOCAP")
    L += ["## Why R107's lead was bigger: R107's model, then each app choice", ""] + steps_table(per)
    L += ["## Boss's account rule by arm set (Rs 40,000 drawdown, no month at or below -Rs 13,000)", ""] + subsets_table(per)
    return "\n".join(L) + "\n"


def entries(per: dict, dec: dict) -> dict:
    out = {}
    for t in K.TESTS:
        g = dec[t]
        def one(p):
            x, c = per[p][t], per[p]["CAP2"]
            return (f"{dict(design='Design', wf='Walk-forward', final='Final')[p]}: {x['trades']:,} trades, net {rs(x['net'])} "
                    f"(CAP2 {rs(c['net'])}, {c['trades']:,} trades; no cap {rs(per[p]['NOCAP']['net'])}), max DD {rs(x['max_dd'])} "
                    f"(CAP2 {rs(c['max_dd'])}), worst day {rs(x['worst_day'])}, months <= -Rs 13k {x['months_below']} (CAP2 "
                    f"{c['months_below']}), Rs 40k breaches {x['dd_breaches']} (CAP2 {c['dd_breaches']}), twin p {x['twin']['p']}.")
        summ = " ".join(one(p) for p in K.PERIODS)
        summ += f" BH q {g['q_all']} over {dec['_m']['total']:,} tests (R108 alone {g['q_r108']}). " + \
            (f"Fails {len(g['fails'])} checks, first: " + "; ".join(g["fails"][:3]) + "." if g["fails"] else "Passes every gate.")
        out[t] = summ
    return out


def yaml_quote(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


