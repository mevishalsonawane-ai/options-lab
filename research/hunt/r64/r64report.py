"""R64 report: results/summary.json -> results/report.md (the BEFORE vs AFTER tables of HUNT_R64_LOCK_30_60_100.md).

    python research/hunt/r64/r64study.py report
"""
from __future__ import annotations

import json

import r64cfg as R

PH = (("design", "Design 20 Nov 2024 - 31 Mar 2026"), ("wf", "Walk-forward Apr 2025 - Mar 2026 (Solo 2.0: Jul 2025 -)"),
      ("final", "Final 1 Apr - 13/14 Oct 2026 (already read by R51 / R52 / R57: weaker evidence)"))
SHORT = {"B0": "BEFORE", "A1": "A1 -10% + ladder, own time", "A2": "A2 -10% + ladder, to 15:15",
         "A3": "A3 -10% only", "A4": "A4 own stop + ladder"}


def rs(x) -> str:
    if x is None:
        return "-"
    x = round(x)
    s = f"{abs(x):,}"
    return f"-Rs {s}" if x < 0 else f"Rs {s}"


def pct(x) -> str:
    return "-" if x is None else f"{100 * x:.0f}%"


def table(rows: dict) -> list:
    """rows: {variant: stats dict} -> markdown lines."""
    out = ["| variant | trades (days) | win | net | per trade | avg win | avg loss | biggest loss | worst day | "
           "max DD | green days | stops / locks / targets | big movers: kept / cut |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for v, s in rows.items():
        if not s or not s.get("trades"):
            out.append(f"| {SHORT[v]} | 0 | | | | | | | | | | | |")
            continue
        out.append(f"| {SHORT[v]} | {s['trades']:,} ({s['days']}) | {pct(s['win'])} | **{rs(s['net'])}** | "
                   f"{rs(s['per_trade'])} | {rs(s['avg_win'])} | {rs(s['avg_loss'])} | {rs(s['biggest_loss'])} | "
                   f"{rs(s['worst_day'])} | {rs(s['max_dd'])} | {pct(s['green_days'])} | "
                   f"{s['stops']} / {s['locks']} / {s['targets']} | {s['big_movers']}: {s['big_kept']} / "
                   f"{s['big_cut']} |")
    return out


def gate_table(arm: dict) -> list:
    out = ["| variant | final twin p | BH q (15 tests) | AFTER - BEFORE, design (bootstrap p) | AFTER - BEFORE, final "
           "(bootstrap p) | walk-forward quarters | verdict |", "|---|---|---|---|---|---|---|"]
    for v in R.VARIANTS:
        r = arm[v]
        pb = r.get("paired_vs_before")
        d = f"{rs(pb['design']['diff'])} ({pb['design']['p']})" if pb else "-"
        f = f"{rs(pb['final']['diff'])} ({pb['final']['p']})" if pb else "-"
        qs = ", ".join(rs(q["net"]) for q in r["wf_quarters"])
        out.append(f"| {SHORT[v]} | {r['p']} | {r['q']} | {d} | {f} | {qs} | {r['verdict']} |")
    return out


def main():
    s = json.loads((R.RESULTS / "summary.json").read_text())
    L = ["# R64 tables (generated by r64report.py from results/summary.json)", ""]
    for arm in R.ARMS:
        a = s["arms"][arm]
        L += [f"## {arm}", "", f"Decision (PREREG section 5): **{a['decision']['recommended']}**; risk trade-offs "
              f"(lower max DD or worst day at a lower net): {', '.join(a['decision']['tradeoffs']) or 'none'}.", ""]
        for ph, title in PH:
            L += [f"### {arm} - {title}", ""] + table({v: a[v][ph] for v in R.VARIANTS}) + [""]
        L += [f"### {arm} - gates and the paired comparison", ""] + gate_table(a) + [""]
    L += ["## The three together (one lot each, all arms' trades added)", ""]
    for ph, title in PH:
        L += [f"### Together - {title}", ""] + table({v: s["together"][v][ph] for v in R.VARIANTS}) + [""]
    pb = ["| variant | AFTER - BEFORE, design (bootstrap p) | AFTER - BEFORE, final (bootstrap p) |", "|---|---|---|"]
    for v in R.VARIANTS[1:]:
        x = s["together"][v]["paired_vs_before"]
        pb.append(f"| {SHORT[v]} | {rs(x['design']['diff'])} ({x['design']['p']}) | {rs(x['final']['diff'])} "
                  f"({x['final']['p']}) |")
    L += ["### Together - paired comparison", ""] + pb + [""]
    bd = s["boss_day"]
    L += [f"## {bd['day']}", "", "In the lake: " + ("yes" if bd["in_lake"] else "no (the lake ends 13 Oct 2026, 14 Oct "
                                                    "for NIFTY / BANKNIFTY in R57's stores)"), ""]
    (R.RESULTS / "report.md").write_text("\n".join(L))
    return "\n".join(L)


if __name__ == "__main__":
    main()
