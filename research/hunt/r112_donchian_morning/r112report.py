from __future__ import annotations

import json

import yaml

import r112cfg as K

ENTRIES = K.ROOT / "research" / "experiments" / "entries"
DOC = "research/HUNT_R112_DONCHIAN_MORNING.md"
PREREG = "research/hunt/r112_donchian_morning/PREREG.md"
UNDS5 = ["NIFTY", "BANKNIFTY", "FINNIFTY", "MIDCPNIFTY", "SENSEX"]
WHO = {"R72": "R72 Breadth Donchian", "R51": "R51 Donchian 20 + Supertrend", "ALONE": "both arms (each alone, summed)",
       "NOCAP": "both arms in one book, no cap", "CAP2": "both arms in one book, cap of 2 (as the app)"}


def rs(x) -> str:
    if x is None:
        return "-"
    x = round(x)
    s = f"{abs(x):,}"
    # Indian grouping (lakh / crore)
    a = str(abs(x))
    if len(a) > 3:
        head, tail = a[:-3], a[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts) + "," + tail
    return ("-Rs " if x < 0 else "Rs ") + s


def pct(x) -> str:
    return "-" if x is None else f"{100 * x:.0f}%"


def load(name: str):
    p = K.RESULTS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def block(res: dict, who: str, rule: str, period: str):
    if res is None:
        return None
    src = res["arms"] if who in K.ARMS else res["both"]
    return src.get(who, {}).get(rule, {}).get(period)


HEAD = ("| rule | trades | win | needs (own) | net | avg win / loss | green days | worst day | max DD | months <= -13k |\n"
        "|---|---|---|---|---|---|---|---|---|---|")


def row(rule: str, s: dict | None) -> str:
    if not s or not s.get("trades"):
        return f"| {rule} | 0 | - | - | Rs 0 | - | - | - | - | 0 |"
    return (f"| {rule} | {s['trades']:,} | {pct(s['win'])} | {pct(s['be_win'])} | {rs(s['net'])} | "
            f"{rs(s['avg_win'])} / {rs(-s['avg_loss'])} | {pct(s['green_days'])} of {s['days']} | {rs(s['worst_day'])} | "
            f"{rs(s['max_dd'])} | {s['months_below']} of {s['months']} |")


def table(res_by_period: dict, who: str) -> list:
    out = []
    for period, res in res_by_period:
        if res is None:
            continue
        n = res["sessions"] if period != "wf" else None
        out.append(f"\n**{WHO[who]}, {period}**" + (f" ({n} sessions)" if n else "") + "\n\n" + HEAD)
        for rule in K.RULES:
            out.append(row(rule, block(res, who, rule, period)))
    return out


def report() -> str:
    d, f, p = load("design"), load("final"), load("post")
    dec = load("decision")
    pers = [("design", d), ("wf", d), ("final", f), ("post", p)]
    L = ["# R112 results (generated by r112report.py)\n",
         "Rules: " + "; ".join(f"**{r}** = {K.LABEL[r]}" for r in K.RULES) + ".",
         "\n'needs (own)' = the break-even win rate from the rule's own trades: average loss / (average win + average "
         "loss). For +Rs 1,500 / -Rs 1,000 exactly, it is 40%. Green days are of the days with a trade.\n"]
    for who in ("R72", "R51", "ALONE", "CAP2", "NOCAP"):
        L.append(f"\n## {WHO[who]}")
        L += table(pers, who)
    if d:
        L.append("\n## Walk-forward quarters (net; Apr-Jun 2025, Jul-Sep, Oct-Dec, Jan-Mar 2026)\n")
        L.append("| who | " + " | ".join(K.RULES) + " |\n|---|" + "---|" * len(K.RULES))
        for who, qs in d["wf_q"].items():
            L.append(f"| {WHO[who]} | " + " | ".join(" / ".join(rs(x) for x in qs[r]) for r in K.RULES) + " |")
        L.append("\n## Parity\n")
        for ph, res in (("design", d), ("final", f)):
            if res:
                for a, v in res["parity"].items():
                    L.append(f"- {ph} {a}: {v['trades']:,} trades, {rs(v['net'])} (published {v['published']})")
        L.append("\n## Where +Rs 1,500 and -Rs 1,000 sit on a typical premium (B0 design entries, lot of 15 Oct 2026)\n")
        L.append("| index | lot | typical premium | lot value | round-trip charges | +Rs 1,500 needs | -Rs 1,000 is | loss at -15% |\n"
                 "|---|---|---|---|---|---|---|---|")
        for u, v in d["levels"].items():
            L.append(f"| {u} | {v['lot']} | Rs {v['premium']} | {rs(v['lot_value'])} | {rs(v['charges'])} | "
                     f"+{v['target_move_pct']}% | {v['stop_move_pct']}% | {rs(v['loss_at_15pct'])} |")
    if f and dec:
        L.append("\n## Gates (final twins, 100,000 each; BH over 5,829 tests)\n")
        L.append("| arm | rule | entry-twin p | exit-twin p | p | q (all) | q (R112) | passed | why not |\n"
                 "|---|---|---|---|---|---|---|---|---|")
        for a in K.ARMS:
            for r in K.TESTS:
                tw = f["twins"][f"{a}:{r}"]
                g = dec[f"{a}:{r}"]
                L.append(f"| {K.ARM_NAME[a]} | {r} | {tw.get('entry_p', '-')} | {tw.get('exit_p', '-')} | {tw['p']} | "
                         f"{g['q']} | {g['q_r112']} | {'yes' if g['passed'] else 'no'} | {'; '.join(g['fails'])} |")
    for ph, res in (("design", d), ("final", f)):
        if res:
            L.append(f"\n## Exit mix, {ph}\n")
            for a in K.ARMS:
                for r in K.RULES:
                    s = block(res, a, r, ph)
                    if s and s.get("trades"):
                        L.append(f"- {a} {r}: {s['exits']}; largest loss {rs(s['largest_loss'])}")
    return "\n".join(L) + "\n"


def entries():
    d, f, dec = load("design"), load("final"), load("decision")
    n = 0
    for a in K.ARMS:
        for r in K.TESTS:
            g = dec[f"{a}:{r}"]
            sd, sw, sf = (block(d, a, r, "design"), block(d, a, r, "wf"), block(f, a, r, "final"))
            bd, bw, bf = (block(d, a, "B0", "design"), block(d, a, "B0", "wf"), block(f, a, "B0", "final"))

            def line(s):
                return (f"{s['trades']} trades, win {pct(s['win'])} (needs {pct(s['be_win'])}), net {rs(s['net'])}, "
                        f"worst day {rs(s['worst_day'])}, max DD {rs(s['max_dd'])}")

            src = ("index 5-min bars of all five indices (4 of 5 break their Donchian 20 together)" if a == "R72" else
                   "the index's own 5-min bars (Donchian 20 break, Supertrend 10/3 agreeing)")
            e = dict(
                id=f"r112-{a.lower()}-{r.lower()}",
                title=f"R112 {r} on {K.ARM_NAME[a]}: {K.LABEL[r]}",
                family="trade-management",
                date="2026-10-26",
                doc=DOC,
                hypothesis=("Boss (26 Oct): keep both Donchian arms open only till 10 am and exit each order at +Rs 1,500 "
                            f"or -Rs 1,000. This test: {K.LABEL[r]}. Gates: net > 0 and better than today's rules in "
                            "design, walk-forward and final; twin BH q <= 0.10 over 5,829 tests; >= 40 final trades."),
                data_version=("Drive lake gdrive:IraAlgo-data-lake (index_1m, index_daily, options_rolling_1m WEEK) copied "
                              "26 Oct; R51 Amendment A clean stores"),
                period=dict(design="2024-11-20..2026-03-31 (walk-forward window Apr 2025 - Mar 2026)",
                            holdout="2026-04-01..2026-10-13 read once (already read by R51-R111); post 14-19 Oct reported"),
                instruments=UNDS5,
                features=[f"signal source: {src}; the option (1-ITM weekly) is bought; target / stop on its premium"],
                model_or_rule=f"{K.ARM_NAME[a]} with {K.LABEL[r]}",
                settings="research/hunt/r112_donchian_morning/r112cfg.py RULES; PREREG.md section 2",
                prereg=PREREG,
                variants_tried=len(K.ARMS) * len(K.TESTS),
                results=dict(
                    summary=(f"Design: {line(sd)} (today {rs(bd['net'])}). Walk-forward: {line(sw)} (today {rs(bw['net'])}). "
                             f"Final: {line(sf)} (today {rs(bf['net'])}); twin p {g['p']}, BH q {g['q']} (R112 alone "
                             f"{g['q_r112']}). " + ("PASS." if g["passed"] else "Fails: " + "; ".join(g["fails"]) + ".")),
                    costs="dated Zerodha charges, R17 fills (stops -10 bps and 2x the half-spread, gaps at the open), "
                          "limit targets at their price, 1 lot"),
                holdout_read=True,
                verdict="paper-only" if g["passed"] else "rejected",
                notes="Signal on the underlying; nothing changes live.",
            )
            (ENTRIES / f"{e['id']}.yaml").write_text(yaml.safe_dump(e, sort_keys=False, allow_unicode=True, width=120))
            n += 1
    return n


if __name__ == "__main__":
    (K.RESULTS / "report.md").write_text(report())
    if load("decision"):
        print(entries(), "entries")
    print((K.RESULTS / "report.md").read_text()[:3000])
