"""R114 report: results/*.json -> results/report.md (every view, period and the decision; n with every number).

    python research/hunt/r114_donchian_close10/r114report.py
"""
from __future__ import annotations

import json

import r114cfg as K

COLS = ("trades", "win", "net", "avg_win", "avg_loss", "green_days", "worst_day", "max_dd", "months_below",
        "dd_breaches", "days_below")
HEAD = ("trades", "win %", "net Rs", "avg win", "avg loss", "green days %", "worst day", "max DD", "months <= -13k",
        "40k breaches", "days <= -13k")


def rs(x):
    if x is None:
        return "-"
    return f"{x:,.0f}" if isinstance(x, (int, float)) else str(x)


def cell(s: dict, k: str) -> str:
    v = s.get(k)
    if v is None:
        return "-"
    if k in ("win", "green_days"):
        return f"{100 * v:.0f}"
    return rs(v)


def table(rows: list) -> list:
    out = ["| view | period | " + " | ".join(HEAD) + " |", "|---|---|" + "---|" * len(HEAD)]
    for name, per, s in rows:
        out.append(f"| {name} | {per} | " + " | ".join(cell(s, k) for k in COLS) + " |")
    return out


def load(name):
    p = K.RESULTS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def main():
    parts = {n: load(n) for n in ("design", "final", "post")}
    dec = load("decision")
    md = ["# R114 report (generated by r114report.py)", "",
          "Signal source of every rule: the index (R72 breadth Donchian, R51 Donchian 20 + Supertrend, Liquidity's ORB, "
          "R52's open outside value, all on the index's own bars); the 1-ITM weekly option is bought.", ""]
    for rule, lab in K.LABEL.items():
        md.append(f"- **{rule}**: {lab}")
    md.append("")
    for cap in K.CAPS:
        md += [f"## The four-arm book, {cap}", ""]
        rows = []
        for rule in K.RULES:
            for ph, d in parts.items():
                if d is None:
                    continue
                for per, s in d["books"][cap][rule].items():
                    rows.append((rule, per, s))
        md += table(rows) + [""]
    md += ["## Inside the CAP2 book: each arm's real trades and refused entries; Liquidity / R52 trades gained or lost "
           "against BOOK0", "",
           "| rule | period | LIQ real n / net | R72 real n / net | R51 real n / net | R52 real n / net | refused n | "
           "LIQ+R52 gained n / net | LIQ+R52 lost n / net | trades differing from BOOK0 |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for rule in K.RULES:
        for ph, d in parts.items():
            if d is None:
                continue
            for per, s in d["books"]["CAP2"][rule].items():
                a = s["arms"]
                ref = sum(a[x]["refused"]["n"] for x in a)
                g, l_ = s.get("liq_r52_gained"), s.get("liq_r52_lost")
                md.append(f"| {rule} | {per} | " + " | ".join(f"{a[x]['real']['n']} / {rs(a[x]['real']['net'])}"
                                                              for x in K.ARMS)
                          + f" | {ref} | " + (f"{g['n']} / {rs(g['net'])}" if g else "-") + " | "
                          + (f"{l_['n']} / {rs(l_['net'])}" if l_ else "-") + f" | {s.get('changed_vs_book0', '-')} |")
    md += ["", "## Each arm alone (its own research record, no book rules), and R112's two-arm CAP2 view", ""]
    rows = []
    for who in ("R72", "R51", "LIQ", "R52", "R72+R51 CAP2 (R112's view)"):
        for ph, d in parts.items():
            if d is None or who not in d["alone"]:
                continue
            for rule, pers in d["alone"][who].items():
                if rule not in ("BOOK0", "X10"):
                    continue
                for per, s in pers.items():
                    rows.append((f"{who} {rule}", per, s))
    md += table(rows) + [""]
    md += ["## Parity (PREREG section 1)", ""]
    for ph in ("design", "final"):
        d = parts[ph]
        if d:
            for k, v in d["parity"].items():
                md.append(f"- {ph} {k}: {v['trades']} trades, Rs {rs(v['net'])} (R108 published {v['published']}): "
                          f"{'reproduced' if v['reproduced'] else 'NOT reproduced'}")
    md.append("")
    if dec:
        tw = dec["twins"]
        md += ["## Twins and the decision (final, CAP2)", "",
               f"- X10 net Rs {rs(tw['net'])}; refusal twin mean Rs {rs(tw['refusal_mean'])} "
               f"({tw['refusal_removed']} Donchian trades removed), p = {tw['refusal_p']}; exit twin mean "
               f"Rs {rs(tw['exit_mean'])} ({tw['exit_changed']} trades sold earlier by the 10:00 close), p = {tw['exit_p']}",
               f"- p = {dec['p']}, BH q = {dec['q_all']} over m = {dec['m']}; trades differing from BOOK0: "
               f"{tw['changed_vs_book0']}",
               f"- **{'PASSED' if dec['passed'] else 'FAILED'}**" + ("" if dec["passed"] else ": " + "; ".join(dec["fails"])),
               ""]
    (K.RESULTS / "report.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
