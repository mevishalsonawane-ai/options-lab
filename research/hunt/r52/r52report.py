"""results/design.json (+ final.json once read) -> results/report.md: one table per rule, OLD vs NOW (design) vs FINAL."""
from __future__ import annotations

import json

import r52cfg as K

COLS = ("trades", "win", "net", "net/day", "avg win", "avg loss", "worst day", "max DD", "p", "q", "verdict")


def _rs(x):
    return "-" if x is None or x != x else f"{x:+,.0f}"


def row(label, s, q=None, verdict=""):
    if s is None:
        return f"| {label} | " + " | ".join(["-"] * len(COLS)) + " |"
    return (f"| {label} | {s['trades']} | {s['win_rate']:.0%} | {_rs(s['net'])} | {_rs(s['per_day'])} | {_rs(s['avg_win'])} | "
            f"{_rs(s['avg_loss'])} | {_rs(s['worst_day'])} | {_rs(s['max_dd'])} | {s['p']:.3f} | "
            f"{'-' if q is None else f'{q:.2f}'} | {verdict} |")


def _label(key, vid, pre):
    for g in pre.get(key, {}).get("grid", []):
        if g["vid"] == vid:
            return f"{g['params']} · {g['rule']} · exits {g['exits']}"
    return vid


def section(key, d, fin, old, pre=None):
    o = old.get(key, {})
    sp = d["spec"]
    sc = d["scores"]
    pick = d["pick"]
    lines = [f"### {key}: {o.get('title') or sp.get('title') or sp.get('strategy')}", ""]
    lines.append(f"- **Signal source:** {sp.get('source')}. **Original setting:** {sp.get('params')} · {sp.get('rule')} · "
                 f"exits {sp.get('exits')} · expiry {sp.get('expiry')} · {sp.get('pos')}. Why: {sp.get('why')}.")
    lines.append(f"- **Old verdict:** {o.get('old', 'see CATALOGUE.md')}")
    wf = d["wf_orig"]["net"]
    lines.append(f"- **Design walk-forward** (4 quarters Apr 2025 - Mar 2026): original {_rs(wf)}"
                 + (f"; re-tune pick `{pick}` {_rs(d['wf_each'][pick])} (of {d['n_variants'] - 1} grid settings, "
                    f"{sum(1 for v, x in d['wf_each'].items() if v != 'orig' and x > 0)} with walk-forward > 0)" if pick else
                    f"; no grid setting had walk-forward > 0 (of {d['n_variants'] - 1})"))
    if pick:
        lines.append(f"- **Pick's setting:** {d.get('pick_label') or _label(key, pick, pre or {})}")
    lines += ["", "| read | " + " | ".join(COLS) + " |", "|---" * (len(COLS) + 1) + "|"]
    lines.append(row("NOW design, original", sc["orig"], sc["orig"].get("q_design")))
    if pick:
        lines.append(row(f"NOW design, pick {pick}", sc[pick], sc[pick].get("q_design")))
    for vid in ["orig"] + ([pick] if pick else []):
        f = fin.get(f"{key}:{vid}")
        if f is not None:
            lines.append(row(f"FINAL test, {'original' if vid == 'orig' else 'pick ' + vid}", f, f.get("q"),
                             f["gates"]["verdict"]))
    if not fin:
        lines.append("| FINAL test | not read yet |" + " |" * (len(COLS) - 1))
    by = sc["orig"].get("by_und", {})
    if by:
        lines.append("")
        lines.append("Design original by index: " + ", ".join(f"{u} {_rs(v)}" for u, v in sorted(by.items()))
                     + "; by fold: " + ", ".join(_rs(x) for x in sc["orig"]["by_fold"]) + ".")
    return "\n".join(lines) + "\n"


def main():
    d = json.loads((K.RESULTS / "design.json").read_text())
    fp = K.RESULTS / "final.json"
    fin = json.loads(fp.read_text()) if fp.exists() else {}
    old = json.loads((K.RESULTS / "old_verdicts.json").read_text())
    pp = K.RESULTS / "rules_prereg.json"
    pre = json.loads(pp.read_text()) if pp.exists() else {}
    out = ["# R52 results (generated by r52report.py)", ""]
    for key in sorted(d):
        out.append(section(key, d[key], fin, old, pre))
    (K.RESULTS / "report.md").write_text("\n".join(out))
    print(f"report: {len(d)} rules")


if __name__ == "__main__":
    main()
