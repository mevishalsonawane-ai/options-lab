"""R98 report tables: everything in HUNT_R98_HERO_ALL_INDEX.md comes from here.

    python3 -I research/hunt/r98/report.py    # reads $R98_OUT/{days,events,why,rows,scores}.parquet and results/model.json,
                                              # writes results/report.md and results/summary.json
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import r98data as R  # noqa: E402
from rows import EXIT_COLS, EXITS  # noqa: E402

RES = Path(__file__).resolve().parent / "results"
HOLD = "x_inf_0"
SEED = 98


def pct(x, d=0):
    return f"{x * 100:.{d}f}%"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def hhmm(t):
    m = 9 * 60 + 15 + int(t)
    return f"{m // 60:02d}:{m % 60:02d}"


def main():
    days = pd.read_parquet(R.OUT / "days.parquet")
    ev = pd.read_parquet(R.OUT / "events.parquet")
    why = pd.read_parquet(R.OUT / "why.parquet")
    rows = pd.read_parquet(R.OUT / "rows.parquet")
    scores = pd.read_parquet(R.OUT / "scores.parquet")
    model = json.loads((RES / "model.json").read_text())
    S, md = {}, ["# R98 report tables (generated by report.py)\n"]
    order = list(R.UNDS) + ["ALL"]

    # ---------------------------------------------------------------- 1. census by index
    t = []
    for u in order:
        g = days if u == "ALL" else days[days.und == u]
        r = dict(index=u, expiries=len(g), range=f"{g.day.min()} .. {g.day.max()}")
        for k in (5, 10, 20, 33):
            r[f"days >= {k}x"] = pct((g.best_mult >= k).mean())
        r["median best x"] = f"{g.best_mult.median():.1f}"
        r["avg options >= 10x / day"] = f"{g.n10.mean():.2f}"
        t.append(r)
    S["census"] = t
    md += ["## 1. Census: expiry days with some Rs 1-10 option running k× (closes, 10:00 entry .. 15:20)\n",
           md_table(pd.DataFrame(t)), ""]
    days["year"] = pd.to_datetime(days.day).dt.year
    pv = days.pivot_table(index="und", columns="year", values="best_mult",
                          aggfunc=lambda x: f"{(x >= 10).mean() * 100:.0f}% ({len(x)})").reindex(list(R.UNDS))
    md += ["**10× days by year** (share of expiries, expiries in brackets):\n",
           md_table(pv.reset_index(names="index").fillna("-")), ""]

    # ---------------------------------------------------------------- 2. anatomy (top event per day, >= 10x)
    h = ev[ev.mult >= 10]
    top = h.sort_values("mult").groupby(["und", "day"]).tail(1)
    q = lambda s: f"{s.quantile(.25):.2f} / {s.median():.2f} / {s.quantile(.75):.2f}"
    feats = [("entry price Rs", "p0"), ("multiple", "mult"), ("index move %", "move_pct"),
             ("index move in straddles", "move_em"), ("strike distance in straddles", "dist_em"),
             ("strikes OTM", "dist_strikes"), ("straddle % of spot", "em0_pct"), ("minutes to peak", "mins_to_peak"),
             ("minutes at >= half the gain", "mins_half"), ("give-back peak -> 15:20", "giveback"), ("VIX", "vix0")]
    t = []
    for u in order:
        g = top if u == "ALL" else top[top.und == u]
        r = dict(index=u, days=len(g))
        for name, c in feats:
            r[name] = f"{g[c].median():.2f}"
        t.append(r)
    S["anatomy_median"] = t
    md += ["## 2. Anatomy: the biggest hero of each 10× day (medians)\n", md_table(pd.DataFrame(t)), "",
           "Quartiles, all indices (q25 / median / q75):\n"]
    md += [f"- {name}: {q(top[c].astype(float))}" for name, c in feats] + [""]
    b = lambda s: pd.to_datetime(s, format="%H:%M").dt.floor("30min").dt.strftime("%H:%M").value_counts().sort_index()
    tt = pd.DataFrame({"start (cheapest point)": b(top.t0_hhmm), "peak": b(top.t1_hhmm)}).fillna(0).astype(int)
    md += ["**Time of day** (number of 10× days, 30-minute buckets):\n", md_table(tt.reset_index(names="from")), ""]
    S["times"] = tt.to_dict()
    S["end_ge2x"] = float((top.p_end >= 2 * top.p0).mean())
    S["reversal_share"] = float((top.pos0 < 1 / 3).mean())
    md += [f"- At 15:20 the day's best hero was still worth ≥ 2× its start on {pct(S['end_ge2x'])} of 10× days.",
           f"- {pct(S['reversal_share'])} started with the index in the far third of the day's range (a reversal); "
           f"{pct((top.pos0 > 2 / 3).mean())} at the near extreme (a continuation). The start is the cheapest point, "
           "chosen with hindsight, which favours reversals.", ""]

    # ---------------------------------------------------------------- 3. why: realised vs implied
    why["best_em"] = why[["up_em", "dn_em"]].max(axis=1)
    why["hero10"] = why[["best_call", "best_put"]].max(axis=1) >= 10
    why["abs_term"] = why.term_em.abs()
    bins = [0, 1, 1.5, 2, 2.5, 3, 4, 1e9]
    lab = ["< 1", "1-1.5", "1.5-2", "2-2.5", "2.5-3", "3-4", ">= 4"]
    why["bin"] = pd.cut(why.best_em, bins, right=False, labels=lab)
    t = why.groupby("bin", observed=True).agg(cases=("hero10", "size"), hero=("hero10", "mean"))
    t["share of cases"] = (t.cases / len(why)).map(pct)
    t["P(some cheap option 10x)"] = t.hero.map(lambda x: pct(x, 1))
    for side, col, ex in (("calls", "best_call", "up_em"), ("puts", "best_put", "dn_em")):
        t[f"P({side} 10x | move that way)"] = why.groupby(pd.cut(why[ex], bins, right=False, labels=lab),
                                                       observed=True)[col].apply(lambda x: pct((x >= 10).mean(), 1))
    t = t.drop(columns=["hero"]).reset_index(names="best one-way move, in straddles")
    S["why"] = t.to_dict(orient="records")
    S["term_median"] = float(why.abs_term.median())
    S["term_mean"] = float(why.abs_term.mean())
    md += ["## 3. Why: a hero needs the index to move 2.5-3× what the straddle priced\n",
           f"Cases: {len(why)} (expiry day × decision time 11:00, 12:00, 13:00, 13:30, 14:00, 14:30). Straddle = ATM call + "
           f"put at that time. The move to 15:20 in straddle units: terminal |move| median {S['term_median']:.2f}, mean "
           f"{S['term_mean']:.2f}; best one-way excursion median {why.best_em.median():.2f}.\n",
           md_table(t), ""]
    t = why.groupby("tau").agg(cases=("hero10", "size"), hero=("hero10", "mean"), ge2=("best_em", lambda x: (x >= 2).mean()),
                               ge3=("best_em", lambda x: (x >= 3).mean()))
    t = t.assign(hero=t.hero.map(lambda x: pct(x, 1)), ge2=t.ge2.map(pct), ge3=t.ge3.map(pct)).reset_index()
    t.columns = ["time", "cases", "P(10x from cheap options at that time)", "move >= 2 straddles", "move >= 3 straddles"]
    md += [md_table(t), ""]

    # ---------------------------------------------------------------- 4. when: afternoon hero vs morning state
    w13 = why[why.tau == "13:00"].copy()
    w13["hero_pm"] = w13.hero10
    dd = days.merge(w13[["und", "day", "hero_pm", "em_pct"]], on=["und", "day"], how="inner")
    dd["weekday"] = pd.to_datetime(dd.day).dt.strftime("%a")
    base = dd.hero_pm.mean()
    S["pm_base"] = float(base)
    md += ["## 4. When: does the morning tell which afternoon will have a hero?\n",
           f"Afternoon hero = some option cheap (Rs 1-10, OTM) at 13:00 reaches 10× by 15:20. Base rate {pct(base, 1)} of "
           f"{len(dd)} expiry days.\n"]
    specs = [("VIX at the previous close", "vix_prev", [0, 12, 14, 17, 22, 100], ["< 12", "12-14", "14-17", "17-22", ">= 22"]),
             ("opening gap %", "gap_pct", [-10, -1, -0.5, -0.25, 0.25, 0.5, 1, 10],
              ["<= -1", "-1..-0.5", "-0.5..-0.25", "flat", "0.25..0.5", "0.5..1", ">= 1"]),
             ("09:15-13:00 range % of spot", "am_range_pct", [0, 0.4, 0.6, 0.8, 1.1, 10], ["< 0.4", "0.4-0.6", "0.6-0.8", "0.8-1.1", ">= 1.1"]),
             ("13:00 straddle % of spot", "em_pct", [0, 0.15, 0.25, 0.35, 0.5, 10], ["< 0.15", "0.15-0.25", "0.25-0.35", "0.35-0.5", ">= 0.5"]),
             ("weekday", "weekday", None, None), ("monthly expiry", "monthly", None, None), ("index", "und", None, None)]
    S["when"] = {}
    for name, col, bb, ll in specs:
        x = pd.cut(dd[col], bb, labels=ll, right=False) if bb else dd[col]
        g = dd.groupby(x, observed=True).hero_pm.agg(["mean", "size"])
        cells = [f"{k}: {pct(r['mean'])} ({int(r['size'])})" for k, r in g.iterrows()]
        S["when"][name] = {str(k): [float(r["mean"]), int(r["size"])] for k, r in g.iterrows()}
        md.append(f"- **{name}:** " + "; ".join(cells))
    md.append("")

    # ---------------------------------------------------------------- 5. tickets: base rates and the win-rate frontier
    t = []
    for u in order:
        g = rows if u == "ALL" else rows[rows.und == u]
        t.append(dict(index=u, tickets=len(g), days=g.groupby(["und", "day"]).ngroups, **{"P(2x)": pct(g.y2.mean(), 1),
                 "P(5x)": pct(g.y5.mean(), 1), "P(10x)": pct(g.y10.mean(), 1),
                 "held to 15:20: profitable": pct((g[HOLD] > 0).mean(), 1),
                 "held: mean net Rs per Rs 5,000": f"{g[HOLD].mean():,.0f}",
                 "ends near zero": pct(((g.end_px < 0.1 * g.entry) | (g.end_px < 0.10)).mean())}))
    S["tickets"] = t
    md += ["## 5. Tickets: every cheap option every 5 minutes, 11:00-14:55 (no prediction)\n", md_table(pd.DataFrame(t)), ""]
    fr = pd.DataFrame([dict(target="hold" if not np.isfinite(tg) else f"{tg:g}×", stop="none" if st == 0 else f"{st:g}×",
                            win=(rows[c] > 0).mean(), mean=rows[c].mean()) for (tg, st), c in zip(EXITS, EXIT_COLS)])
    win = fr.pivot(index="target", columns="stop", values="win").map(lambda x: pct(x))
    mean = fr.pivot(index="target", columns="stop", values="mean").map(lambda x: f"{x:,.0f}")
    keyo = ["1.1×", "1.2×", "1.3×", "1.5×", "2×", "3×", "5×", "10×", "20×", "hold"]
    keys = ["none", "0.2×", "0.4×", "0.5×", "0.6×", "0.8×"]
    win, mean = win.reindex(index=keyo, columns=keys), mean.reindex(index=keyo, columns=keys)
    S["frontier_max_win"] = float(fr.win.max())
    S["frontier_max_mean"] = float(fr["mean"].max())
    md += ["**Win rate (share of tickets with net P&L > 0)** by target (rows) and stop (columns, × entry):\n",
           md_table(win.reset_index(names="target")), "", "**Mean net Rs per Rs 5,000 ticket:**\n",
           md_table(mean.reset_index(names="target")), "",
           f"Highest win rate of any exit: {pct(S['frontier_max_win'], 1)}; best mean: Rs {S['frontier_max_mean']:,.0f}. "
           "No exit reaches 75% and every exit loses money.", ""]

    # ---------------------------------------------------------------- 6. the 75% test: models
    t = []
    for k in ("hgb_y2", "logit_y2", "hgb_y5", "logit_y5", "hgb_y10", "logit_y10"):
        x = model[k]
        t.append({"model / label": k, "AUC (2023-26)": f"{x['auc_pooled']:.3f}",
                  "base rate": pct(x["base_rate_test"], 1),
                  "top 1%: precision": pct(x["top0.01"]["precision"], 1),
                  "top 5%": pct(x["top0.05"]["precision"], 1),
                  "best threshold (>= 100 picks, 30 days)": f"{pct(x['best_threshold']['precision'], 1)} "
                  f"({x['best_threshold']['picks']} picks, {x['best_threshold']['days']} days)",
                  "one pick per index-day": pct(x["one_per_day"]["precision"], 1),
                  "75%?": "no"})
    S["models"] = t
    md += ["## 6. The pre-registered 75% test: walk-forward models (test years 2023-26)\n", md_table(pd.DataFrame(t)), ""]
    dl = model["day_level"]
    md += [f"Day-level (at 13:00, will any cheap option run 10× by 15:20?): base {pct(dl['hgb']['base'], 1)} of "
           f"{dl['hgb']['days']} days; AUC {dl['hgb']['auc']:.2f} (boosting) and {dl['logit']['auc']:.2f} (logistic), "
           f"below 0.5; best top-decile precision {pct(max(dl['hgb']['top0.1']['precision'], dl['logit']['top0.1']['precision']), 1)}.", ""]
    for name in ("frontier_top10_hgb_y2", "frontier_top10_hgb_y5"):
        f = pd.DataFrame(model[name])
        w = f.loc[f.win.idxmax()]
        md.append(f"- Exit grid on the {name.split('_', 2)[2]} model's top 10% of tickets: highest win rate "
                  f"{pct(w.win, 1)} (target {w.target:g}×, stop {'none' if w.stop != w.stop or w.stop is None else f'{w.stop:g}×'}), which loses Rs {-w.mean_net:,.0f} a "
                  f"ticket; best mean of any exit Rs {f.mean_net.max():,.0f} per Rs 5,000.")
    md.append("")

    # ---------------------------------------------------------------- 7. exploratory: one ticket a day (not pre-registered)
    df = rows.join(scores)
    df["yr"] = pd.to_datetime(df.day).dt.year
    d = df[df.yr >= 2023]
    rng = np.random.default_rng(SEED)
    idx = [np.array(v) for v in d.groupby(["und", "day"]).indices.values()]
    t = []
    for m, col in (("logit_y10", HOLD), ("logit_y10", "x_inf_0.5"), ("hgb_y10", HOLD), ("hgb_y5", HOLD), ("logit_y5", HOLD)):
        top = d.loc[d.groupby(["und", "day"])[m].idxmax()]
        x = top[col].values
        tot = x.sum()
        by = top.groupby(["und", "day"])[col].sum().sort_values(ascending=False)
        boot = [rng.choice(x, len(x)).mean() for _ in range(2000)]
        vals = d[col].values
        ctrl = np.array([np.mean([vals[rng.choice(i)] for i in idx]) for _ in range(300)])
        t.append({"pick": m, "exit": "hold to 15:20" if col == HOLD else "hold, -50% stop (best of 60, post hoc)",
                  "tickets": len(x), "mean net Rs": f"{x.mean():,.0f}",
                  "bootstrap 95%": f"{np.percentile(boot, 2.5):,.0f} .. {np.percentile(boot, 97.5):,.0f}",
                  "without the 5 best days": f"{(tot - by.head(5).sum()) / len(x):,.0f}",
                  "years > 0 (of 4)": int((top.groupby("yr")[col].sum() > 0).sum()),
                  "random pick, same days": f"{ctrl.mean():,.0f}", "hit 10x": pct(top.y10.mean(), 1)})
    S["one_per_day"] = t
    md += ["## 7. Exploratory, not pre-registered: one ticket per index-day, the model's top-scored option\n",
           md_table(pd.DataFrame(t)), "",
           "The model's daily pick is the nearest cheap strike (median entry Rs "
           f"{d.loc[d.groupby(['und', 'day']).logit_y10.idxmax()].entry.median():.2f}, about 2 strikes OTM), not a "
           "lottery ticket.", ""]

    # ---------------------------------------------------------------- 8. the zero side
    z = rows.assign(lossx=(rows.end_px - rows.entry) / rows.entry)
    S["zero"] = dict(below_entry=float((z.end_px < z.entry).mean()), **{f"ge{k}x": float((z.lossx >= k).mean()) for k in (1, 2, 5, 9, 19)},
                     doubles_intraday=float((z.best_mult >= 2).mean()), worst=float(z.lossx.max()))
    md += ["## 8. The zero side (a mirror, not a tested strategy)\n",
           f"- {pct(S['zero']['below_entry'], 1)} of cheap-option snapshots end (15:20) below the price paid.",
           f"- {pct(S['zero']['ge1x'], 2)} end at ≥ 2× (a seller loses ≥ 1× the premium), {pct(S['zero']['ge9x'], 2)} at ≥ 10×, "
           f"{pct(S['zero']['ge19x'], 2)} at ≥ 20×; the worst ends at {S['zero']['worst']:.0f}× the premium lost.",
           f"- {pct(S['zero']['doubles_intraday'], 1)} double at some minute before 15:20.", ""]

    # ---------------------------------------------------------------- 9. 13 Oct 2026
    x = rows[(rows.und == "NIFTY") & (rows.day == pd.Timestamp("2026-10-13").date()) & (rows.t == R.minute(13, 30))]
    x = x.sort_values(["side", "strike"])[["side", "strike", "entry", "best_mult", "end_px", HOLD, "f_r15", "f_stx"]]
    x.columns = ["side", "strike", "entry Rs", "best x", "15:20 Rs", "held net Rs / 5k", "15-min move to its side %",
                 "straddle vs its low"]
    x["held net Rs / 5k"] = x["held net Rs / 5k"].map(lambda v: f"{v:,.0f}")
    md += ["## 9. NIFTY 13 Oct 2026 at 13:30 (now in the lake)\n", md_table(x.round(2)), ""]
    S["oct13"] = x.round(2).to_dict(orient="records")

    RES.mkdir(exist_ok=True)
    (RES / "report.md").write_text("\n".join(md) + "\n")
    (RES / "summary.json").write_text(json.dumps(S, indent=1, default=str))
    print("written", RES / "report.md")


if __name__ == "__main__":
    main()
