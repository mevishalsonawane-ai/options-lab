"""R98e Part A (PREREG_E section 2): does the new information improve R98's walk-forward model?

    python3 -I research/hunt/r98/model_e.py     # -> results/model_e.json, results/model_e.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

sys.path.insert(0, str(Path(__file__).resolve().parent))
import r98data as R  # noqa: E402
from model import hgb, TEST_YEARS  # noqa: E402
from features_e import NEW  # noqa: E402
from hero2 import md_table, pct, rs  # noqa: E402

RES = Path(__file__).resolve().parent / "results"
KEYS = ["und", "day", "t", "strike", "side"]
SEED = 98


def load():
    rows = pd.read_parquet(R.OUT / "rows.parquet")
    fe = pd.read_parquet(R.OUT / "feat_e.parquet")
    df = rows.merge(fe, on=KEYS, how="left", validate="one_to_one")
    df["yr"] = pd.to_datetime(df.day).dt.year
    return df


def run(df, feats, label, perm=False):
    score = pd.Series(np.nan, index=df.index)
    imp = {f: [] for f in NEW} if perm else None
    rng = np.random.default_rng(SEED)
    for y in TEST_YEARS:
        tr, te = df[df.yr < y], df[df.yr == y]
        m = hgb()
        m.fit(tr[feats].values, tr[label].values.astype(int))
        s = m.predict_proba(te[feats].values)[:, 1]
        score.loc[te.index] = s
        if perm:
            base = roc_auc_score(te[label].astype(int), s)
            X = te[feats].values.copy()
            for f in NEW:
                j = feats.index(f)
                Xp = X.copy()
                Xp[:, j] = rng.permutation(Xp[:, j])
                imp[f].append(base - roc_auc_score(te[label].astype(int), m.predict_proba(Xp)[:, 1]))
    return score, ({f: float(np.mean(v)) for f, v in imp.items()} if perm else None)


def summary(df, s, label):
    d = df.assign(s=s).dropna(subset=["s"])
    top = d[d.s >= d.groupby("yr").s.transform(lambda x: x.quantile(0.99))]
    one = d.loc[d.groupby(["und", "day"]).s.idxmax()]
    by = one.groupby(["und", "day"]).x_inf_0.sum().sort_values(ascending=False)
    return dict(auc=float(roc_auc_score(d[label].astype(int), d.s)),
                auc_by_year={int(y): float(roc_auc_score(g[label].astype(int), g.s)) for y, g in d.groupby("yr")},
                top1=float(top[label].mean()), one_prec=float(one[label].mean()),
                one_hold=float(one.x_inf_0.mean()), one_stop20=float(one["x_inf_0.8"].mean()),
                one_hold_wo5=float((one.x_inf_0.sum() - by.head(5).sum()) / len(one)), one_n=len(one),
                one_years_pos=int((one.groupby("yr").x_inf_0.sum() > 0).sum()))


def main():
    df = load()
    base = [c for c in df.columns if c.startswith("f_")]
    full = base + NEW
    S, md = {}, ["# R98e Part A: does the new information improve the walk-forward model? (generated by model_e.py)\n"]
    md.append(f"Rows {len(df):,}; new features present: " +
              ", ".join(f"{f} {pct(df[f].notna().mean())}" for f in NEW) + "\n")
    t = []
    for label in ("y5", "y10"):
        sb, _ = run(df, base, label)
        sf, imp = run(df, full, label, perm=True)
        a, b = summary(df, sb, label), summary(df, sf, label)
        S[label] = dict(base=a, full=b, importance=imp)
        for name, x in (("R98 features", a), ("R98 + new", b)):
            t.append({"label": label, "features": name, "AUC 2023-26": f"{x['auc']:.3f}", "top 1% precision": pct(x["top1"], 1),
                      "one/day precision": pct(x["one_prec"], 1), "one/day held Rs": rs(x["one_hold"]),
                      "one/day -20% stop Rs": rs(x["one_stop20"]), "one/day held w/o 5 best days": rs(x["one_hold_wo5"]),
                      "years > 0": f"{x['one_years_pos']}/4"})
        print(label, json.dumps({k: v for k, v in b.items() if k != "auc_by_year"}), flush=True)
    md += [md_table(pd.DataFrame(t)), ""]
    for label in ("y5", "y10"):
        imp = sorted(S[label]["importance"].items(), key=lambda z: -z[1])
        md += [f"Permutation importance of the new features ({label}; AUC drop when shuffled, test years mean):\n",
               md_table(pd.DataFrame([dict(feature=f, auc_drop=f"{v:+.4f}") for f, v in imp])), ""]
    RES.mkdir(exist_ok=True)
    (RES / "model_e.md").write_text("\n".join(md) + "\n")
    (RES / "model_e.json").write_text(json.dumps(S, indent=1, default=str))
    print("\n".join(md))


if __name__ == "__main__":
    main()
