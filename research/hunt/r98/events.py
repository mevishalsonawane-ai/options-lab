"""R98d (PREREG_D.md): hero-zero on event days. Reads events.csv and R98's tables; simulates the M6 event basket.

    python3 -I research/hunt/r98/events.py     # -> results/events.md, results/events.json
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import fisher_exact, mannwhitneyu

sys.path.insert(0, str(Path(__file__).resolve().parent))
import r98data as R  # noqa: E402
import r98lib as L  # noqa: E402
from hero2 import md_table, pct, pick_near5, rs, ticket  # noqa: E402

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
GROUPS = {"RBI": ["RBI"], "BUDGET": ["BUDGET"], "ELECTION": ["ELECTION"], "FOMC": ["FOMC"], "USCPI": ["USCPI"],
          "DOMESTIC": ["RBI", "BUDGET", "ELECTION"], "US": ["FOMC", "USCPI"], "ANY": ["RBI", "BUDGET", "ELECTION", "FOMC", "USCPI"]}
ENTRY = {"RBI": (9, 55), "BUDGET": (10, 55), "ELECTION": (9, 20), "FOMC": (9, 20), "USCPI": (9, 20)}
M6_EXITS = ("B_hold", "B_stop20", "E1_half2x_s0.5")
PRIORITY = ["ELECTION", "BUDGET", "RBI", "FOMC", "USCPI"]       # an index-day hit by several events takes the first
SEED = 98


def bh(p: list[float]) -> list[float]:
    p = np.asarray(p, float)
    n = len(p)
    o = np.argsort(p)
    q = np.empty(n)
    run = 1.0
    for i in range(n - 1, -1, -1):
        run = min(run, p[o[i]] * n / (i + 1))
        q[o[i]] = run
    return q.tolist()


def labels() -> pd.DataFrame:
    ev = pd.read_csv(HERE / "events.csv")
    out = {}
    for _, r in ev.iterrows():
        out.setdefault(r.session, set()).add(r.category)
    return out


def main():
    ev = labels()
    days = pd.read_parquet(R.OUT / "days.parquet")
    days["key"] = days.day.astype(str)
    days["cats"] = days.key.map(lambda k: ev.get(k, set()))
    why = pd.read_parquet(R.OUT / "why.parquet")
    why["best_em"] = why[["up_em", "dn_em"]].max(axis=1)
    why["hero"] = why[["best_call", "best_put"]].max(axis=1) >= 10
    w11 = why[why.tau == "11:00"].set_index(["und", "day"])
    w13 = why[why.tau == "13:00"].set_index(["und", "day"])
    d = days.set_index(["und", "day"])
    d["m1"] = d.best_mult >= 10
    d["m2"] = w13.hero.reindex(d.index)
    d["em11"], d["em13"] = w11.em_pct.reindex(d.index), w13.em_pct.reindex(d.index)
    d["mv11"], d["mv13"] = w11.best_em.reindex(d.index), w13.best_em.reindex(d.index)
    d = d.reset_index()
    rows = pd.read_parquet(R.OUT / "rows.parquet", columns=["und", "day", "y10", "x_inf_0", "x_inf_0.8"])
    rows["key"] = rows.day.astype(str)
    S, md = {}, ["# R98d: hero-zero on event days (generated by events.py)\n"]
    md += [f"Calendar: `events.csv` ({sum(1 for _ in open(HERE / 'events.csv')) - 1} events, with sources). Expiry-index-days in "
           f"the study: {len(d)}.\n"]
    # ---------------------------------------------------------------- M1-M5
    tab, pv = [], []
    for g, cats in GROUPS.items():
        m = d.cats.map(lambda s: bool(s & set(cats)))
        e, o = d[m], d[~m]
        if not len(e):
            continue
        rk = rows.key.isin({k for k, s in ev.items() if s & set(cats)})
        er, orr = rows[rk & rows.und.isin(e.und.unique())], rows[~rk]
        p1 = fisher_exact([[int(e.m1.sum()), int((~e.m1).sum())], [int(o.m1.sum()), int((~o.m1).sum())]])[1]
        e2, o2 = e.m2.dropna().astype(bool), o.m2.dropna().astype(bool)
        p2 = fisher_exact([[int(e2.sum()), int((~e2).sum())], [int(o2.sum()), int((~o2).sum())]])[1]
        p3 = mannwhitneyu(e.mv13.dropna(), o.mv13.dropna()).pvalue if e.mv13.notna().sum() > 2 else 1.0
        pv += [p1, p2, p3]
        tab.append({"group": g, "expiry-index-days": len(e),
                    "M1 hero day (event / other)": f"{pct(e.m1.mean())} / {pct(o.m1.mean())}",
                    "M2 afternoon hero": f"{pct(e2.mean())} / {pct(o2.mean())}",
                    "M3 move at 13:00, straddles (median)": f"{e.mv13.median():.2f} / {o.mv13.median():.2f}",
                    "M3 share >= 2.5": f"{pct((e.mv13 >= 2.5).mean())} / {pct((o.mv13 >= 2.5).mean())}",
                    "M4 straddle % of spot 11:00": f"{e.em11.median():.2f} / {o.em11.median():.2f}",
                    "M5 P(10x) a ticket": f"{pct(er.y10.mean(), 1)} / {pct(orr.y10.mean(), 1)}",
                    "M5 held, Rs per 5k": f"{rs(er.x_inf_0.mean())} / {rs(orr.x_inf_0.mean())}",
                    "M5 -20% stop": f"{rs(er['x_inf_0.8'].mean())} / {rs(orr['x_inf_0.8'].mean())}",
                    "_p": (p1, p2, p3)})
    q = bh(pv)
    for i, t in enumerate(tab):
        p1, p2, p3 = t.pop("_p")
        t["p (M1 / M2 / M3)"] = f"{p1:.2f} / {p2:.2f} / {p3:.2f}"
        t["BH q (min)"] = f"{min(q[3 * i:3 * i + 3]):.2f}"
    S["metrics"] = tab
    S["bh_min"] = float(min(q)) if q else None
    md += ["## M1-M5: event expiry-index-days against all other expiry-index-days (event / other)\n", md_table(pd.DataFrame(tab)),
           "", f"Smallest BH q over the 24 tests: {min(q):.2f}. A finding needs q < 0.05.", ""]
    # per-event list for the domestic events (small enough to show)
    dom = d[d.cats.map(lambda s: bool(s & set(GROUPS["DOMESTIC"])))].sort_values("day")
    lst = [{"day": str(r.day), "index": r.und, "event": ",".join(sorted(r.cats)), "best x (10:00-15:20)": f"{r.best_mult:.1f}",
            "move at 11:00 (straddles)": f"{r.mv11:.2f}" if r.mv11 == r.mv11 else "-",
            "straddle % 11:00": f"{r.em11:.2f}" if r.em11 == r.em11 else "-"} for _, r in dom.iterrows()]
    S["domestic_days"] = lst
    md += ["### Every domestic-event expiry-index-day\n", md_table(pd.DataFrame(lst)), ""]
    # ---------------------------------------------------------------- M6 event basket
    tickets = []
    for u in R.UNDS:
        for day in R.load(u):
            cats = ev.get(str(day.day))
            if not cats:
                continue
            cat = next(c for c in PRIORITY if c in cats)
            hh, mm = ENTRY[cat]
            t = R.minute(hh, mm)
            sp = L.spot(day)
            em, _ = L.straddle(day)
            if np.isnan(sp[t]):
                continue
            for s, k in pick_near5(day, t, sp[t]).items():
                x = ticket(day, k, s, t, em[t] if not np.isnan(em[t]) else np.nan, "M6", dict(cat=cat))
                if x:
                    tickets.append(x)
    tk = pd.DataFrame(tickets)
    tk["yr"] = pd.to_datetime(tk.day).dt.year
    rng = np.random.default_rng(SEED)
    t6 = []
    for g, cats in (("DOMESTIC", GROUPS["DOMESTIC"]), ("US", GROUPS["US"]), ("ANY", GROUPS["ANY"])) + tuple(
            (c, [c]) for c in ("RBI", "FOMC", "USCPI")):
        h = tk[tk.cat.isin(cats)]
        for x in M6_EXITS:
            v = h[x].values
            by = h.groupby(["und", "day"])[x].sum().sort_values(ascending=False)
            cnt = h.groupby(["und", "day"]).size().reindex(by.index).values
            bs = [by.values[i].sum() / cnt[i].sum() for i in (rng.integers(0, len(by), len(by)) for _ in range(2000))]
            lo95, hi95 = np.percentile(bs, 2.5), np.percentile(bs, 97.5)
            wo3 = (v.sum() - by.head(3).sum()) / len(v)
            yrs = h.groupby("yr")[x].sum()
            ok = v.mean() > 0 and lo95 > 0 and wo3 > 0 and (yrs > 0).all()
            t6.append({"group": g, "exit": x, "tickets": len(v), "days": len(by), "win": pct((v > 0).mean(), 1),
                       "mean Rs": rs(v.mean()), "bootstrap 95%": f"{rs(lo95)} .. {rs(hi95)}", "w/o 3 best days": rs(wo3),
                       "years > 0": f"{int((yrs > 0).sum())}/{len(yrs)}", "P(10x)": pct((h.best_mult >= 10).mean(), 1),
                       "passes": "YES" if ok else "no"})
    S["m6"] = t6
    md += ["## M6: the event lottery basket (CE + PE nearest Rs 5, bought just before the event or at 09:20)\n",
           md_table(pd.DataFrame(t6)), ""]
    best = tk.sort_values("B_hold", ascending=False).head(8)
    lst = [{"day": str(r.day), "index": r.und, "event": r["cat"], "option": f"{int(r.strike)} {'CE' if r.side == 'C' else 'PE'}",
            "entry": f"{r.entry:.2f}", "best x": f"{r.best_mult:.1f}", "held Rs": rs(r.B_hold)} for _, r in best.iterrows()]
    S["m6_best"] = lst
    md += ["The basket's 8 best tickets:\n", md_table(pd.DataFrame(lst)), ""]
    RES.mkdir(exist_ok=True)
    (RES / "events.md").write_text("\n".join(md) + "\n")
    (RES / "events.json").write_text(json.dumps(S, indent=1, default=str))
    print("\n".join(md))


if __name__ == "__main__":
    main()
