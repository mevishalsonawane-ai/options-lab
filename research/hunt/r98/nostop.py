"""R98 follow-up (Boss, 21 Oct 2026: "What if we remove stoploss"): the same tickets with no stop, compared with stops.

    python3 -I research/hunt/r98/nostop.py     # writes results/nostop.md and results/nostop.json

Adds one exit the main study did not have: hold to expiry SETTLEMENT (no 15:20 square-off). The option is worth its
intrinsic value at the index's official close (lake index_daily), on which NSE/BSE settle index options; an option
settling under Rs 0.10 is worthless. Settlement is charged like a sale with no spread (Rs 20 + GST, STT 0.15%
of the value, exchange fees), which is conservative: the real exercise STT and broker fees differ by broker.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import r98data as R  # noqa: E402
import r98lib as L  # noqa: E402

RES = Path(__file__).resolve().parent / "results"
TARGETS = ["1.1", "1.2", "1.5", "2", "3", "5", "10", "20", "inf"]
STOPS = ["0", "0.8", "0.5", "0.2"]   # none, -20%, -50%, -80% (a stop at 0.8x / 0.5x / 0.2x the entry)
NAMES = {"0": "no stop", "0.8": "-20% stop", "0.5": "-50% stop", "0.2": "-80% stop"}


def pct(x, d=0):
    return f"{x * 100:.{d}f}%"


def rs(x):
    return f"{x:,.0f}"


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for _, r in df.iterrows()]
    return "\n".join(out)


def settle_close() -> dict:
    """(und, day) -> the index's OFFICIAL close (lake index_daily; NSE/BSE settle index options on it). The validated
    Dhan daily closes match NSE's official closes on 99.6-100% of sampled days (research/data/VALIDATION.md)."""
    d = pd.read_parquet(R.LAKE / "index_daily.parquet")
    d = d[d.symbol.isin(R.UNDS)]
    return {(u, pd.Timestamp(t).date()): float(c) for u, t, c in zip(d.symbol, d.date, d.close)}


def settle_pnl(df: pd.DataFrame) -> np.ndarray:
    cl = settle_close()
    s = np.array([cl.get((u, d), np.nan) for u, d in zip(df.und, df.day)])
    intr = np.where(df.side.values == "C", np.maximum(s - df.strike.values, 0.0), np.maximum(df.strike.values - s, 0.0))
    # net_pnl sells at price - 1 tick; settlement has no spread, so pass intrinsic + tick (and < 0.10 = worthless)
    px = np.where(intr < 0.10, 0.0, intr + L.TICK)
    return np.array([L.net_pnl(u, e, p) for u, e, p in zip(df.und.values, df.entry.values, px)])


def stats(x: np.ndarray, entry_budget=L.BUDGET) -> dict:
    return dict(win=float((x > 0).mean()), mean=float(x.mean()), median=float(np.median(x)),
                p05=float(np.percentile(x, 5)), lose90=float((x <= -0.9 * entry_budget).mean()))


def main():
    cols = ["und", "day", "t", "strike", "side", "entry"] + [f"x_{t}_{s}" for t in TARGETS for s in STOPS]
    df = pd.read_parquet(R.OUT / "rows.parquet", columns=cols)
    df["settle"] = settle_pnl(df)
    sc = pd.read_parquet(R.OUT / "scores.parquet", columns=["hgb_y2", "logit_y10"])
    df = df.join(sc)
    df["yr"] = pd.to_datetime(df.day).dt.year
    S, md = {}, ["# R98 follow-up: what if we remove the stop-loss? (generated by nostop.py)\n"]

    # A. pooled grid: every target, no stop vs -50% vs -80%, plus settlement
    t = []
    for tg in TARGETS:
        r = {"target": "hold to 15:20" if tg == "inf" else f"{tg}×"}
        for s in STOPS:
            st = stats(df[f"x_{tg}_{s}"].values)
            r[f"{NAMES[s]}: win"] = pct(st["win"], 1)
            r[f"{NAMES[s]}: mean Rs"] = rs(st["mean"])
        t.append(r)
    st = stats(df.settle.values)
    t.append({"target": "hold to expiry settlement", "no stop: win": pct(st["win"], 1), "no stop: mean Rs": rs(st["mean"]),
              **{f"{NAMES[s]}: {k}": "-" for s in STOPS[1:] for k in ("win", "mean Rs")}})
    S["grid"] = t
    md += ["## A. All 394,956 tickets (Rs 5,000 each, all five indices, 2021-26)\n", md_table(pd.DataFrame(t)), ""]

    # B. the shape of a no-stop ticket
    t = []
    for name, col in (("no stop, hold to 15:20", "x_inf_0"), ("no stop, hold to settlement", "settle"),
                      ("no stop, sell at 2×", "x_2_0"), ("-20% stop, hold to 15:20", "x_inf_0.8"),
                      ("-50% stop, hold to 15:20", "x_inf_0.5"),
                      ("-80% stop, hold to 15:20", "x_inf_0.2")):
        st = stats(df[col].values)
        t.append({"exit": name, "win": pct(st["win"], 1), "mean Rs": rs(st["mean"]), "median Rs": rs(st["median"]),
                  "worst 5% (Rs)": rs(st["p05"]), "lose >= 90% of the ticket": pct(st["lose90"])})
    S["shape"] = t
    md += ["## B. What a ticket looks like with and without the stop\n", md_table(pd.DataFrame(t)), ""]

    # C. what the stop costs: tickets that fell through the stop and still reached the target
    t = []
    for tg in ("1.1", "1.5", "2", "5", "10"):
        w0 = (df[f"x_{tg}_0"] > 0).mean()
        for s in ("0.8", "0.5", "0.2"):
            ws = (df[f"x_{tg}_{s}"] > 0).mean()
            t.append({"target": f"{tg}×", "stop": NAMES[s], "win without stop": pct(w0, 1), "win with stop": pct(ws, 1),
                      "tickets the stop 'killed' (fell through it, then hit the target)": pct(w0 - ws, 1),
                      "mean Rs without stop": rs(df[f"x_{tg}_0"].mean()), "mean Rs with stop": rs(df[f"x_{tg}_{s}"].mean())})
    S["recovery"] = t
    md += ["## C. How many winners does the stop kill, and what does it save?\n", md_table(pd.DataFrame(t)), ""]

    # D. per index
    t = []
    for u in list(R.UNDS) + ["ALL"]:
        g = df if u == "ALL" else df[df.und == u]
        t.append({"index": u, "tickets": len(g),
                  "no stop, 15:20: win / mean": f"{pct((g.x_inf_0 > 0).mean(), 1)} / {rs(g.x_inf_0.mean())}",
                  "no stop, settlement: win / mean": f"{pct((g.settle > 0).mean(), 1)} / {rs(g.settle.mean())}",
                  "no stop, 2× target: win / mean": f"{pct((g.x_2_0 > 0).mean(), 1)} / {rs(g.x_2_0.mean())}",
                  "-50% stop, 15:20: win / mean": f"{pct((g['x_inf_0.5'] > 0).mean(), 1)} / {rs(g['x_inf_0.5'].mean())}",
                  "-20% stop, 15:20: win / mean": f"{pct((g['x_inf_0.8'] > 0).mean(), 1)} / {rs(g['x_inf_0.8'].mean())}"})
    S["by_index"] = t
    md += ["## D. By index\n", md_table(pd.DataFrame(t)), ""]

    # E. by year, no stop held to 15:20 and settlement
    t = []
    for y, g in df.groupby("yr"):
        t.append({"year": int(y), "tickets": len(g), "no stop 15:20: mean": rs(g.x_inf_0.mean()),
                  "settlement: mean": rs(g.settle.mean()), "-50% stop: mean": rs(g["x_inf_0.5"].mean()),
                  "-20% stop: mean": rs(g["x_inf_0.8"].mean())})
    S["by_year"] = t
    md += ["## E. By year (mean net Rs per Rs 5,000 ticket)\n", md_table(pd.DataFrame(t)), ""]

    # F. the model's picks (test years 2023-26 only)
    d = df[df.yr >= 2023]
    top10 = d[d.hgb_y2 >= d.groupby("yr").hgb_y2.transform(lambda x: x.quantile(0.9))]
    one = d.loc[d.groupby(["und", "day"]).logit_y10.idxmax()]
    t = []
    for name, g in (("model's top 10% (2x model)", top10), ("one ticket per index-day (10x model)", one)):
        for ex, col in (("no stop, 15:20", "x_inf_0"), ("no stop, settlement", "settle"), ("-50% stop, 15:20", "x_inf_0.5"),
                        ("-20% stop, 15:20", "x_inf_0.8"), ("no stop, 2× target", "x_2_0"), ("-50% stop, 2× target", "x_2_0.5")):
            x = g[col].values
            by = g.groupby(["und", "day"])[col].sum().sort_values(ascending=False)
            t.append({"tickets": f"{name} ({len(g)})", "exit": ex, "win": pct((x > 0).mean(), 1), "mean Rs": rs(x.mean()),
                      "mean without the 5 best days": rs((x.sum() - by.head(5).sum()) / len(x)),
                      "years > 0 (of 4)": int((g.groupby("yr")[col].sum() > 0).sum())})
    S["models"] = t
    md += ["## F. The model's picks, test years 2023-26 (post hoc: R98's models were not built to choose an exit)\n",
           md_table(pd.DataFrame(t)), ""]

    # G. 13 Oct 2026, NIFTY, 13:30 tickets
    x = df[(df.und == "NIFTY") & (df.day == pd.Timestamp("2026-10-13").date()) & (df.t == R.minute(13, 30))]
    x = x.sort_values(["side", "strike"])
    t = [{"option": f"{int(r.strike)} {'CE' if r.side == 'C' else 'PE'}", "entry Rs": f"{r.entry:.2f}",
          "no stop, 15:20": rs(r.x_inf_0), "no stop, settlement": rs(r.settle), "-50% stop, 15:20": rs(r["x_inf_0.5"])}
         for _, r in x.iterrows()]
    S["oct13"] = t
    md += ["## G. NIFTY 13 Oct 2026, tickets bought at 13:30\n", md_table(pd.DataFrame(t)), ""]

    RES.mkdir(exist_ok=True)
    (RES / "nostop.md").write_text("\n".join(md) + "\n")
    (RES / "nostop.json").write_text(json.dumps(S, indent=1, default=str))
    print("\n".join(md))


if __name__ == "__main__":
    main()
