"""R107 report and experiment entries from results/design.json, final.json and decision.json.

    python research/hunt/r107_meters_more/r107report.py          # results/report.md + research/experiments/entries/r107-*.yaml
    python research/experiments/validate.py
"""
from __future__ import annotations

import json

import yaml

import r107cfg as K

ENTRIES = K.ROOT / "research" / "experiments" / "entries"
DOC = "research/HUNT_R107_METERS_MORE.md"
PREREG = "research/hunt/r107_meters_more/PREREG.md"
PNAME = {"design": "design (20 Nov 2024 - 31 Mar 2026)", "wf": "walk-forward window (Apr 2025 - Mar 2026)",
         "final": "final (1 Apr - 13 Oct 2026, read once)"}
SRC = {"LIQ": ("index 15/30-min + 5-min bars (liquidity pool breaks)", ["BANKNIFTY", "FINNIFTY", "MIDCPNIFTY"]),
       "R72": ("index 5-min bars of all five indices (Donchian 20, 4 of 5 break)", list(K.UNDS)),
       "R51": ("index 5-min bars (Donchian 20)", list(K.UNDS)),
       "R52": ("index first 5-min bar + previous day's value area", list(K.UNDS)),
       "BOOK": ("the four arms' own index signals", list(K.UNDS))}


def rs(x) -> str:
    if x is None:
        return "-"
    x = round(x)
    return f"-Rs {abs(x):,}" if x < 0 else f"Rs {x:,}"


def fx(x) -> str:
    return "inf" if x is None else f"{x:.2f}"


def load():
    d = json.loads((K.RESULTS / "design.json").read_text())
    f = json.loads((K.RESULTS / "final.json").read_text())
    dec = json.loads((K.RESULTS / "decision.json").read_text())
    return {"design": d["design"], "wf": d["wf"], "final": f["final"]}, dec


def row(t: str, r: dict) -> str:
    v, b, a, m = r["variant"], r["base"], r["always"], r["twin_median"]
    return (f"| {t} | {v['trades']:,} ({v['changed']:,}) | {rs(v['net'])} | {rs(b['net'])} | {rs(a['net'])} | "
            f"{fx(v['r_dd'])} / {fx(b['r_dd'])} / {fx(a['r_dd'])} / {fx(m['r_dd'])} | "
            f"{fx(v['r_wd'])} / {fx(b['r_wd'])} / {fx(a['r_wd'])} / {fx(m['r_wd'])} | {rs(v['max_dd'])} ({rs(b['max_dd'])}) | "
            f"{rs(v['worst_day'])} ({rs(b['worst_day'])}) | {v['months_below']}/{v['months']} ({b['months_below']}) | "
            f"{v['twin_p']} |")


def report(P: dict, dec: dict) -> str:
    out = ["# R107 report (generated by r107report.py)", "",
           "Columns: n = trades (in brackets: trades sized up, or new positions for G3 / D3); net of the variant, today "
           "(B1, 1 lot) and 'always' (A2 = every trade 2 lots; A3 = cap 3 every day for G3 / D3); ratios variant / "
           "today / always / twins' median; max DD and worst day (today in brackets); months at or below -Rs 13,000 "
           "(today in brackets); twin p (net / max DD, 10,000 random-day twins).", ""]
    for p in K.PERIODS:
        out += [f"## {PNAME[p]}", "",
                "| test | n (changed) | net | today | always | net / max DD | net / worst day | max DD | worst day | "
                "months <= -13k | twin p |", "|" + "---|" * 11]
        out += [row(t, P[p][t]) for t in K.TEST_IDS]
        out.append("")
    out += ["## Decision (BH over 11 + 573 earlier tests = 584)", "", "| test | final twin p | q (584) | q (R107) | passes | "
            "first failures |", "|---|---|---|---|---|---|"]
    for t in K.TEST_IDS:
        g = dec[t]
        out.append(f"| {t} | {g['twin_p']} | {g['q_all']} | {g['q_r107']} | {'yes' if g['passed'] else 'no'} | "
                   f"{'; '.join(g['fails'][:3])} ({len(g['fails'])} in all) |")
    out += ["", "## What the meters tell (descriptive, 1 lot)", ""]
    for p in K.PERIODS:
        x = P[p]["_describe"]
        out += [f"### {PNAME[p]}", "", f"Danger levels: {x['_danger_levels']}. Negative-GEX sessions per index (09:20 / "
                "10:00 of n): " + ", ".join(f"{u} {v['neg_0920']} / {v['neg_1000']} of {v['sessions']}"
                                            for u, v in x["_gex_share"].items()), "",
                "| arm | GEX < 0: n, per trade, win | GEX >= 0: n, per trade, win | flagged days: days, n, per trade, per day, "
                "worst day | normal days: days, n, per trade, per day, worst day |", "|---|---|---|---|---|"]
        for a in K.ARMS + ("BOOK",):
            y = x[a]
            g1, g2, d1, d2 = y["gex_neg"], y["gex_other"], y["danger_flagged"], y["danger_normal"]
            out.append(f"| {a} | {g1['n']}, {rs(g1['per_trade'])}, {g1['win']} | {g2['n']}, {rs(g2['per_trade'])}, {g2['win']} | "
                       f"{d1['sessions']}, {d1['n']}, {rs(d1['per_trade'])}, {rs(d1['per_session'])}, {rs(d1['worst_day'])} | "
                       f"{d2['sessions']}, {d2['n']}, {rs(d2['per_trade'])}, {rs(d2['per_session'])}, {rs(d2['worst_day'])} |")
        out.append("")
    return "\n".join(out) + "\n"


def line(r: dict) -> str:
    v, b, a, m = r["variant"], r["base"], r["always"], r["twin_median"]
    return (f"{v['trades']} trades ({v['changed']} changed), net {rs(v['net'])} (today {rs(b['net'])}, always {rs(a['net'])}); "
            f"net / max DD {fx(v['r_dd'])} (today {fx(b['r_dd'])}, always {fx(a['r_dd'])}, twins {fx(m['r_dd'])}); "
            f"net / worst day {fx(v['r_wd'])} (today {fx(b['r_wd'])}); max DD {rs(v['max_dd'])}")


def entries(P: dict, dec: dict) -> int:
    n = 0
    for t in K.TEST_IDS:
        spec = K.TESTS[t]
        src, unds = SRC[spec["scope"]]
        g = dec[t]
        meter = ("dealer GEX S1 near expiry of the trade's index at 09:20 / 10:00 (R28), option-chain context only"
                 if spec["meter"] == "gex" else "the app's fixed danger meter (gap, VIX, VIX change, event, expiry, weekday)")
        e = dict(
            id=f"r107-{t.lower()}",
            title=f"R107 {t} on {K.ARM_NAME[spec['scope']]}: {K.label(t)}",
            family="sizing-execution",
            date="2026-10-26",
            doc=DOC,
            hypothesis=(f"Boss (26 Oct): use the GEX and danger meters to trade MORE on the days they flag. This rule: "
                        f"{K.label(t)}. Gates: net > 0 and net / max DD and net / worst day above today's rule, 'always more' "
                        "and the random-day twins' median in design, walk-forward and final; final twin BH q <= 0.10 over "
                        "584 tests (11 + 573 earlier); >= 30 final trades changed."),
            data_version=("Drive lake gdrive:IraAlgo-data-lake (index_1m incl. INDIAVIX, index_daily, options_rolling_1m WEEK) "
                          "and derived/r28_gex copied 26 Oct; R51 Amendment A clean stores"),
            period=dict(design="2024-11-20..2026-03-31 (walk-forward window Apr 2025 - Mar 2026)",
                        holdout="2026-04-01..2026-10-13 read once (already read by R51-R106)"),
            instruments=unds,
            features=[f"signal source: {src} (unchanged); meter: {meter}; only the size or the 3rd same-direction place changes"],
            model_or_rule=f"{K.ARM_NAME[spec['scope']]} with {K.label(t)}",
            settings="research/hunt/r107_meters_more/r107cfg.py TESTS; PREREG.md sections 2-4",
            prereg=PREREG,
            variants_tried=len(K.TEST_IDS),
            results=dict(
                summary=(f"Design: {line(P['design'][t])}. Walk-forward: {line(P['wf'][t])}. Final: {line(P['final'][t])}; "
                         f"twin p {g['twin_p']}, BH q {g['q_all']} (R107 alone {g['q_r107']}). "
                         + ("PASS." if g["passed"] else f"Fails {len(g['fails'])} checks, first: " + "; ".join(g["fails"][:3]) + ".")),
                costs="dated Zerodha charges, R17 fills; 2 lots priced by the engine as a 2-lot order (fills and charges)"),
            holdout_read=True,
            verdict="paper-only" if g["passed"] else "rejected",
            notes="Signal on the underlying; nothing changes live or on paper.",
        )
        (ENTRIES / f"{e['id']}.yaml").write_text(yaml.safe_dump(e, sort_keys=False, allow_unicode=True, width=120))
        n += 1
    return n


def main():
    P, dec = load()
    (K.RESULTS / "report.md").write_text(report(P, dec))
    print(entries(P, dec), "entries; report.md written")


if __name__ == "__main__":
    main()
