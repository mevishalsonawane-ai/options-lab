"""R50 report: results/report.md from design.json and final.json (tables per family, the lottery view, the re-tune
grids, the biggest final-test trades and the expiry days used).

    python3 research/hunt/r50/r50report.py
"""
from __future__ import annotations

import json
import pickle

import r50cfg as K
import r50rules as RR


def inr(x) -> str:
    """Rs in Indian grouping, signed (1,23,456)."""
    if x is None:
        return "-"
    v = int(round(float(x)))
    s = "-" if v < 0 else "+" if v > 0 else ""
    v = abs(v)
    t = str(v)
    if len(t) > 3:
        head, tail = t[:-3], t[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        t = ",".join(parts) + "," + tail
    return s + t


def pct(x) -> str:
    return "-" if x is None else f"{x:.0f}%"


def verdict(r) -> str:
    g = r["gates"]
    if g["pass"]:
        return "PASS"
    if g["too_few"]:
        return "fail (too few trades to judge)"
    return "fail"


def rows_for_family(fam, des, fin):
    out = []
    for rs in RR.ORIGINALS:
        if rs.family == fam:
            out.append((rs.id, rs, des["originals"][rs.id], fin["originals"][rs.id] if fin else None, rs.id))
    for tid, f in RR.RETUNE_FAMILY.items():
        if f == fam:
            ch = des["retunes"][tid]["chosen"]
            spec = dict(RR.RETUNES[tid])[ch]
            d = dict(des["retunes"][tid]["cells"][ch])
            d["wf_net"] = des["retunes"][tid]["wf_net"]
            out.append((f"{tid} ({ch})", spec, d, fin["retunes"][tid] if fin else None, tid))
    return out


def main():
    des = json.loads((K.RESULTS / "design.json").read_text())
    fp = K.RESULTS / "final.json"
    fin = json.loads(fp.read_text()) if fp.exists() else None
    exp = json.loads((K.RESULTS / "expiry_days.json").read_text())
    L = ["# R50 results (generated by report.py)", ""]
    nd = {u: sum(1 for d in exp[u] if d <= str(K.DESIGN_END)) for u in K.UNDS}
    nf = {u: len(exp[u]) - nd[u] for u in K.UNDS}
    L += ["## Expiry days used", "",
          "| index | design (20 Nov 2024 - 31 Mar 2026) | final test (1 Apr - 13 Oct 2026) | first | last |",
          "|---|---|---|---|---|"]
    for u in K.UNDS:
        L.append(f"| {u} | {nd[u]} | {nf[u]} | {exp[u][0]} | {exp[u][-1]} |")
    L.append(f"| all | {sum(nd.values())} | {sum(nf.values())} | | |")
    L += ["", "Every date: `results/expiry_days.json`.", ""]
    fams = []
    for rs in RR.ORIGINALS:
        if rs.family not in fams:
            fams.append(rs.family)
    for fam in fams:
        L += [f"## {fam}", "",
              "| rule | signal source | OLD verdict (full old data) | NOW design: trades / win / 5x-10x peaks / net / per expiry-day "
              "/ worst day / max DD / top-5 share / p / walk-forward | FINAL: trades / win / 5x-10x peaks (banked 5x) / net / "
              "per expiry-day / worst day / max DD / top-5 share / p / q / 2x spread | verdict |",
              "|---|---|---|---|---|---|"]
        for name, rs, d, f, rid in rows_for_family(fam, des, fin):
            m = d["m"]
            dp = f"{d['p']:.3f}" if d.get("p") is not None else "-"
            dcell = (f"{m['trades']} / {m['win']}% / {m['hero5']}-{m['hero10']} / {inr(m['net'])} / {inr(m['per_day'])} / "
                     f"{inr(m['worst_day'])} / {inr(-m['max_dd'])} / {pct(m['top5'])} / {dp} / {inr(d['wf_net'])}")
            if f:
                fm = f["m"]
                fcell = (f"{fm['trades']} / {fm['win']}% / {fm['hero5']}-{fm['hero10']} ({fm['banked5']}) / {inr(fm['net'])} / "
                         f"{inr(fm['per_day'])} / {inr(fm['worst_day'])} / {inr(-fm['max_dd'])} / {pct(fm['top5'])} / "
                         f"{f['p']:.3f} / {f['q']:.3f} / {inr(f['spread2x'])}")
                v = verdict(f)
            else:
                fcell, v = "(not read)", "-"
            old = RR.OLD.get(rid, "new re-tune (R50)")
            L.append(f"| {name} | {rs.source} | {old} | {dcell} | {fcell} | {v} |")
        L.append("")
    L += ["## The lottery view: how much of the profit is the top 1 / 3 / 5 trades", "",
          "Share of net (only when net > 0) and the net without those trades.", "",
          "| rule | design net | top 1 / 3 / 5 share | design without top 1 / 3 / 5 | final net | top 1 / 3 / 5 share | final "
          "without top 1 / 3 / 5 |", "|---|---|---|---|---|---|---|"]
    for fam in fams:
        for name, rs, d, f, rid in rows_for_family(fam, des, fin):
            m = d["m"]
            a = f"{inr(m['net'])} | {pct(m['top1'])} / {pct(m['top3'])} / {pct(m['top5'])} | {inr(m['ex1'])} / {inr(m['ex3'])} / {inr(m['ex5'])}"
            if f:
                fm = f["m"]
                b = (f"{inr(fm['net'])} | {pct(fm['top1'])} / {pct(fm['top3'])} / {pct(fm['top5'])} | {inr(fm['ex1'])} / "
                     f"{inr(fm['ex3'])} / {inr(fm['ex5'])}")
            else:
                b = "- | - | -"
            L.append(f"| {name} | {a} | {b} |")
    L += ["", "## Re-tune grids (design, every cell; walk-forward picks)", "",
          "| re-tune | cell | design trades | design net | B0 | B1 | B2 | B3 | B4 |", "|---|---|---|---|---|---|---|---|---|"]
    for tid, v in des["retunes"].items():
        for name, c in v["cells"].items():
            b = c["blocks"]
            L.append(f"| {tid} | {name} | {c['m']['trades']} | {inr(c['m']['net'])} | " + " | ".join(inr(b[k]) for k in ("B0", "B1", "B2", "B3", "B4")) + " |")
        L.append(f"| {tid} | walk-forward picks {v['picks']} | | WF net {inr(v['wf_net'])} | chosen on all design: {v['chosen']} | | | | |")
    L += ["", "## Design blocks of the originals (net)", "", "| rule | B0 | B1 | B2 | B3 | B4 | walk-forward (B1-B4) |",
          "|---|---|---|---|---|---|---|"]
    for rs in RR.ORIGINALS:
        b = des["originals"][rs.id]["blocks"]
        L.append(f"| {rs.id} | " + " | ".join(inr(b[k]) for k in ("B0", "B1", "B2", "B3", "B4")) +
                 f" | {inr(des['originals'][rs.id]['wf_net'])} |")
    if fin:
        L += ["", "## Biggest final-test trades of the rules that made money in the final test", "",
              "| rule | index | expiry | side | strike | fill Rs | exit / fill | net |", "|---|---|---|---|---|---|---|---|"]
        for grp in ("originals", "retunes"):
            for rid, f in fin[grp].items():
                if f["m"]["net"] <= 0:
                    continue
                fid = f["id"].replace(":", "_")
                p = K.OUT / "trades" / f"final_{fid}.pkl"
                if not p.exists():
                    continue
                ts = sorted(pickle.loads(p.read_bytes()), key=lambda x: -x["net"])[:3]
                for x in ts:
                    L.append(f"| {f['id']} | {x['und']} | {x['d']} | {'CE' if x['side'] > 0 else 'PE'} | {x['strike']:g} | "
                             f"{x['entry']:.2f} | {x['xmult']:.1f}x | {inr(x['net'])} |")
        L += ["", f"Passed every gate: {', '.join(fin['passed']) or 'none'} (BH family {fin['bh_family']})."]
    (K.RESULTS / "report.md").write_text("\n".join(L) + "\n")
    print("wrote", K.RESULTS / "report.md")


if __name__ == "__main__":
    main()
