def cost_table() -> dict:
    """Median design 1-ITM premium per book and the round trip in points / ATR units (PREREG cost check)."""
    A.lake_ready()
    from research.hunt.r53.mcx import data as D
    out = {}
    for inst, (book, units) in S.OPTION_BOOK.items():
        m = D.load_market(book)
        prem = []
        for (d, cp, k), (ii, V) in m.legs.items():
            dd = pd.Timestamp(d).date()
            if not (A.DESIGN[0] <= dd <= A.DESIGN[1]):
                continue
            off = m.k_at.get((cp, -1 if cp == 0 else 1))
            if off is None:
                continue
            hit = off[ii] == k
            if hit.any():
                prem.append(np.median(V[hit, 3]))
        p = float(np.median(prem)) if prem else float("nan")
        rt = S.opt_cost(book, p * units, p * units, 18 * 60, 18 * 60)
        out[inst] = {"book": book, "units": units, "median_itm1_premium": p, "round_trip_rs": rt,
                     "cost_points_at_delta": rt / (units * DELTA)}
    return out


def run():
    T = pd.read_csv(A.RESULTS / "part1_cells.csv.gz")
    D = pd.read_csv(A.RESULTS / "part1_describe.csv")
    cost = cost_table()
    # median ATR in points per instrument x timeframe from the describe table's median range / (range / ATR)
    D["atr_pts"] = D.med_range / D.med_rng_atr
    atr = D[D.bucket == "ALL"].set_index(["inst", "tf"]).atr_pts.to_dict()
    for inst, c in cost.items():
        c["cost_atr"] = {tf: c["cost_points_at_delta"] / atr[(inst, tf)] for tf in ("1m", "5m", "15m", "60m")
                         if (inst, tf) in atr}
    (A.RESULTS / "part1_cost.json").write_text(json.dumps(cost, indent=1))
    intr = ~T.tf.str.startswith("day")
    P = T[intr & (T.h == A.PRIMARY_H) & T.p.notna()].copy()
    P["both"] = np.sign(P.effect_h1) == np.sign(P.effect_h2)
    P["cost_atr"] = [cost[i]["cost_atr"].get(tf, np.nan) for i, tf in zip(P.inst, P.tf)]
    P["beats_cost"] = P.mean_s.abs() > P.cost_atr
    sig = P[P.q < A.Q_GATE].sort_values("q")
    P["both_tests"] = (P.q < A.Q_GATE) & (P.q_cm < A.Q_GATE)
    sig2 = P[P.both_tests].sort_values("q_cm")
    L = ["# R85 Part 1 report (design 5 Aug 2025 - 31 Mar 2026; generated by report1.py)", ""]
    L.append(f"- Tested cells at h = 3 candles (n >= {A.MIN_N}): **{len(P)}**; BH q < 0.10: **{len(sig)}**; "
             f"of these the same sign in both design halves: **{int(sig.both.sum())}**; and mean move larger than "
             f"an option buyer's round trip: **{int((sig.both & sig.beats_cost).sum())}**.")
    L.append(f"- With the colour-matched (drift-neutral) baseline too (NOTES.md D1): **{len(sig2)}** cells pass both; "
             f"of these, larger than the option round trip: **{int(sig2.beats_cost.sum())}**.")
    L.append("")
    L.append("## Option cost check (1 lot, 1-ITM, evening spread, delta 0.6)")
    L.append("")
    L.append("| signal | option book | median 1-ITM premium | round trip Rs | needed move (points) | in ATR: 1m / 5m / 15m / 1h |")
    L.append("|---|---|---|---|---|---|")
    for inst, c in cost.items():
        ca = c["cost_atr"]
        L.append(f"| {inst} | {c['book']} x {c['units']:g} | {c['median_itm1_premium']:.1f} | {c['round_trip_rs']:.0f} | "
                 f"{c['cost_points_at_delta']:.2f} | " + " / ".join(f"{ca.get(t, np.nan):.2f}" for t in
                                                                   ("1m", "5m", "15m", "60m")) + " |")
    L.append("")
    L.append("## Cells that pass BOTH tests (pre-registered q < 0.10 and colour-matched q_cm < 0.10), h = 3")
    L.append("")
    L.append("| instrument | tf | candle | colour | session | n (days) | continues next 3 | same-colour random | mean move (ATR) | effect vs same colour | q_cm | q | beats option cost |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in sig2.itertuples():
        L.append(f"| {r.inst} | {r.tf} | {LABEL.get(r.cond, r.cond)} | {r.colour} | {r.bucket} | {r.n} ({r.days}) | "
                 f"{r.cont:.0%} | {r.base_cm:+.3f} ATR | {r.mean_s:+.3f} | {r.effect_cm:+.3f} | {r.q_cm:.3g} | {r.q:.3g} | "
                 f"{'yes' if r.beats_cost else 'no'} |")
    L.append("")
    L.append("## Findings with BH q < 0.10 on the pre-registered (pooled) baseline, h = 3, strongest first")
    L.append("")
    L.append("| instrument | tf | candle | colour | session | n (days) | continues next 3 | random-time | mean move (ATR) | effect | q | both halves | beats option cost |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in sig.head(80).itertuples():
        L.append(f"| {r.inst} | {r.tf} | {LABEL.get(r.cond, r.cond)} | {r.colour} | {r.bucket} | {r.n} ({r.days}) | "
                 f"{r.cont:.0%} | {r.base_cont:.0%} | {r.mean_s:+.3f} | {r.effect:+.3f} | {r.q:.3g} | "
                 f"{'yes' if r.both else 'no'} | {'yes' if r.beats_cost else 'no'} |")
    # what each candle means: pooled over instruments and timeframes, bucket ALL
    L += ["", "## What each candle means (all six instruments, 5m / 15m / 1h, any session; h = 3)", "",
          "| candle | colour | cells | median continuation | median random-time | median effect (ATR) | cells q < 0.10 (up / down) |",
          "|---|---|---|---|---|---|---|"]
    Q = P[(P.bucket == "ALL") & P.tf.isin(["5m", "15m", "60m"])]
    for cond in [c for c in LABEL if c in set(Q.cond)]:
        for col in ("green", "red"):
            x = Q[(Q.cond == cond) & (Q.colour == col)]
            if not len(x):
                continue
            s = x[x.q < A.Q_GATE]
            L.append(f"| {LABEL[cond]} | {col} | {len(x)} | {x.cont.median():.0%} | {x.base_cont.median():.0%} | "
                     f"{x.effect.median():+.3f} | {int((s.effect > 0).sum())} / {int((s.effect < 0).sum())} |")
    # day candles
    Dd = T[(T.tf == "day_design") & (T.h == A.PRIMARY_H) & T.p.notna()]
    Dc = T[(T.tf == "day_confirm") & (T.h == A.PRIMARY_H)].set_index(["inst", "cond", "colour"])
    ds = Dd[Dd.q < A.Q_GATE].sort_values("q")
    L += ["", f"## Day candles (design 2010-2022; confirmation 2023 - Mar 2026). Tested {len(Dd)}, q < 0.10: {len(ds)}",
          "", "| instrument | candle | colour | n | continues next 3 days | random | effect | q | confirm n | confirm effect |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for r in ds.head(40).itertuples():
        c = Dc.loc[(r.inst, r.cond, r.colour)] if (r.inst, r.cond, r.colour) in Dc.index else None
        L.append(f"| {r.inst} | {LABEL.get(r.cond, r.cond)} | {r.colour} | {r.n} | {r.cont:.0%} | {r.base_cont:.0%} | "
                 f"{r.effect:+.3f} | {r.q:.3g} | {int(c.n) if c is not None else 0} | "
                 f"{(c.effect if c is not None else np.nan):+.3f} |")
    # descriptive: colour shares by bucket
    L += ["", "## When candles are green or red (5m, design)", "",
          "| instrument | session | candles | green | red | doji | median range (Rs per mini lot) |", "|---|---|---|---|---|---|---|"]
    for r in D[(D.tf == "5m")].itertuples():
        L.append(f"| {r.inst} | {r.bucket} | {r.n} | {r.green:.1%} | {r.red:.1%} | {r.doji:.1%} | {r.med_range_rs:,.0f} |")
    (A.RESULTS / "part1_report.md").write_text("\n".join(L) + "\n")
    sig.to_csv(A.RESULTS / "part1_significant.csv", index=False, float_format="%.5g")
    sig2.to_csv(A.RESULTS / "part1_both_tests.csv", index=False, float_format="%.5g")
    print("\n".join(L[:6]))
    return sig


if __name__ == "__main__":
    run()
