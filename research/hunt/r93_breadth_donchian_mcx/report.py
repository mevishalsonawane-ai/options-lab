"""R93 report: results/report.md from results/design.json (and results/holdout.json once the holdout was read).

    python -m research.hunt.r93_breadth_donchian_mcx.report
"""
from __future__ import annotations

import json

from research.hunt.r93_breadth_donchian_mcx import cfg as K


def rs(x) -> str:
    if x is None or x != x:
        return "-"
    s = f"{abs(x):,.0f}"
    return ("-Rs " if x < 0 else "Rs ") + s


def pct(x) -> str:
    return "-" if x is None else f"{100 * x:.0f}%"


def row(name, s) -> str:
    if not s or not s.get("trades"):
        return f"| {name} | 0 | - | - | - | - | - | - | - | - |"
    return (f"| {name} | {s['trades']:,} | {pct(s['win_rate'])} | {rs(s['avg_win'])} / {rs(s['avg_loss'])} | "
            f"{rs(s.get('gross'))} | {rs(s['net'])} | {rs(s['worst_day'])} | {rs(s.get('worst_month'))} ({s.get('months_below_stop', 0)} of "
            f"{s.get('months', 0)} below -13k) | {rs(s['max_dd'])} | {rs(s.get('net_2x_slip'))} |")


HEAD = ("| | trades | win | avg win / loss | gross (before costs) | net | worst day | worst month (months below the "
        "stop) | max DD | net at 2x spread |\n|---|---|---|---|---|---|---|---|---|---|")


def split_table(sp) -> list:
    out = ["| split | trades | win | net | net / trade | metals: trades, net / trade | energy: trades, net / trade |",
           "|---|---|---|---|---|---|---|"]
    for name, s in sp.items():
        for k in ("confirmed", "unconfirmed"):
            x = s[k]
            m, e = x["metals"], x["energy"]
            out.append(f"| {name}: {k} | {x['trades']:,} | {pct(x['win_rate'])} | {rs(x['net'])} | "
                       f"{rs(x['net_per_trade'])} | {m['trades']:,}, {rs(m['net_per_trade'])} | "
                       f"{e['trades']:,}, {rs(e['net_per_trade'])} |")
    fams = sorted({f for s in sp.values() for k in ("confirmed", "unconfirmed") for f in s[k].get("by_family", {})})
    if fams:
        out += ["", "Per family, gross (before costs) / net per trade (trades):", "",
                "| split | " + " | ".join(fams) + " |", "|---|" + "---|" * len(fams)]
        for name, s in sp.items():
            for k in ("confirmed", "unconfirmed"):
                bf = s[k].get("by_family", {})
                cells = [f"{rs(bf[f]['gross_per_trade'])} / {rs(bf[f]['net_per_trade'])} ({bf[f]['trades']})" if f in bf
                         else "-" for f in fams]
                out.append(f"| {name}: {k} | " + " | ".join(cells) + " |")
    return out


def main() -> str:
    D = json.loads((K.RESULTS / "design.json").read_text())
    H = json.loads((K.RESULTS / "holdout.json").read_text()) if (K.RESULTS / "holdout.json").exists() else None
    L = ["# R93 results (generated by report.py)", ""]
    L += ["## Design", "", HEAD]
    for v in K.VARIANTS:
        o = D["variants"][v]
        L.append(row(f"{v} {o['label']}", o["design"]))
    L += ["", "Design twin p (random entries, same days and sides): " +
          ", ".join(f"{v} {D['variants'][v]['design_twin_p']:.3f} (twins avg {rs(D['variants'][v]['design_twin_mean'])})"
                    for v in K.VARIANTS), ""]
    for v in K.VARIANTS:
        L += [f"### {v} design by family and group", "", HEAD]
        b = D["variants"][v]["design_breakdown"]
        for f, s in b["by_family"].items():
            L.append(row(f, s))
        for g, s in b["by_group"].items():
            L.append(row(f"**{g}**", s))
        L.append("")
    for key in ("walk_forward_intraday", "walk_forward_daily"):
        w = D[key]
        L += [f"### {key.replace('_', ' ')}", "", "| variant | " + " | ".join(f"{a}..{b}" for a, b in w["folds"])
              + " | sum |", "|---|" + "---|" * (len(w["folds"]) + 1)]
        for v, x in w["fold_net"].items():
            L.append(f"| {v} | " + " | ".join(rs(y) for y in x) + f" | {rs(w['fold_sum'][v])} |")
        L += ["", f"Selection (best variant to date, traded in the next fold): picks {w['selection_picks']}, "
                  f"out-of-sample {rs(w['selection_oos'])}", ""]
    L += ["### Does breadth sort the breaks? (design)", ""] + split_table(D["breadth_split_design"]) + [""]
    if H:
        L += ["## Locked holdout (read once)", "", HEAD]
        for v in K.VARIANTS:
            o = H["variants"][v]
            L.append(row(f"{v} {o['label']}", o["holdout"]))
        L += ["", "| variant | twin avg | twin p | BH q | gates failed | verdict |", "|---|---|---|---|---|---|"]
        for v in K.VARIANTS:
            o = H["variants"][v]
            failed = [k for k, ok in o["gates"].items() if k != "PASS" and not ok]
            L.append(f"| {v} | {rs(o['twin_mean'])} | {o['twin_p']:.3f} | {o['bh_q']:.3f} | "
                     f"{', '.join(failed) or 'none'} | {'PASS' if o['gates']['PASS'] else 'fail'} |")
        L.append("")
        for v in K.VARIANTS:
            L += [f"### {v} holdout by family and group", "", HEAD]
            b = H["variants"][v]["holdout_breakdown"]
            for f, s in b["by_family"].items():
                L.append(row(f, s))
            for g, s in b["by_group"].items():
                L.append(row(f"**{g}**", s))
            s = H["variants"][v]["holdout"]
            if s.get("trades"):
                L += ["", f"Without the top 5 trades {rs(s['net_wo_top5'])}; without the best family ({s['best_family']}) "
                          f"{rs(s['net_wo_best_family'])}; calls {s['calls']} / {rs(s['net_calls'])}, puts {s['puts']} / "
                          f"{rs(s['net_puts'])}; exits {s['exits']}; stale exits {s['stale_exits']}.", ""]
        L += ["### Does breadth sort the breaks? (holdout)", ""] + split_table(H["breadth_split_holdout"]) + [""]
    text = "\n".join(L) + "\n"
    (K.RESULTS / "report.md").write_text(text)
    return text


if __name__ == "__main__":
    print(main())
