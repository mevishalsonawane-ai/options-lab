"""R44 report: results/report.md from results/design.json (+ results/holdout.json when it exists).

    python3 research/hunt/r44/report.py
"""
from __future__ import annotations

import json

import r44cfg as K

BOSS = [  # (strategy, und, side, session, Boss trades, Boss net) - OOS 2024-2026, Boss costs
    ("ema821_adx15_plock", "BANKNIFTY", "CE", "full", 1330, -52483),
    ("ema921_adx20", "BANKNIFTY", "CE", "full", 710, -34313),
    ("ema821_adx15_plock", "FINNIFTY", "CE", "full", 451, -33714),
    ("ema921_adx20", "NIFTY", "CE", "full", 768, -58515),
    ("rsi_fade", "CRUDEOIL", "PE", "morning", 497, -2750),
]


def rs(x):
    if x is None:
        return "-"
    return f"{x:,.0f}"


def pct(x):
    return "-" if x is None else f"{100 * x:.1f}%"


def pq(x):
    return "-" if x is None else f"{x:.3f}"


def cell_table(cells, per, lab="main"):
    rows = ["| strategy | index | side | session | trades | win | net real | net Boss | exp/trade | net/session | "
            "worst day | max DD | p | q |", "|" + "---|" * 14]
    for k, r in cells.items():
        s = r.get(f"{lab}:{per}")
        if s is None or not s.get("trades"):
            continue
        st, und, side, sess = k.split("|")
        rows.append(f"| {st} | {und} | {side} | {sess} | {s['trades']:,} | {pct(s['win'])} | {rs(s['net'])} | "
                    f"{rs(s['net_boss'])} | {rs(s['exp'])} | {rs(s['per_session'])} | {rs(s['worst_day'])} | "
                    f"{rs(s['max_dd'])} | {pq(s.get('p'))} | {pq(s.get('q'))} |")
    return "\n".join(rows)


def totals(cells, per, lab="main", strats=None, mcx=None):
    n = net = boss = hist = 0
    pos = tot = 0
    for k, r in cells.items():
        st, und, side, sess = k.split("|")
        if strats and st not in strats:
            continue
        if mcx is not None and K.is_mcx(und) != mcx:
            continue
        s = r.get(f"{lab}:{per}")
        if not s or not s.get("trades"):
            continue
        n += s["trades"]
        net += s["net"]
        boss += s["net_boss"]
        hist += s["net_hist"]
        tot += 1
        pos += s["net"] > 0
    return dict(trades=n, net=net, boss=boss, hist=hist, cells=tot, positive=pos)


def strat_summary(cells, pers):
    rows = ["| strategy | " + " | ".join(f"{p}: trades / net real / net Boss / net hist lots" for p in pers) + " |",
            "|---|" + "---|" * len(pers)]
    for st in K.STRATS:
        parts = []
        for p in pers:
            t = totals(cells, p, strats={st}, mcx=False)
            parts.append(f"{t['trades']:,} / {rs(t['net'])} / {rs(t['boss'])} / {rs(t['hist'])}")
        rows.append(f"| {st} | " + " | ".join(parts) + " |")
    return "\n".join(rows)


def boss_table(cells, per):
    rows = ["| cell | Boss trades | Boss net | our trades | our net (Boss costs) | our net (real) | "
            "our incl. expiry: trades / net Boss |", "|---|---|---|---|---|---|---|"]
    for st, und, side, sess, bt, bn in BOSS:
        k = f"{st}|{und}|{side}|{sess}"
        s = cells[k].get(f"main:{per}", {})
        e = cells[k].get(f"incl_expiry:{per}", {})
        rows.append(f"| {st} {und} {side} {sess} | {bt:,} | {rs(bn)} | {s.get('trades', 0):,} | {rs(s.get('net_boss'))} | "
                    f"{rs(s.get('net'))} | {e.get('trades', 0):,} / {rs(e.get('net_boss'))} |")
    return "\n".join(rows)


def main():
    dz = json.loads((K.RESULTS / "design.json").read_text())
    hp = K.RESULTS / "holdout.json"
    hz = json.loads(hp.read_text()) if hp.exists() else None
    C = (hz or dz)["cells"]
    out = ["# R44 results (generated by report.py)", ""]
    out.append(f"BH family: {dz['meta']['bh_family']} cells (OOS-design p, {K.TWINS} random-entry twins each).")
    passing = [k for k in C if C[k]["gates"]["pass"]]
    out.append(f"Cells passing every gate: {passing or 'none'}.")
    out.append("")
    for per in ("IS", "OOS_design"):
        t = totals(C, per, mcx=False)
        tb = totals(C, per, mcx=True)
        out.append(f"- {per} NSE/BSE, all cells: {t['trades']:,} trades, net real Rs {rs(t['net'])}, net Boss costs "
                   f"Rs {rs(t['boss'])}; {t['positive']} of {t['cells']} cells positive (real). CRUDEOIL: "
                   f"{tb['trades']:,} trades, real Rs {rs(tb['net'])}, Boss Rs {rs(tb['boss'])}, "
                   f"{tb['positive']} of {tb['cells']} positive.")
    if hz:
        for per in ("holdout", "OOS_boss", "JanAug2026", "SepOct2026", "ALL"):
            t = totals(C, per, mcx=False)
            tb = totals(C, per, mcx=True)
            out.append(f"- {per} NSE/BSE: {t['trades']:,} trades, real Rs {rs(t['net'])}, Boss Rs {rs(t['boss'])}; "
                       f"{t['positive']} of {t['cells']} positive. CRUDEOIL: {tb['trades']:,} trades, real "
                       f"Rs {rs(tb['net'])}, {tb['positive']} of {tb['cells']} positive.")
        m = hz["meta"]
        out.append(f"- Sep-Oct window: {m['sepoct_window'][0]} .. {m['sepoct_window'][1]} ({m['sepoct_sessions']} "
                   f"sessions). Design numbers moved when the holdout was opened: {m['design_numbers_moved'] or 'none'}.")
    out.append("")
    pers = ["IS", "OOS_design"] + (["holdout", "OOS_boss"] if hz else [])
    out += ["## Per strategy, NSE/BSE totals (current lots; hist = lot in force on the day, real costs)", "",
            strat_summary(C, pers), ""]
    if hz:
        out += ["## Side by side with Boss's sweep (OOS 2024 - 12 Oct 2026)", "", boss_table(C, "OOS_boss"), ""]
        fam = totals(C, "ALL", strats=set(K.CHAMPION_FAMILY), mcx=False)
        out.append(f"Champion family (ema821_adx15 + ema821_adx15_plock, NSE/BSE, 2021 - 12 Oct 2026): "
                   f"{fam['trades']:,} trades, Boss costs Rs {rs(fam['boss'])}, real Rs {rs(fam['net'])} "
                   f"(Boss: 42,347 trades, Rs -86,03,171).")
        out.append("")
        for per in ("SepOct2026", "JanAug2026"):
            out += [f"## October champion ema821_adx15: {per}", "",
                    cell_table({k: v for k, v in C.items() if k.startswith("ema821_adx15|")}, per), ""]
    for per in pers:
        out += [f"## Every cell: {per} (expiry days skipped)", "", cell_table(C, per), ""]
    out += ["## Every cell: OOS_design incl. expiry days (labelled separately)", "",
            cell_table(C, "OOS_design", "incl_expiry"), ""]
    out += ["## Gates", "", "| cell | " + " | ".join(next(iter(C.values()))["gates"].keys()) + " |",
            "|---|" + "---|" * len(next(iter(C.values()))["gates"])]
    for k, r in C.items():
        g = r["gates"]
        if g["OOS_design>0"] or g["pass"]:
            out.append(f"| {k} | " + " | ".join("yes" if v else "no" for v in g.values()) + " |")
    out.append("")
    out.append("(Only cells with a positive OOS-design net are listed; every other cell fails gate 2.)")
    (K.RESULTS / "report.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[:20]))


if __name__ == "__main__":
    main()
