"""R90 report: every table from results/*.json into results/report.md.

    python -m research.hunt.r90_almazov_bos.report
"""
from __future__ import annotations

import json

from . import cfg as K


def _f(x, nd=0):
    if x is None:
        return ""
    if isinstance(x, float) and nd:
        return f"{x:,.{nd}f}"
    try:
        return f"{x:,.0f}"
    except (TypeError, ValueError):
        return str(x)


def _pct(x):
    return "" if x is None else f"{100 * x:.0f}%"


def cell_table(cells: list, with_gates: bool) -> list:
    h = ("| instrument | variant | trades (a day) | win | avg win / loss | per trade | net | max DD | worst day | "
         "worst month | stopped <= 3 bars | twin after (mean, p) | twin window (mean, p) | q | und pts / trade | "
         "opt gross / cost pts | as written: trades, pts / trade, win, Rs |" + (" gates |" if with_gates else ""))
    out = [h, "|" + "---|" * (h.count("|") - 1)]
    for c in cells:
        o = c["opt"]
        u = c.get("und", {})
        aw = c.get("as_written", {})
        g = c.get("gates", {})
        fails = ",".join(k for k, v in g.items() if k != "pass" and not v)
        q = c.get("q", c.get("q_all"))
        out.append(
            f"| {K.LABEL.get(c['inst'], c['inst'])} | {c['variant']} | {o.get('trades', 0)} ({o.get('per_day', 0):.2f}) | "
            f"{_pct(o.get('win'))} | {_f(o.get('avg_win'))} / {_f(o.get('avg_loss'))} | {_f(o.get('expectancy'))} | "
            f"{_f(o.get('net'))} | {_f(o.get('max_dd'))} | {_f(o.get('worst_day'))} | {_f(o.get('worst_month'))} | "
            f"{_pct(c.get('fast_stop'))} | {_f(o.get('twin_mean'))}, {o.get('twin_p', '')} | "
            f"{_f(o.get('wtwin_mean'))}, {o.get('wtwin_p', '')} | {'' if q is None else f'{q:.2f}'} | "
            f"{_f(u.get('pts_mean'), 2)} | {_f(c.get('opt_gross_pts'), 2)} / {_f(c.get('opt_cost_pts'), 2)} | "
            f"{aw.get('trades', 0)}, {_f(aw.get('pts_mean'), 2)}, {_pct(aw.get('win'))}, {_f(aw.get('rs'))} |"
            + ((" PASS |" if g.get("pass") else f" {fails} |") if with_gates else ""))
    return out


def pooled_table(pooled: dict) -> list:
    out = ["| group | variant | trades | option net | twin after mean | twin window mean | underlying Rs (no costs) | "
           "as-written trades | as-written Rs (no costs) | stopped <= 3 bars |", "|---|---|---|---|---|---|---|---|---|---|"]
    for k, p in pooled.items():
        g, v = k.split("|")
        out.append(f"| {g} | {v} | {p['trades']} | {_f(p['net'])} | {_f(p['twin_mean'])} | {_f(p['wtwin_mean'])} | "
                   f"{_f(p['und_rs'])} | {p['aw_trades']} | {_f(p['aw_rs'])} | {_pct(p['fast_stop'])} |")
    return out


def fold_table(cells: list) -> list:
    out = ["| instrument | variant | folds (trades: net) |", "|---|---|---|"]
    for c in cells:
        out.append(f"| {K.LABEL.get(c['inst'], c['inst'])} | {c['variant']} | " +
                   "; ".join(f"{f['lo'][:7]}: {f['trades']}: {_f(f['net'])}" for f in c["folds"]) + " |")
    return out


def main():
    L = ["# R90 results (generated by report.py)", ""]
    D = json.loads((K.RESULTS / "design.json").read_text())
    L += [f"## Design ({D['n_cells']} cells; passers: {', '.join(D['passers']) or 'none'})", ""]
    L += cell_table(D["cells"], True) + [""]
    L += ["## Design pooled (not tested)", ""] + pooled_table(D["pooled"]) + [""]
    L += ["## Design folds", ""] + fold_table(D["cells"]) + [""]
    L += ["## Selection walk-forward", "", "| instrument | picks (fold: pick, next net) | selection net | A5 net |",
          "|---|---|---|---|"]
    for inst, w in D["selection_wf"].items():
        L.append(f"| {K.LABEL.get(inst, inst)} | " + "; ".join(f"{p['fold'][:7]}: {p['pick']} {_f(p['next_net'])}"
                                                            for p in w["picks"]) +
                 f" | {_f(w['selection_net'])} | {_f(w['base_net'])} |")
    L.append("")
    if (K.RESULTS / "final.json").exists():
        F = json.loads((K.RESULTS / "final.json").read_text())
        L += ["## Holdout (read once)", "", f"Design passers: {', '.join(F['design_passers']) or 'none'}; verdict: "
              f"{json.dumps(F['verdict'])}", ""]
        L += cell_table(F["cells"], False) + [""]
        L += ["## Holdout pooled", ""] + pooled_table(F["pooled"]) + [""]
    (K.RESULTS / "report.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
