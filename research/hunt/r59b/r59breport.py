"""R59b report: results/report.md from literal.json, design.json and final.json (no data needed).

    python3 -I research/hunt/r59b/r59breport.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import r59bcfg as K  # noqa: E402


def load(name):
    return json.loads((K.RESULTS / name).read_text())


def rs(x):
    return "n/a" if x is None else f"{x:+,.0f}"


def cell_row(name, d, f):
    p = "n/a" if f.get("p") is None else f"{f['p']:.3f}"
    q = "n/a" if f.get("q") is None else f"{f['q']:.2f}"
    return (f"| {name} | {d.get('trades', 0)}, {rs(d.get('per_trade'))}, {rs(d.get('net'))}, {rs(d.get('gross_per_trade'))} | "
            f"{f.get('trades', 0)} | {f.get('win', 'n/a')}% | {rs(f.get('per_trade'))} | {rs(f.get('gross_per_trade'))} | "
            f"{rs(f.get('net'))} | {rs(f.get('net2'))} | {rs(f.get('net_wo_top5'))} | {p} | {q} | "
            f"{rs(f.get('cap_median'))} / {rs(f.get('cap_max'))} | {f.get('trades_per_session', 'n/a')} | "
            f"{'PASS' if f.get('pass') else ', '.join(f.get('fails', []))} |")


def main():
    L, Dz, F = load("literal.json"), load("design.json")["cells"], load("final.json")
    Fc = F["cells"]
    out = ["# R59b results (generated by r59breport.py)", ""]
    p, cc = L["pooled"], L["claim_checks"]
    out += ["## Step 1: their rule, literally (rolling 15-minute ATM series, 4 Nov 2024 - 14 Oct 2026: a check of their "
            "claim only)", "",
            f"Pooled: {p['trades']:,} trades, {p['win']}% win, {rs(p['per_trade'])} a trade, median {rs(p['median'])}, "
            f"total {rs(p['total'])}, max drawdown {rs(cc['max_drawdown'])}, {cc['trades_per_day']} trades a day "
            f"({cc['dates']} dates).", "",
            "Win by quarter: " + ", ".join(f"{k} {v['win']}% ({v['trades']})" for k, v in cc["win_by_quarter"].items()),
            "", "Win by stock: " + ", ".join(f"{k} {v['win']}% ({v['trades']})" for k, v in cc["win_by_stock"].items()),
            "", "| series | trades | win | Rs/trade | total | one-contract trades, Rs/trade | profit share from switches/rolls |"
            " held-contract diag. Rs/trade |", "|---|---|---|---|---|---|---|---|"]
    for k, v in L["cells"].items():
        oc = v["by_category"]["one_contract"]
        out.append(f"| {k} | {v['trades']} | {v['win']}% | {rs(v['per_trade'])} | {rs(v['total'])} | {oc['trades']}, "
                   f"{rs(oc['per_trade'])} | {v['by_category']['any_switch_or_roll']['share_profit']}% | "
                   f"{rs(v['held_contract_diag']['per_trade'])} |")
    out += ["", "## Step 2: decomposition (pooled; categories overlap)", "",
            "| category | trades | share of trades | profit | share of profit | Rs/trade | win |", "|---|---|---|---|---|---|---|"]
    for c, v in p["by_category"].items():
        out.append(f"| {c} | {v['trades']} | {v['share_trades']}% | {rs(v['profit'])} | {v['share_profit']}% | "
                   f"{rs(v['per_trade'])} | {v['win']}% |")
    out += ["", f"Held-contract diagnostic (their trades valued on the contract held at the signal bar, Rs 10k notional, "
            f"Rs 95, no spread): {p['held_contract_diag']}", ""]
    out += ["## Step 3: honest cells (1 lot, real fills, dated charges, per-stock spread)", "",
            "Columns: design trades, Rs/trade, net, gross/trade (before costs); final trades, win, Rs/trade, gross/trade, "
            "net at 1x, net at 2x costs, net without the top 5, p (random-entry twins), BH q over 126 cells, capital per "
            "trade (median / max, premium x 1 lot), trades per eligible session, gate.", ""]
    for fam, label in (("A", "A: their band on the HELD contract (option-chart signal, NON-DEFAULT)"),
                       ("B", "B: the band on the STOCK (lower -> CE, upper -> PE; signal on the stock, default)")):
        for v in K.VARIANTS:
            out += [f"### {label}, {v}", "",
                    "| cell | design | final trades | win | Rs/trade | gross/trade | net | net 2x | w/o top 5 | p | q | "
                    "capital | trades/session | gate |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for sym in K.STOCKS:
                for nm in ("CE", "PE"):
                    n = f"{fam}-{v}-{sym}-{nm}"
                    out.append(cell_row(f"{sym} {nm}", Dz.get(n, {}), Fc.get(n, {})))
            n = f"{fam}-{v}-ALL"
            out.append(cell_row("**all**", Dz.get(n, {}), Fc.get(n, {})))
            out.append("")
    out += ["## Before costs: is a tuning round worth it? (PREREG rule)", "",
            "| pooled cell | design gross/trade (t) | final gross/trade (t) | final median cost/trade | worth trying |",
            "|---|---|---|---|---|"]
    for n, t in F["tuning"].items():
        out.append(f"| {n} | {rs(t['design_gross'])} ({t['design_t']}) | {rs(t['final_gross'])} ({t['final_t']}) | "
                   f"{rs(t['final_cost_median'])} | {'yes' if t['worth_trying'] else 'no'} |")
    npass = sum(1 for c in Fc.values() if c.get("pass"))
    out += ["", f"Cells passing every gate: {npass} of {len(Fc)}. Last session: {F['last_session']}.", ""]
    (K.RESULTS / "report.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
