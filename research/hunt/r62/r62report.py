"""R62 tables: results/report.md from results/design.json, final.json and (if present) opt_design.json / opt_final.json.

    python research/hunt/r62/r62report.py
"""
from __future__ import annotations

import json

import r62cfg as K

BOOK_NAME = {
    "IDX": "5 indices, volume source (a) option-chain volume, 1-ITM index option bought (PRIMARY)",
    "STK": "10 stocks, real stock volume, the stock in cash intraday (PRIMARY)",
    "IDX-b": "NIFTY + BANKNIFTY, volume source (b) constituents' traded value (secondary)",
    "IDX-c": "5 indices, volume source (c) TPO (secondary)",
    "STK-c": "10 stocks, TPO (secondary)",
    "STK-sw": "10 stocks, real volume, long-only 1-5 day swing in delivery (secondary)",
}


def rs(x) -> str:
    return "-" if x is None else f"{x:+,.0f}"


def row(v: str, d: dict, f: dict | None) -> str:
    a = d["x1"]
    cells = [v, f"{a.get('trades', 0)}", rs(a.get("net")), rs(d["x2"].get("net")), "yes" if d.get("design_gate") else "no"]
    if f is None:
        return "| " + " | ".join(cells) + " |"
    b = f["x1"]
    if not b.get("trades"):
        cells += ["0"] + ["-"] * 12 + [f.get("verdict", "-")]
        return "| " + " | ".join(cells) + " |"
    q = f.get("q", f.get("q_own"))
    cells += [f"{b['trades']}", f"{b['win']:.0%}", rs(b["avg_win"]), rs(b["avg_loss"]), f"{b['r_mult']:+.2f}",
              rs(b["net"]), rs(f["x2"]["net"]), rs(b["worst_day"]), rs(-b["max_dd"]), b["months_green"],
              "-" if f.get("p") is None else f"{f['p']:.3f}", "-" if q is None else f"{q:.2f}",
              rs(f.get("risk1", {}).get("net_risk1")), f.get("verdict", "-")]
    return "| " + " | ".join(cells) + " |"


HEAD = ("| variant | design trades | design net | design 2x | design gate | final trades | win | avg win | avg loss | "
        "R mult | final net | 2x | worst day | max DD | months green | p | q | 1%-risk net | verdict |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")


def main():
    des = json.loads((K.RESULTS / "design.json").read_text())
    fin_p = K.RESULTS / "final.json"
    fin = json.loads(fin_p.read_text()) if fin_p.exists() else None
    out = ["# R62 tables (generated by r62report.py)", "",
           "Rupees, 1 lot (index option: the lot in force; stock: the latest F&O lot in shares), real charges and "
           "slippage. Design 20 Nov 2024 - 31 Mar 2026; final 1 Apr 2026 - 14 Oct 2026 (indices) / 12 Oct 2026 "
           "(stocks), read once. q: Benjamini-Hochberg over the 32 primary tests (secondary books: their own 16, "
           "context only). R mult: the underlying's move to the exit over the entry-to-stop distance (mean). "
           "1%-risk net: information only (Rs 1 lakh capital, Rs 1,000 at risk a trade).", ""]
    for book, name in BOOK_NAME.items():
        out += [f"## {book}: {name}", "", HEAD]
        for v in K.VARIANTS:
            k = f"{book}/{v}"
            out.append(row(v, des["results"][k], fin["results"][k] if fin else None))
        out.append("")
        if fin:
            best = max(K.VARIANTS, key=lambda v: fin["results"][f"{book}/{v}"]["x1"].get("net", 0))
            f = fin["results"][f"{book}/{best}"]["x1"]
            if f.get("trades"):
                per = "; ".join(f"{s} {n} / {rs(x)}" for s, (n, x) in f["inst"].items())
                out += [f"Best final variant {best}, by instrument (trades / net): {per}. Exits: {f['why']}. "
                        f"Longs {f['longs']}, shorts {f['shorts']}.", ""]
    for part in ("design", "final"):
        p = K.RESULTS / f"opt_{part}.json"
        if p.exists():
            x = json.loads(p.read_text())
            out += [f"## STK-opt ({part}): the stock's ATM monthly option on R58's engine (context only)", "",
                    "| variant | trades | win | net | 2x | worst day | max DD | stale/model exits |", "|---|---|---|---|---|---|---|---|"]
            for v in K.VARIANTS:
                s = x[v]
                if not s.get("trades"):
                    out.append(f"| {v} | 0 | - | - | - | - | - | - |")
                    continue
                out.append(f"| {v} | {s['trades']} | {s['win']:.0%} | {rs(s['net'])} | {rs(s['net_2x'])} | "
                           f"{rs(s['worst_day'])} | {rs(-s['max_dd'])} | {s['stale_model_exits']} |")
            out.append("")
    out += ["## Candidate and leg counts (design)", "", "| book:instrument | legs | profiles | POC zones | POC+OB | "
            "LVN zones | LVN+FVG | candidates |", "|---|---|---|---|---|---|---|---|"]
    for k, c in des["counts"].items():
        out.append(f"| {k} | {c['legs']} | {c['profiles']} | {c['poc']} | {c['poc_conf']} | {c['lvn']} | {c['lvn_conf']} | "
                   f"{c['candidates']} |")
    (K.RESULTS / "report.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
