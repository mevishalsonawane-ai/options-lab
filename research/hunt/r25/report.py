"""R25 report: results/report.md from census.json, anatomy.json, design.json, walkforward.json, holdout.json.

    python3 research/hunt/r25/report.py
"""
from __future__ import annotations

import json

import r25cfg as K

IDS = ["H0", "L1", "L2", "L3", "L4", "V4", "T1", "T2", "T3"]


def _j(name):
    p = K.RESULTS / name
    return json.loads(p.read_text()) if p.exists() else {}


def rs(x):
    return "—" if x is None else f"{x:+,.0f}"


def rule_table(res: dict, title: str) -> list[str]:
    L = ["", f"### {title}", "",
         "| rule | expiries | trades | hit % | avg win | avg loss | net Rs | per expiry | per Rs 1,000 risked | per lot (net, trades) | green expiries % | worst day | max DD | losing streak (trades / expiries) | best day share % | net w/o best day | 2× spread | out-of-range = 0 |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i in IDS:
        r = res.get(i)
        if not r:
            continue
        m = r["m"]
        L.append(f"| {i} | {m['expiries']} | {m['trades']} | {m['hit_pct']} | {rs(m['avg_win'])} | {rs(m['avg_loss'])} | "
                 f"{rs(m['net'])} | {rs(m['per_expiry'])} | {rs(m['per_1000_risked'])} | {rs(r['per_lot']['net'])} ({r['per_lot']['trades']}) | "
                 f"{m['green_expiries_pct']} | {rs(m['worst_day'])} | {rs(m['max_dd'])} | {m['losing_streak_trades']} / "
                 f"{m['losing_streak_expiries']} | {m['best_day_share_pct'] if m['best_day_share_pct'] is not None else '—'} | "
                 f"{rs(m['net_without_best_day'])} | {rs(r['x2_spread'])} | {rs(r['oor_zero'])} |")
    return L


def exit_table(res: dict, title: str) -> list[str]:
    L = ["", f"### {title}", "", "| rule (its own exit) | hold | half 3× | half 5× | ladder | rupee trail | app |",
         "|---|---|---|---|---|---|---|"]
    for i in IDS:
        r = res.get(i)
        if r and "exit_grid" in r:
            g = r["exit_grid"]
            L.append(f"| {i} ({r['exits']}) | " + " | ".join(rs(g[e]) for e in ("hold", "half3", "half5", "ladder", "trail", "app")) + " |")
    return L


def main():
    c, a, d, w, h = _j("census.json"), _j("anatomy.json"), _j("design.json"), _j("walkforward.json"), _j("holdout.json")
    L = ["# R25 report (generated by report.py; every number with its sample size)", ""]
    L += ["## Rules as chosen", "", "| rule | what | exits | params (T: chosen on all design days) | budget |", "|---|---|---|---|---|"]
    for i in IDS:
        if i in d:
            L.append(f"| {i} | {d[i]['note']} | {d[i]['exits']} | {d[i]['params']} | {d[i]['budget']:,.0f} |")
    L += rule_table(d, "Design (470 expiries, 2023 - 12 Oct 2026)")
    L += exit_table(d, "Design: the same entries with every exit (net Rs)")
    if d:
        L += ["", "### Design per year (net Rs, trades)", "", "| rule | " + " | ".join(str(y) for y in (2023, 2024, 2025, 2026)) + " |",
              "|---|---|---|---|---|"]
        for i in IDS:
            if i in d:
                py = d[i]["per_year"]
                L.append(f"| {i} | " + " | ".join(f"{rs(py[str(y)]['net'])} ({py[str(y)]['trades']})" if str(y) in py else "—"
                                                    for y in (2023, 2024, 2025, 2026)) + " |")
    if w:
        L += ["", "### Walk-forward (anchored; T rules re-chosen on the earlier years)", "",
              "| rule | 2024 | 2025 | 2026 | sum | years > 0 | picks (T) |", "|---|---|---|---|---|---|---|"]
        for i in IDS:
            if i in w:
                f = {x["test_year"]: x for x in w[i]["folds"]}
                picks = "; ".join(f"{x['test_year']}: {x.get('params')} {x.get('exits', '')}" for x in w[i]["folds"]) if i.startswith("T") else ""
                L.append(f"| {i} | " + " | ".join(f"{rs(f[y]['net'])} ({f[y]['trades']})" for y in (2024, 2025, 2026)) +
                         f" | {rs(w[i]['sum'])} | {w[i]['years_positive']} | {picks} |")
    if h:
        L += rule_table(h, f"HOLDOUT (read once {h['read_at_utc'][:16]} UTC; {h['expiries']})")
        L += exit_table(h, "Holdout: the same entries with every exit (net Rs)")
        L += ["", "### Holdout significance, BH and gates", "",
              "| rule | test | p | BH q (18) | random-strike twin p (mean) | random-time twin mean | gates failed | passes |",
              "|---|---|---|---|---|---|---|---|"]
        for i in IDS:
            r = h[i]
            s = r["sig"]
            failed = ", ".join(k.split("_")[0] for k, v in r["gates"].items() if not v) or "none"
            L.append(f"| {i} | {s['test']} | {s['p']:.3f} | {h['bh_family'][i]['q']:.3f} | {s['twin_strike_p']:.3f} "
                     f"({rs(s['twin_strike_mean'])}) | {rs(s.get('twin_time_mean'))} | {failed} | {'YES' if r['passes'] else 'no'} |")
        L += ["", "R21's p-values in the family: " + ", ".join(f"{k} {v['p']:.3f} (q {v['q']:.3f})" for k, v in h["bh_family"].items() if k.startswith("R21"))]
        g = h.get("exit_grid_bh", {})
        if g:
            low = sorted(g.items(), key=lambda kv: kv[1]["p"])[:6]
            L += ["", "Exit grid (54 rule × exit nets on the holdout, bootstrap p, own BH): smallest p " +
                  ", ".join(f"{k} p {v['p']:.3f} q {v['q']:.3f}" for k, v in low)]
    (K.RESULTS / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L)[:12000])


if __name__ == "__main__":
    main()
