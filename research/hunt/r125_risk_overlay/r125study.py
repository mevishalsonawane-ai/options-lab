"""R125 study (PREREG.md): Z1 / Z2 on R123 V2's trades; twins, BH (all families and within the loop), gates.

    python3 research/hunt/r125_risk_overlay/r125study.py run      # -> results/results.json, results/report.md
"""
from __future__ import annotations

import json
import pickle
import sys

import numpy as np

import r125cfg as K
import r125lib as L
import r119study as S19
import r117lib as L117


def load():
    parts = pickle.loads(K.R123_TRADES.read_bytes())
    return ([t for p in parts for t in p["V2"]["tr"]], [t for p in parts for t in p["V2"]["tr2"]])


def loop_ps():
    out = {}
    for r, (folder, how) in K.LOOP_RESULTS.items():
        res = json.loads((K.ROOT / "research" / "hunt" / folder / "results" / "results.json").read_text())
        for t, x in res["tests"].items():
            out[f"{r}-{t}"] = float(x["boot_p"] if how == "boot_p" else x["twin"]["p"])
    return out


def run():
    tr, tr2 = load()
    rng = np.random.default_rng(K.SEED)
    books = {"Z1": (L.one_a_day(tr), L.one_a_day(tr2)), "Z2": (L.breaker(L.one_a_day(tr)), L.breaker(L.one_a_day(tr2)))}
    m_all = L117.count_prior(K.ROOT / "research" / "experiments" / "entries", K.ENTRIES_LAST_DAY) + len(K.TESTS)
    fin_all = [t for t in tr if K.period(t.day) == "final"]
    z1_fin = [t for t in books["Z1"][0] if K.period(t.day) == "final"]
    res = {"tests": {}, "m_all": m_all, "r123_v2": {per: S19.metrics([t for t in tr if K.period(t.day) == per])
                                                    for per in (*K.PERIODS,)} | {"all": S19.metrics(tr)}}
    ps = []
    for z, (b, b2) in books.items():
        m = {per: S19.metrics([t for t in b if K.period(t.day) == per]) for per in K.PERIODS}
        m["all"] = S19.metrics(b)
        f2 = S19.metrics([t for t in b2 if K.period(t.day) == "final"])
        fin = [t for t in b if K.period(t.day) == "final"]
        if z == "Z1":
            tw = L.z1_twin(fin_all, K.TWINS, rng)
            skipped = len(tr) - len(b)
        else:
            tw = L.drop_twin(z1_fin, len(z1_fin) - len(fin), K.TWINS, rng)
            skipped = len(books["Z1"][0]) - len(b)
        tp = L117.twin_p(sum(t.net for t in fin), tw)
        ps.append(tp["p"])
        res["tests"][z] = dict(name=K.TESTS[z], periods=m, final_2x=f2, twin=tp, skipped=skipped)
    q_all = L117.bh(ps, m_all)
    lp = loop_ps()
    lp.update({f"R125-{z}": p for z, p in zip(K.TESTS, ps)})
    q_loop = dict(zip(lp, L117.bh(list(lp.values()))))
    for i, z in enumerate(K.TESTS):
        r = res["tests"][z]
        r.update(q_all=float(q_all[i]), q_loop=float(q_loop[f"R125-{z}"]))
        f, a = r["periods"]["final"], r["periods"]["all"]
        fails = [f"{per} mean <= 0" for per in K.PERIODS if not r["periods"][per].get("trades") or r["periods"][per]["mean"] <= 0]
        if f.get("trades") and f["ex3"] <= 0:
            fails.append("final <= 0 without 3 best days")
        if not r["final_2x"].get("trades") or r["final_2x"]["mean"] <= 0:
            fails.append("final mean <= 0 at 2x slippage")
        if r["twin"]["p"] >= K.GATE_P:
            fails.append(f"twin p {r['twin']['p']:.3g}")
        if r["q_all"] > K.GATE_Q:
            fails.append(f"BH q {r['q_all']:.3g}")
        if f.get("trades", 0) < K.MIN_FINAL:
            fails.append(f"< {K.MIN_FINAL} final trades")
        for lab, x in (("final", f), ("2021-26", a)):
            if x.get("trades") and x["months_at_stop"] > 0:
                fails.append(f"{x['months_at_stop']} {lab} months <= -13k")
            if x.get("trades") and x["max_dd"] >= K.DD_STOP:
                fails.append(f"{lab} drawdown >= 40k")
        r["gates"] = dict(passed=not fails, fails=fails)
    res["q_loop_all"] = {k: float(v) for k, v in q_loop.items()}
    K.RESULTS.mkdir(exist_ok=True)
    (K.RESULTS / "results.json").write_text(json.dumps(res, indent=1, default=str))
    (K.RESULTS / "report.md").write_text(report(res))
    print(report(res))


def rs(x):
    return "-" if x is None else f"{x:+,.0f}".replace("+-", "-")


def report(res):
    md = ["# R125 results (generated by r125study.py)", "", f"Signal source: {K.SIGNAL_SOURCE}. BH m = {res['m_all']:,}.", "",
          "| book | period | trades | WIN | mean Rs | total Rs | worst day | max DD | months <= -13k | w/o 3 best |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    rows = [("R123 V2 (as tested)", res["r123_v2"])] + [(f"{z}: {r['name']}", r["periods"]) for z, r in res["tests"].items()]
    for lab, pm in rows:
        for per in (*K.PERIODS, "all"):
            m = pm[per]
            md.append(f"| {lab} | {per} | {m['trades']} | {m['win']:.1f}% | {rs(m['mean'])} | {rs(m['total'])} | "
                      f"{rs(m['worst_day'])} | {m['max_dd']:,.0f} | {m['months_at_stop']} | {rs(m['ex3'])} |")
    md.append("")
    for z, r in res["tests"].items():
        md += [f"## {z}: {r['name']}", "", f"- Trades skipped by the rule: {r['skipped']}.",
               f"- Final at 2x slippage: mean Rs {rs(r['final_2x'].get('mean'))}.",
               f"- Twin p {r['twin']['p']:.4f}; BH q (all families) {r['q_all']:.3g}; q within the loop (R121-R125) "
               f"{r['q_loop']:.3g}.",
               f"- **{'PASS' if r['gates']['passed'] else 'fail'}**" + ("" if r["gates"]["passed"] else ": "
               + "; ".join(r["gates"]["fails"])), ""]
    md += ["## q within the loop (BH over R121-R125's 10 tests; not a gate)", "",
           "| test | q |", "|---|---|"] + [f"| {k} | {v:.3g} |" for k, v in res["q_loop_all"].items()]
    return "\n".join(md) + "\n"


if __name__ == "__main__":
    if sys.argv[1:2] == ["run"]:
        run()
    else:
        print(__doc__)
