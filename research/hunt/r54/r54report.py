"""R54 tables (results/report.md) from results/design.json and results/final.json.

    python3 research/hunt/r54/r54report.py
"""
from __future__ import annotations

import json

import r54cfg as K

HEAD = ("| entry | end | exit | tickets | hit | 2x / 5x / 10x | net | per Rs 1,000 staked | worst day | max DD | "
        "top-1 / top-5 share | net without top 5 | 2x spread | no-guard net | p | q |")


def inr(x) -> str:
    if x is None:
        return "-"
    x = float(x)
    s = "-" if x < 0 else "+"
    n = f"{abs(x):,.0f}"
    if abs(x) >= 100000:                       # Indian grouping: 1,23,456
        i = int(round(abs(x)))
        a, b = divmod(i, 1000)
        g = []
        while a >= 100:
            a, c = divmod(a, 100)
            g.append(f"{c:02d}")
        n = ",".join([str(a)] + g[::-1]) + f",{b:03d}"
    return s + n


def hhmm(s: str) -> str:
    return f"{s[:2]}:{s[2:]}"


def share(v) -> str:
    return "-" if v is None else f"{v:.0f}%"


def cell_row(c: dict) -> str:
    m = c["m"]
    return (f"| {hhmm(c['entry'])} | {hhmm(c['end'])} | {'25% trail' if c['exit'] == 'tr25' else 'hold'} | {m['tickets']} | "
            f"{m['hit']:.0f}% | {m['x2']} / {m['x5']} / {m['x10']} | {inr(m['net'])} | {inr(m['per1000'])} | "
            f"{inr(m['worst_day'])} | {m['max_dd']:,.0f} | {share(m['top1'])} / {share(m['top5'])} | {inr(m['ex5'])} | "
            f"{inr(c['spread2x'])} | {inr(c['no_guard_net'])} | {c['p']:.3f} | {c['q']:.2f} |")


def table(res: dict) -> str:
    out = [HEAD, "|" + "---|" * 16]
    for k in sorted(res["cells"], key=lambda k: (k.split("-")[2], k.split("-")[0], k.split("-")[1])):
        out.append(cell_row(res["cells"][k]))
    return "\n".join(out)


def compare(des: dict, fin: dict) -> str:
    out = ["| comparison (per index-expiry-day) | design mean [95% CI] | final mean [95% CI] | reading |", "|---|---|---|---|"]
    for k, d in des["compare"].items():
        f = fin["compare"][k]
        out.append(f"| {k.replace(' | ', ', ')} | {inr(d['mean'])} [{inr(d['lo'])}, {inr(d['hi'])}] | {inr(f['mean'])} [{inr(f['lo'])}, "
                   f"{inr(f['hi'])}] | {f['reading']} |")
    return "\n".join(out)


def callouts(fin: dict) -> str:
    out = ["| cell | day | leg | strike | fill | exit price (why) | peak | net |", "|---|---|---|---|---|---|---|---|"]
    for k in sorted(fin["cells"], key=lambda k: (k.split("-")[2], k)):
        if k.split("-")[1] not in ("1505", "1515"):
            continue
        for c in fin["cells"][k]["callouts"]:
            out.append(f"| {k} | {c['und']} {c['d']} | {c['side']} | {c['strike']:,.0f} | {c['entry']:.2f} | "
                       f"{c['exit']:.2f} ({c['why']}) | {c['peak']}x | {inr(c['net'])} |")
    return "\n".join(out)


def gates(fin: dict) -> str:
    out = ["| cell | final net > 0 | p < 0.05 | q <= 0.10 | 40+ tickets | without top 5 > 0 | design net > 0 | pass |",
           "|---|---|---|---|---|---|---|---|"]
    yn = {True: "yes", False: "no"}
    for k, c in fin["cells"].items():
        g = c["gates"]
        out.append(f"| {k} | " + " | ".join(yn[g[x]] for x in ("net>0", "p<0.05", "q<=0.10", "40+ tickets",
                                                               "net without top 5 > 0", "design net > 0", "pass")) + " |")
    return "\n".join(out)


def liquidity() -> str:
    lq = json.loads((K.RESULTS / "liquidity.json").read_text())
    out = [f"Design days: {lq['days']}. Base (14:00-14:59) median 1-minute range: {lq['base_median_range_pct']}% of the "
           "price.", "", "| bucket | contract-minutes | median range | no-trade minutes | multiplier |", "|---|---|---|---|---|"]
    for b in lq["buckets"]:
        if b["bucket"] >= "14:00":
            out.append(f"| {b['bucket']} | {b['obs']:,} | {b['median_range_pct']}% | {b['no_trade_pct']}% | {b['mult']} |")
    return "\n".join(out)


def main():
    des = json.loads((K.RESULTS / "design.json").read_text())
    fin = json.loads((K.RESULTS / "final.json").read_text())
    md = ["# R54 tables (generated by r54report.py)", "",
          f"Design: {des['n_days']} index-expiry-days {des['by_index']}. Final test: {fin['n_days']} {fin['by_index']}.", "",
          "## Late-minute liquidity (design days, before any P&L)", "", liquidity(), "",
          "## Design (20 Nov 2024 - 31 Mar 2026)", "", table(des), "",
          "## Final test (1 Apr - 13 Oct 2026, read once)", "", table(fin), "",
          "## Paired comparisons", "", compare(des, fin), "",
          "## Called-out days (final test)", "", callouts(fin), "",
          "## Paper gate (final test)", "", gates(fin), ""]
    (K.RESULTS / "report.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
