#!/usr/bin/env python3
"""R92 report: results/report.md from results/design.json (+ results/holdout.json once read).

    python3 research/hunt/r92_orb_time/r92report.py
"""
from __future__ import annotations

import json

import r92cfg as K

ARMS = (("orb", "ORB"), ("orb_fresh", "ORB Fresh"), ("orb_sweep", "ORB Sweep"), ("range_fade", "Range Fade"))
SHORT = {"NIFTY": "N", "BANKNIFTY": "BN", "FINNIFTY": "FN", "MIDCPNIFTY": "MC", "SENSEX": "SX"}


def rs(x) -> str:
    return f"{x:+,.0f}"


def gates(g: dict) -> str:
    return "".join("y" if g[k] else "n" for k in g if k != "pass") + (" PASS" if g["pass"] else "")


def row(d: dict, h: dict | None) -> str:
    yrs = d["per_year"]
    full = sum(yrs.get(str(y), [0, 0])[0] > 0 for y in (2022, 2023, 2024, 2025))
    up = sum(v[0] > 0 for v in d["per_und"].values())
    wm = d["worst_month"][1] if d["worst_month"] else 0
    wmu = min((v[1] for v in d["worst_month_und"].values()), default=0)
    cells = [d["label"], f"{d['trades']:,}", f"{100 * d['win_rate']:.0f}%", rs(d["net"]), rs(d["exp"]),
             f"{d['pts_mean']:+.1f}", f"{d['money_p']:.3f}", f"{d['q']:.2f}", rs(d["twin_mean"]), f"{d['twin_p']:.3f}",
             f"{up}/{len(d['per_und'])}", f"{full}/4", rs(wm), rs(wmu), gates(d["gates"])]
    if h is not None:
        cells += [f"{h['trades']:,}", f"{100 * h['win_rate']:.0f}%", rs(h["net"]), rs(h["exp"]), f"{h['twin_p']:.3f}",
                  rs(h["worst_month"][1]) if h["worst_month"] else "0", f"{rs(h['unseen'][0])} ({h['unseen'][1]})"]
    return "| " + " | ".join(cells) + " |"


HEAD = ("| cell | trades | win | net Rs | Rs / trade | index pts / trade | money p | q | twin mean Rs | twin p | "
        "indices > 0 | years > 0 (2022-25) | worst month pooled | worst month one index | design gates G1-G6 |")
HEAD_H = (" holdout trades | win | net Rs | Rs / trade | twin p | worst month | 13-19 Oct net (trades) |")


def table(cs: list, H: dict | None) -> list[str]:
    head = HEAD + (HEAD_H if H else "")
    n = head.count("|") - 1
    out = [head, "|" + "---|" * n]
    for d in cs:
        out.append(row(d, H.get(d["id"]) if H else None))
    return out


def main():
    D = json.loads((K.RESULTS / "design.json").read_text())
    Hj = json.loads((K.RESULTS / "holdout.json").read_text()) if (K.RESULTS / "holdout.json").exists() else None
    H = {c["id"]: c for c in Hj["cells"]} if Hj else None
    cs = D["cells"]
    L = ["# R92 tables (generated by r92report.py; do not edit)", "",
         f"Design 1 Aug 2021 - 31 Mar 2026, sessions per index {D['sessions']}. m = {D['m']} cells, BH at q 0.10 "
         "over all of them (money p). Rs per 1 lot after the charges in force on each date and R17's fills. "
         "'index pts' = the underlying's move in the trade's direction from entry to exit, no costs. Twin = the same "
         "trade re-entered at a random other minute of the arm's window (500 twins). Gates: G1 net > 0 and >= 100 "
         "trades, G2 q <= 0.10, G3 twin p < 0.05, G4 >= 3 of 4 years and >= 3 of 5 indices > 0, G5 > 0 without the top "
         "5, G6 worst month on each index >= -Rs 13k.", ""]
    if Hj:
        L += [f"Holdout 1 Apr - 19 Oct 2026 (read once, {Hj['written']}), sessions {Hj['sessions']}; 13-19 Oct 2026 "
              f"(seen by no earlier ORB study) {Hj['unseen_sessions']}.", ""]
    for fam, title in (("T", "Family T: entry-time slots"), ("R", "Family R: opening-range length"),
                       ("D", "Family D: day type"), ("X", "Family X: exit time"),
                       ("C", "Family C: hour x expiry day"), ("H12", "H12: R3's 12:00-12:59 lead (post hoc from R3)")):
        L += [f"## {title}", ""]
        for arm, name in ARMS:
            for mode in ("ANY", "FIRST", "APP", "ATTR"):
                sub = [c for c in cs if c["family"] == fam and c["arm"] == arm and c["mode"] == mode]
                if not sub:
                    continue
                L += [f"### {name}" + (f" ({mode})" if fam == "T" else ""), ""] + table(sub, H) + [""]
    L += ["## Per index (design net Rs, trades)", "", "| cell | " + " | ".join(K.UNDS) + " |",
          "|---|" + "---|" * len(K.UNDS)]
    for c in cs:
        L.append(f"| {c['label']} | " + " | ".join(
            f"{rs(c['per_und'][u][0])} ({c['per_und'][u][1]})" if u in c["per_und"] else "-" for u in K.UNDS) + " |")
    L += ["", "## Per year (design net Rs, trades)", "", "| cell | 2021 | 2022 | 2023 | 2024 | 2025 | 2026 |",
          "|---|---|---|---|---|---|---|"]
    for c in cs:
        L.append(f"| {c['label']} | " + " | ".join(
            f"{rs(c['per_year'][str(y)][0])} ({c['per_year'][str(y)][1]})" if str(y) in c["per_year"] else "-"
            for y in range(2021, 2027)) + " |")
    L += ["", "## Nested walk-forward (the best cell on the earlier years, traded in the next)", "",
          "| test year | pick | its net before | test-year net (trades) |", "|---|---|---|---|"]
    for w in D["nested_wf"]:
        L.append(f"| {w['year']} | {w['label']} | {rs(w['past'])} | {rs(w['test_net'])} ({w['test_trades']}) |")
    tot = sum(w["test_net"] for w in D["nested_wf"])
    L += ["", f"Chain total out of sample: Rs {rs(tot)}.", "",
          f"Design passers: {D['passers'] or 'none'}." + (f" Holdout passers: {Hj['passers'] or 'none'}." if Hj else ""),
          ""]
    (K.RESULTS / "report.md").write_text("\n".join(L))
    print("wrote", K.RESULTS / "report.md")


if __name__ == "__main__":
    main()
