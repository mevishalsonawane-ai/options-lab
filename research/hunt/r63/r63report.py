"""R63 tables: results/report.md from results/design.json and results/final.json (both periods, every cell).

    python research/hunt/r63/r63report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import r63cfg as K  # noqa: E402
import r63rules as RR  # noqa: E402


def inr(x) -> str:
    if x is None:
        return "-"
    s = "-" if x < 0 else "+"
    x = abs(float(x))
    whole = f"{x:,.0f}"
    # Indian grouping (lakhs)
    n = str(int(round(x)))
    if len(n) > 3:
        head, tail = n[:-3], n[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        whole = ",".join(parts + [tail])
    return f"{s}Rs {whole}"


def row(c: dict, d: dict | None, f: bool) -> str:
    g = c.get("gate")
    verdict = ("**PASS**" if g["passed"] else "fail: " + "; ".join(g["fails"])) if g else ""
    cells = [str(c["trades"]), str(c["changed"]), inr(c["saved_on_losers"]), inr(c["given_up_on_winners"]), inr(c["improvement"]),
             inr(c["impr_ex_top5"]), inr(c["plain_net"]), inr(c["rule_net"]), f"{inr(-c['plain_max_dd'])} / {inr(-c['rule_max_dd'])}",
             f"{inr(c['plain_worst_day'])} / {inr(c['rule_worst_day'])}", f"{c['p']:.3f}" if c.get("p") is not None else "-",
             inr(c.get("twin_mean"))]
    if f:
        cells += [f"{g['q']:.3f}", verdict]
    else:
        cells += [inr(c.get("wf_net")), " ".join(inr(x) for x in c.get("wf_quarters", []))]
    return "| " + " | ".join(cells) + " |"


def table(res: dict, final: bool) -> list:
    hdr = ["rule", "strategy", "trades", "changed", "saved on losers", "given up on winners", "net change", "net change w/o top 5",
           "plain net", "net with rule", "max DD plain / rule", "worst day plain / rule", "twin p", "twin mean"]
    hdr += ["BH q", "verdict"] if final else ["walk-forward", "WF quarters (Apr-Jun 25 .. Jan-Mar 26)"]
    out = ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    for r in RR.RULES:
        for s in K.STRATS + (K.POOLED,):
            out.append(row(res["cells"][r][s], None, final).replace("| ", f"| {r} | {K.NAMES[s]} | ", 1))
    return out


def main():
    d = json.loads((K.RESULTS / "design.json").read_text())
    f = json.loads((K.RESULTS / "final.json").read_text())
    L = ["# R63 tables (generated by r63report.py)", "",
         f"Final test {f['period'][0]} - {f['period'][1]} (read once); design {d['period'][0]} - {d['period'][1]}. "
         "Rupees after charges and fills, 1 lot. 'net change' = sum over the changed trades of (with rule - plain). "
         "Twins: 500 random early exits of the same changed trades.", "",
         f"Passed: {', '.join(f['passed']) or 'none'}. Paper rule per strategy: {f['paper_rule']}. Shadow rule (pooled design-best): {f['shadow_rule']}.",
         "", "## Final test", ""] + table(f, True) + ["", "## Design (walk-forward = the four out-of-sample quarters)", ""] + table(d, False)
    L += ["", "## Per index, final test (changed trades, net change; BANKNIFTY apart for 26 Oct)", "",
          "| rule | strategy | " + " | ".join(K.ALL_UNDS) + " |", "|---|---|" + "---|" * len(K.ALL_UNDS)]
    for r in RR.RULES:
        for s in K.STRATS:
            bi = f["cells"][r][s].get("by_index", {})
            L.append(f"| {r} | {K.NAMES[s]} | " + " | ".join(
                (f"{bi[u]['changed']} / {inr(bi[u]['improvement'])}" if u in bi else "-") for u in K.ALL_UNDS) + " |")
    h = f["cells"]["T3"]["HERO"]
    L += ["", "## The pass: T3 on the Hero ticket, final test by month", "",
          "| month | net change |", "|---|---|"] + [f"| {m} | {inr(v)} |" for m, v in sorted(h["by_month"].items())]
    (K.RESULTS / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:12]))


if __name__ == "__main__":
    main()
