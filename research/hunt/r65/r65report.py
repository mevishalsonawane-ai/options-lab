"""R65 report: results/summary.json -> results/report.md (the tables of HUNT_R65_STEP_TRAIL.md).

    python research/hunt/r65/r65study.py report
"""
from __future__ import annotations

import json

import r65cfg as R

PH = (("design", "Design 20 Nov 2024 - 31 Mar 2026"), ("wf", "Walk-forward Apr 2025 - Mar 2026 (Solo 2.0: Jul 2025 -)"),
      ("final", "Final 1 Apr - 13/14 Oct 2026 (already read by R51 / R52 / R57 / R64: weak evidence)"))
SHOW = R.VARIANTS + R.REFS


def rs(x) -> str:
    if x is None:
        return "-"
    x = round(x)
    s = f"{abs(x):,}"
    return f"-Rs {s}" if x < 0 else f"Rs {s}"


def pct(x) -> str:
    return "-" if x is None else f"{100 * x:.0f}%"


def table(rows: dict) -> list:
    out = ["| variant | trades (days) | win | net | per trade | avg win | avg loss | biggest loss | worst day | "
           "max DD | green days | stops / locks / targets |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for v, s in rows.items():
        if not s or not s.get("trades"):
            out.append(f"| {R.VLABEL[v]} | 0 | | | | | | | | | | |")
            continue
        out.append(f"| {R.VLABEL[v]} | {s['trades']:,} ({s['days']}) | {pct(s['win'])} | **{rs(s['net'])}** | "
                   f"{rs(s['per_trade'])} | {rs(s['avg_win'])} | {rs(s['avg_loss'])} | {rs(s['biggest_loss'])} | "
                   f"{rs(s['worst_day'])} | {rs(s['max_dd'])} | {pct(s['green_days'])} | "
                   f"{s['stops']} / {s['locks']} / {s['targets']} |")
    return out


def trail_table(rows: dict, ph: str) -> list:
    out = ["| variant | trades the lock closed (matched) | Rs given up (n) | Rs saved on give-backs (n) | net effect | "
           "cut a plain +30% exit | option went on to +30% after the exit |", "|---|---|---|---|---|---|---|"]
    for v, r in rows.items():
        t = r["trail"][ph]
        out.append(f"| {R.VLABEL[v]} | {t['locked']} ({t['matched']}) | {rs(t['given_up'])} ({t['n_worse']}) | "
                   f"{rs(t['saved'])} ({t['n_better']}) | **{rs(t['net_effect'])}** | {t['cut_plain30']} | "
                   f"{t['went_on30']} |")
    return out


def gate_table(arm: dict) -> list:
    out = ["| variant | entry-twin p | BH q (30) | exit-twin p (k early exits) | BH q (24) | vs B0 final (boot p) | "
           "vs A4 final (boot p) | walk-forward quarters | verdict |", "|---|---|---|---|---|---|---|---|---|"]
    for v in R.VARIANTS:
        r = arm[v]
        pb = r.get("paired", {})

        def pv(b):
            x = pb.get(f"vs_{b}")
            return f"{rs(x['final']['diff'])} ({x['final']['p']})" if x else "-"
        ex = f"{r['exit_p']} ({r['exit_k']})" if r.get("exit_p") is not None else "-"
        qs = ", ".join(rs(q["net"]) for q in r["wf_quarters"])
        out.append(f"| {R.VLABEL[v]} | {r['p']} | {r['q']} | {ex} | {r.get('exit_q', '-')} | {pv('B0')} | {pv('A4')} | "
                   f"{qs} | {r['verdict']} |")
    return out


def example(e) -> str:
    if not e:
        return "none"
    return (f"{e['und']} {e['day']} {e['side']}: trail {rs(e['trail_net'])} ({100 * e['trail_ret']:+.0f}%) vs plain "
            f"{rs(e['plain_net'])} ({100 * e['plain_ret']:+.0f}%, {e['plain_why']})")


def main():
    s = json.loads((R.RESULTS / "summary.json").read_text())
    L = ["# R65 tables (generated by r65report.py from results/summary.json)", ""]
    for arm in R.ARMS:
        a = s["arms"][arm]
        d = a["decision"]
        L += [f"## {arm}", "", f"Decision (PREREG section 6): recommended **{d['recommended'] or 'none'}**; keep "
              f"{d['keep']}. Risk trade-offs vs A4 (lower final max DD or worst day at a lower net): "
              f"{', '.join(d['tradeoffs']) or 'none'}.", ""]
        for ph, title in PH:
            L += [f"### {arm} - {title}", ""] + table({v: a[v][ph] for v in SHOW}) + [""]
        for ph in ("design", "final"):
            L += [f"### {arm} - what the lock did, {ph} (against the plain counterpart: B0, or N0 for 'n' variants "
                  "and A4)", ""] + trail_table({v: a[v] for v in R.TRAILS + ("A4",)}, ph) + [""]
        L += [f"### {arm} - examples (final)", ""]
        for v in ("S5", "S5n", "S10", "T5"):
            t = a[v]["trail"]["final"]
            L += [f"- {v}: biggest give-up {example(t['worst_example'])}; biggest save {example(t['best_example'])}"]
        L += ["", f"### {arm} - gates", ""] + gate_table(a) + [""]
    L += ["## The three together (one lot each, all arms' trades added)", ""]
    for ph, title in PH:
        L += [f"### Together - {title}", ""] + table({v: s["together"][v][ph] for v in SHOW}) + [""]
    L += ["### Together - what the lock did, final", ""] + \
        trail_table({v: s["together"][v] for v in R.TRAILS + ("A4",)}, "final") + [""]
    pb = ["| variant | vs B0 design (boot p) | vs B0 final | vs A4 design | vs A4 final |", "|---|---|---|---|---|"]
    for v in R.TRAILS:
        x = s["together"][v]["paired"]
        pb.append(f"| {R.VLABEL[v]} | " + " | ".join(f"{rs(x[b][ph]['diff'])} ({x[b][ph]['p']})" for b in ("vs_B0", "vs_A4")
                                                   for ph in ("design", "final")) + " |")
    L += ["### Together - paired day bootstrap (information only)", ""] + pb + [""]
    (R.RESULTS / "report.md").write_text("\n".join(L))
    return "\n".join(L)


if __name__ == "__main__":
    main()
