"""Level 5: knowledge cards for Jarvis and Boss (PREREG section 9; not a test).

Plain-English cards, each number with its sample size, built from the committed results (design_metrics.json,
l4_design.json, holdout_metrics.json) and the cube. Written after the holdout step, so the descriptive cards of the
five futures-only commodities (whose minutes are all from Aug-Oct 2026) do not read the holdout early.

    python -m research.brain.mcx.study cards     -> results/cards.json, results/CARDS.md
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from . import config, data as D

RESULTS = Path(__file__).resolve().parent / "results"
NAMES = {"GOLD": "gold", "GOLDM": "gold mini", "SILVER": "silver", "SILVERM": "silver mini", "CRUDEOIL": "crude oil",
         "CRUDEOILM": "crude mini", "NATURALGAS": "natural gas", "NATGASMINI": "natural gas mini", "COPPER": "copper",
         "ZINC": "zinc", "ALUMINIUM": "aluminium"}


def _r(x, k=2):
    return None if x is None or not np.isfinite(x) else round(float(x), k)


def hourly_range(S, design_only: bool) -> list[dict]:
    m = S.cube
    keep = (m.ts.dt.date <= config.DESIGN_END) if design_only else np.ones(len(m), bool)
    from . import labels
    y = labels.compute(m[keep])
    d = pd.DataFrame({"ts": y.ts, "r": y.y_range_60m})
    d = d[d.ts.dt.minute == 0].dropna()
    g = d.groupby(d.ts.dt.hour).r
    return [dict(hour=f"{h:02d}:00", median_pct=_r(v.median(), 3), sessions=int(len(v))) for h, v in g]


def build(root=None) -> dict:
    dm = json.loads((RESULTS / "design_metrics.json").read_text())
    l4 = json.loads((RESULTS / "l4_design.json").read_text())
    hp = RESULTS / "holdout_metrics.json"
    hm = json.loads(hp.read_text()) if hp.exists() else None
    cards = []
    for s in config.SPECS:
        S = D.load_symbol(root, s, with_holdout_labels=True)
        modelled = s in dm["specialists"]
        card = dict(symbol=s, name=NAMES[s], modelled=modelled,
                    hourly_range=hourly_range(S, design_only=modelled))
        if modelled:
            sp = dm["specialists"][s]
            v = dm["verdicts"]
            size, C, comm = sp["size"], sp["C"], sp["committee"]
            card["size"] = dict(verdict=v[f"L1A:{s}"], skill_pct=_r(100 * size["skill"], 1), rows=size["rows"],
                                sessions=size["sessions"], best_plain_guess=size["best_baseline"],
                                band80_coverage=_r(size["committee"]["band80_coverage"], 3))
            card["direction"] = dict(verdict=v[f"L1C:{s}"], auc=_r(C.get("auc"), 3), rows=C.get("rows"),
                                     committee_hit_rate=_r(comm.get("hit_rate"), 3), committee_acted=comm.get("acted"))
            if hm and s in hm["specialists"]:
                h = hm["specialists"][s]
                card["holdout"] = dict(size_skill_pct=_r(100 * h["size"]["skill"], 1), size_rows=h["size"]["rows"],
                                       direction_auc=_r(h["C"].get("auc"), 3), direction_rows=h["C"].get("rows"),
                                       committee_hit_rate=_r(h["committee"].get("hit_rate"), 3),
                                       committee_acted=h["committee"].get("acted"))
            us = dm["session"][s]
            card["us_open"] = dict(size_skill_pct=_r(100 * us["size"]["skill"], 1), days=us["size"]["n_days"],
                                   continue_rate=_r(us["continue"]["rate"], 3), continue_auc=_r(us["continue"]["auc"], 3),
                                   verdict_size=v[f"L1Di:{s}"], verdict_continue=v[f"L1Dii:{s}"])
            card["events"] = {k.split(":")[1]: dict(times_bigger=_r(e["multiplier"]), n=e["n_events"],
                                                    follow_rate=_r(e["follow_rate"], 3), n_follow=e["n_follow"],
                                                    verdict_bigger=v[f"L1Ei:{k}"], verdict_follow=v[f"L1Eii:{k}"])
                              for k, e in dm["events"].items() if k.startswith(s + ":")}
        if s in config.TRADE:
            card["rules"] = {k.split(":")[0]: g["verdict"] for k, g in l4["gates"].items() if k.split(":")[1] == s}
        cards.append(card)
    out = dict(built_from=["design_metrics.json", "l4_design.json"] + (["holdout_metrics.json"] if hm else []),
               cards=cards)
    (RESULTS / "cards.json").write_text(json.dumps(out, indent=1, default=str) + "\n")
    (RESULTS / "CARDS.md").write_text(render(out))
    return out


def render(out: dict) -> str:
    L = ["# MCX brain: knowledge cards (MB1)", "",
         "*Generated by `python -m research.brain.mcx.study cards`. Plain English for Jarvis and Boss; every number has "
         "its sample size. Nothing here trades.*", ""]
    for c in out["cards"]:
        L.append(f"## {c['symbol']} ({c['name']})")
        hr = c["hourly_range"]
        if hr:
            big = max(hr, key=lambda x: x["median_pct"] or 0)
            small = min(hr, key=lambda x: x["median_pct"] or 9)
            L.append(f"- Usual 60-minute move (median close range): busiest from {big['hour']} "
                     f"({big['median_pct']}%, {big['sessions']} sessions), quietest from {small['hour']} "
                     f"({small['median_pct']}%, {small['sessions']} sessions)"
                     + ("" if c["modelled"] else " (Aug-Oct 2026 only; not modelled: fewer than 60 design sessions)")
                     + ".")
        if c.get("size"):
            z = c["size"]
            L.append(f"- Size of the next hour: **{z['verdict']}**; the brain's error is {z['skill_pct']}% smaller than "
                     f"the best plain guess ({z['best_plain_guess']}) on {z['rows']:,} forecasts / {z['sessions']} "
                     f"sessions; its 80% band held {z['band80_coverage']} of the time.")
            d = c["direction"]
            L.append(f"- Direction of the next hour: **{d['verdict']}** (AUC {d['auc']} on {d['rows']:,} rows; 0.5 = coin). "
                     f"The committee acted on {d['committee_acted']} rows and was right {d['committee_hit_rate']}.")
            if c.get("holdout"):
                h = c["holdout"]
                L.append(f"- Locked holdout (Jul-Oct 2026, read once): size skill {h['size_skill_pct']}% "
                         f"({h['size_rows']:,} rows); direction AUC {h['direction_auc']} ({h['direction_rows']:,} rows); "
                         f"committee right {h['committee_hit_rate']} on {h['committee_acted']} acted rows.")
            u = c["us_open"]
            L.append(f"- US open (09:30 New York): the next 150 minutes continued the day's move "
                     f"{u['continue_rate']} of {u['days']} days (size {u['verdict_size']}, continuation {u['verdict_continue']}).")
            for k, e in c["events"].items():
                L.append(f"- {k}: the hour after the release was {e['times_bigger']}x the usual hour "
                         f"(median, {e['n']} releases; {e['verdict_bigger']}); it followed the hour before "
                         f"{e['follow_rate']} of {e['n_follow']} times ({e['verdict_follow']}).")
        if c.get("rules"):
            L.append("- Brain rules (L4): " + ", ".join(f"{k} {v}" for k, v in c["rules"].items()) + ".")
        L.append("")
    return "\n".join(L)
